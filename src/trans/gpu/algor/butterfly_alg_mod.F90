SUBROUTINE FREE_HYBRID(YHYBRID)
TYPE(HYBRID_MATRIX),INTENT(INOUT) :: YHYBRID

CALL RELEASE_HYBRID_BLOCKS(YHYBRID)
YHYBRID%SELECTED=.FALSE.
YHYBRID%CONSTRUCTED=.FALSE.
YHYBRID%DENSE_BLOCKS=0
YHYBRID%LOW_RANK_BLOCKS=0
YHYBRID%BUTTERFLY_BLOCKS=0
YHYBRID%DENSE_COST=0
YHYBRID%HYBRID_COST=0
END SUBROUTINE FREE_HYBRID
!====================================================================
SUBROUTINE RELEASE_HYBRID_BLOCKS(YHYBRID)
TYPE(HYBRID_MATRIX),INTENT(INOUT) :: YHYBRID
INTEGER(KIND=JPIM) :: JB

IF (ALLOCATED(YHYBRID%BLOCKS)) THEN
  DO JB=1,SIZE(YHYBRID%BLOCKS)
    CALL FREE_BUTTERFLY(YHYBRID%BLOCKS(JB)%BUT)
    IF (ALLOCATED(YHYBRID%BLOCKS(JB)%DENSE)) &
      DEALLOCATE(YHYBRID%BLOCKS(JB)%DENSE)
  ENDDO
  DEALLOCATE(YHYBRID%BLOCKS)
ENDIF
YHYBRID%BLOCK_COUNT=0
END SUBROUTINE RELEASE_HYBRID_BLOCKS
!====================================================================
SUBROUTINE FREE_BUTTERFLY(YD_STRUCT)
TYPE(BUTTERFLY_STRUCT),INTENT(INOUT) :: YD_STRUCT
INTEGER(KIND=JPIM) :: JL,JJ,JK

IF (ASSOCIATED(YD_STRUCT%SLEV)) THEN
  DO JL=LBOUND(YD_STRUCT%SLEV,1),UBOUND(YD_STRUCT%SLEV,1)
    IF (ASSOCIATED(YD_STRUCT%SLEV(JL)%NODE)) THEN
      DO JK=1,YD_STRUCT%SLEV(JL)%IK
        DO JJ=1,YD_STRUCT%SLEV(JL)%IJ
          IF (ASSOCIATED(YD_STRUCT%SLEV(JL)%NODE(JJ,JK)%ICLIST)) &
            DEALLOCATE(YD_STRUCT%SLEV(JL)%NODE(JJ,JK)%ICLIST)
          IF (ASSOCIATED(YD_STRUCT%SLEV(JL)%NODE(JJ,JK)%PNONIM)) &
            DEALLOCATE(YD_STRUCT%SLEV(JL)%NODE(JJ,JK)%PNONIM)
          IF (ASSOCIATED(YD_STRUCT%SLEV(JL)%NODE(JJ,JK)%B)) &
            DEALLOCATE(YD_STRUCT%SLEV(JL)%NODE(JJ,JK)%B)
          IF (ASSOCIATED(YD_STRUCT%SLEV(JL)%NODE(JJ,JK)%DB)) &
            DEALLOCATE(YD_STRUCT%SLEV(JL)%NODE(JJ,JK)%DB)
        ENDDO
      ENDDO
      DEALLOCATE(YD_STRUCT%SLEV(JL)%NODE)
    ENDIF
  ENDDO
  DEALLOCATE(YD_STRUCT%SLEV)
ENDIF
YD_STRUCT%M_ORDER=0
YD_STRUCT%N_ORDER=0
YD_STRUCT%N_CMAX=0
YD_STRUCT%N_LEVELS=0
YD_STRUCT%IBETALEN_MAX=0
END SUBROUTINE FREE_BUTTERFLY
