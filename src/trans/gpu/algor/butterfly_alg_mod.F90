INTEGER(KIND=JPIB) FUNCTION BUTTERFLY_COST(YD_STRUCT)
TYPE(BUTTERFLY_STRUCT),INTENT(IN) :: YD_STRUCT
INTEGER(KIND=JPIM) :: JL,JJ,JK,IRANKL,IRANKR

BUTTERFLY_COST=0
IF (.NOT.ASSOCIATED(YD_STRUCT%SLEV)) RETURN
DO JK=1,YD_STRUCT%SLEV(0)%IK
  BUTTERFLY_COST=BUTTERFLY_COST+&
    & INT(YD_STRUCT%SLEV(0)%NODE(1,JK)%ICOLS,JPIB)*&
    & INT(YD_STRUCT%SLEV(0)%NODE(1,JK)%IRANK,JPIB)
ENDDO
DO JL=1,YD_STRUCT%N_LEVELS
  DO JK=1,YD_STRUCT%SLEV(JL)%IK
    DO JJ=1,YD_STRUCT%SLEV(JL)%IJ
      IRANKL=YD_STRUCT%SLEV(JL-1)%NODE((JJ+1)/2,2*JK-1)%IRANK
      IRANKR=0
      IF (2*JK <= YD_STRUCT%SLEV(JL-1)%IK) &
        IRANKR=YD_STRUCT%SLEV(JL-1)%NODE((JJ+1)/2,2*JK)%IRANK
      BUTTERFLY_COST=BUTTERFLY_COST+INT(IRANKL+IRANKR,JPIB)*&
        & INT(YD_STRUCT%SLEV(JL)%NODE(JJ,JK)%IRANK,JPIB)
    ENDDO
  ENDDO
ENDDO
JL=YD_STRUCT%N_LEVELS
DO JK=1,YD_STRUCT%SLEV(JL)%IK
  DO JJ=1,YD_STRUCT%SLEV(JL)%IJ
    BUTTERFLY_COST=BUTTERFLY_COST+&
      & INT(YD_STRUCT%SLEV(JL)%NODE(JJ,JK)%IROWS,JPIB)*&
      & INT(YD_STRUCT%SLEV(JL)%NODE(JJ,JK)%IRANK,JPIB)
  ENDDO
ENDDO
END FUNCTION BUTTERFLY_COST
