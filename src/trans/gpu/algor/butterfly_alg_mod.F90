INTEGER(KIND=JPIM),INTENT(IN) :: KKIND

SELECT CASE(KKIND)
CASE(HYBRID_LOW_RANK)
  HYBRID_KIND_NAME='low_rank'
CASE(HYBRID_BUTTERFLY)
  HYBRID_KIND_NAME='butterfly'
CASE DEFAULT
  HYBRID_KIND_NAME='dense'
END SELECT
END FUNCTION HYBRID_KIND_NAME

SUBROUTINE COLLECT_RANKS(BUT,KBLOCK,KKIND,KCOUNT,KSUM,KMIN,KMAX)
TYPE(BUTTERFLY_STRUCT),INTENT(IN) :: BUT
INTEGER(KIND=JPIM),INTENT(IN) :: KBLOCK,KKIND
INTEGER(KIND=JPIM),INTENT(OUT) :: KCOUNT,KMIN,KMAX
INTEGER(KIND=JPIB),INTENT(OUT) :: KSUM
INTEGER(KIND=JPIM) :: JL,JJ,JK,ILEVEL_COUNT,ILEVEL_MIN,ILEVEL_MAX
INTEGER(KIND=JPIB) :: ILEVEL_SUM
REAL(KIND=JPRD) :: ZLEVEL_MEAN

KCOUNT=0
KSUM=0
KMIN=HUGE(KMIN)
KMAX=0
IF (.NOT.ASSOCIATED(BUT%SLEV)) THEN
  KMIN=0
  RETURN
ENDIF

DO JL=0,BUT%N_LEVELS
  ILEVEL_COUNT=0
  ILEVEL_SUM=0
  ILEVEL_MIN=HUGE(ILEVEL_MIN)
  ILEVEL_MAX=0
  DO JK=1,BUT%SLEV(JL)%IK
    DO JJ=1,BUT%SLEV(JL)%IJ
      ILEVEL_COUNT=ILEVEL_COUNT+1
      ILEVEL_SUM=ILEVEL_SUM+INT(BUT%SLEV(JL)%NODE(JJ,JK)%IRANK,JPIB)
      ILEVEL_MIN=MIN(ILEVEL_MIN,BUT%SLEV(JL)%NODE(JJ,JK)%IRANK)
      ILEVEL_MAX=MAX(ILEVEL_MAX,BUT%SLEV(JL)%NODE(JJ,JK)%IRANK)
    ENDDO
  ENDDO
  KCOUNT=KCOUNT+ILEVEL_COUNT
  KSUM=KSUM+ILEVEL_SUM
  KMIN=MIN(KMIN,ILEVEL_MIN)
  KMAX=MAX(KMAX,ILEVEL_MAX)
  IF (LDETAILS) THEN
    ZLEVEL_MEAN=REAL(ILEVEL_SUM,JPRD)/REAL(ILEVEL_COUNT,JPRD)
    WRITE(KUNIT,*) 'GPU_HYBRID_LEVEL path=',TRIM(KPATH),' m=',KMORDER,&
      & ' block=',KBLOCK,' original=',TRIM(HYBRID_KIND_NAME(KKIND)),&
      & ' level=',JL,' nodes=',ILEVEL_COUNT,' rank_min=',ILEVEL_MIN,&
      & ' rank_max=',ILEVEL_MAX,' rank_mean=',ZLEVEL_MEAN
  ENDIF
ENDDO
END SUBROUTINE COLLECT_RANKS

RECURSIVE SUBROUTINE BUILD_REFINED_BLOCK(KR1,KR2,KC1,KC2,KCOUNT)
INTEGER(KIND=JPIM),INTENT(IN) :: KR1,KR2,KC1,KC2
INTEGER(KIND=JPIM),INTENT(INOUT) :: KCOUNT
INTEGER(KIND=JPIM) :: IRMID,ICMID,INR,INC,IORIGINAL_KIND,IORIGINAL_LEVELS
INTEGER(KIND=JPIM) :: IRANK_COUNT,IRANK_MIN,IRANK_MAX
INTEGER(KIND=JPIB) :: ICOST,IRANK_SUM
REAL(KIND=JPRD) :: ZBLOCK_COST_RATIO,ZBLOCK_RANK_MEAN
TYPE(HYBRID_BLOCK) :: YBLOCK

INR=KR2-KR1+1
INC=KC2-KC1+1
IF (INR > 2*INC .AND. INR > 1) THEN
  IRMID=(KR1+KR2)/2
  CALL BUILD_REFINED_BLOCK(KR1,IRMID,KC1,KC2,KCOUNT)
  CALL BUILD_REFINED_BLOCK(IRMID+1,KR2,KC1,KC2,KCOUNT)
  RETURN
ELSEIF (INC > 2*INR .AND. INC > 1) THEN
  ICMID=(KC1+KC2)/2
  CALL BUILD_REFINED_BLOCK(KR1,KR2,KC1,ICMID,KCOUNT)
  CALL BUILD_REFINED_BLOCK(KR1,KR2,ICMID+1,KC2,KCOUNT)
  RETURN
ENDIF

IORIGINAL_KIND=CLASSIFY_BLOCK(KR1,KR2,KC1,KC2)
IF (IORIGINAL_KIND == HYBRID_DENSE .AND. INR > KLEAF .AND. INC > KLEAF) THEN
  CALL SPLIT_REFINED_BLOCK(KR1,KR2,KC1,KC2,KCOUNT)
  RETURN
ENDIF

ITRIAL_COUNT=ITRIAL_COUNT+1
YBLOCK%KIND=IORIGINAL_KIND
YBLOCK%FIRST_ROW=KR1
YBLOCK%FIRST_COL=KC1
YBLOCK%NROWS=INR
YBLOCK%NCOLS=INC
YBLOCK%DENSE_COST=INT(INR,JPIB)*INT(INC,JPIB)
IORIGINAL_LEVELS=0
ICOST=YBLOCK%DENSE_COST
IRANK_COUNT=0
IRANK_SUM=0
IRANK_MIN=0
IRANK_MAX=0

SELECT CASE(YBLOCK%KIND)
CASE(HYBRID_LOW_RANK)
  CALL CONSTRUCT_BUTTERFLY(ZEPS,INC,INR,INC,&
    & PMAT(KR1:KR2,KC1:KC2),YBLOCK%BUT)
  ICOST=BUTTERFLY_COST(YBLOCK%BUT)
  IORIGINAL_LEVELS=YBLOCK%BUT%N_LEVELS
  CALL COLLECT_RANKS(YBLOCK%BUT,ITRIAL_COUNT,IORIGINAL_KIND,&
    & IRANK_COUNT,IRANK_SUM,IRANK_MIN,IRANK_MAX)
CASE(HYBRID_BUTTERFLY)
  CALL CONSTRUCT_BUTTERFLY(ZEPS,MIN(KCMAX,INC),INR,INC,&
    & PMAT(KR1:KR2,KC1:KC2),YBLOCK%BUT)
  ICOST=BUTTERFLY_COST(YBLOCK%BUT)
  IORIGINAL_LEVELS=YBLOCK%BUT%N_LEVELS
  CALL COLLECT_RANKS(YBLOCK%BUT,ITRIAL_COUNT,IORIGINAL_KIND,&
    & IRANK_COUNT,IRANK_SUM,IRANK_MIN,IRANK_MAX)
END SELECT

IF (YBLOCK%KIND /= HYBRID_DENSE .AND. ICOST >= YBLOCK%DENSE_COST .AND. &
  & MIN(INR,INC) > KLEAF) THEN
  IF (LDETAILS) THEN
    WRITE(KUNIT,*) 'GPU_HYBRID_REFINE path=',TRIM(KPATH),' m=',KMORDER,&
      & ' trial=',ITRIAL_COUNT,' original=',TRIM(HYBRID_KIND_NAME(IORIGINAL_KIND)),&
      & ' first_row=',KR1,' rows=',INR,' first_col=',KC1,' cols=',INC,&
      & ' dense_cost=',YBLOCK%DENSE_COST,' trial_cost=',ICOST
  ENDIF
  CALL FREE_BUTTERFLY(YBLOCK%BUT)
  CALL SPLIT_REFINED_BLOCK(KR1,KR2,KC1,KC2,KCOUNT)
  RETURN
ENDIF

IF (YBLOCK%KIND /= HYBRID_DENSE .AND. ICOST >= YBLOCK%DENSE_COST) THEN
  CALL FREE_BUTTERFLY(YBLOCK%BUT)
  YBLOCK%KIND=HYBRID_DENSE
ELSEIF (YBLOCK%KIND /= HYBRID_DENSE) THEN
  YBLOCK%FACTOR_COST=ICOST
ENDIF

IF (YBLOCK%KIND == HYBRID_DENSE) THEN
  ALLOCATE(YBLOCK%DENSE(INR,INC))
  YBLOCK%DENSE=REAL(PMAT(KR1:KR2,KC1:KC2),JPRBT)
  YBLOCK%FACTOR_COST=YBLOCK%DENSE_COST
  YHYBRID%DENSE_BLOCKS=YHYBRID%DENSE_BLOCKS+1
ELSEIF (YBLOCK%KIND == HYBRID_LOW_RANK) THEN
  YHYBRID%LOW_RANK_BLOCKS=YHYBRID%LOW_RANK_BLOCKS+1
ELSE
  YHYBRID%BUTTERFLY_BLOCKS=YHYBRID%BUTTERFLY_BLOCKS+1
ENDIF
YHYBRID%HYBRID_COST=YHYBRID%HYBRID_COST+YBLOCK%FACTOR_COST
IF (IRANK_COUNT > 0) THEN
  ICAND_RANK_COUNT=ICAND_RANK_COUNT+IRANK_COUNT
  ICAND_RANK_SUM=ICAND_RANK_SUM+IRANK_SUM
  ICAND_RANK_MIN=MIN(ICAND_RANK_MIN,IRANK_MIN)
  ICAND_RANK_MAX=MAX(ICAND_RANK_MAX,IRANK_MAX)
ENDIF

KCOUNT=KCOUNT+1
CALL ENSURE_BLOCK_CAPACITY(KCOUNT,KCOUNT-1)
IF (LDETAILS) THEN
  ZBLOCK_COST_RATIO=REAL(ICOST,JPRD)/REAL(YBLOCK%DENSE_COST,JPRD)
  ZBLOCK_RANK_MEAN=0.0_JPRD
  IF (IRANK_COUNT > 0) &
    ZBLOCK_RANK_MEAN=REAL(IRANK_SUM,JPRD)/REAL(IRANK_COUNT,JPRD)
  WRITE(KUNIT,*) 'GPU_HYBRID_BLOCK path=',TRIM(KPATH),' m=',KMORDER,&
    & ' block=',KCOUNT,' trial=',ITRIAL_COUNT,&
    & ' original=',TRIM(HYBRID_KIND_NAME(IORIGINAL_KIND)),&
    & ' final=',TRIM(HYBRID_KIND_NAME(YBLOCK%KIND)),&
    & ' first_row=',KR1,' rows=',INR,' first_col=',KC1,' cols=',INC,&
    & ' levels=',IORIGINAL_LEVELS,' dense_cost=',YBLOCK%DENSE_COST,&
    & ' trial_cost=',ICOST,' factor_cost=',YBLOCK%FACTOR_COST,&
    & ' cost_ratio=',ZBLOCK_COST_RATIO,' rank_nodes=',IRANK_COUNT,&
    & ' rank_min=',IRANK_MIN,' rank_max=',IRANK_MAX,&
    & ' rank_mean=',ZBLOCK_RANK_MEAN
ENDIF
CALL MOVE_HYBRID_BLOCK(YBLOCK,YHYBRID%BLOCKS(KCOUNT))
END SUBROUTINE BUILD_REFINED_BLOCK

RECURSIVE SUBROUTINE SPLIT_REFINED_BLOCK(KR1,KR2,KC1,KC2,KCOUNT)
INTEGER(KIND=JPIM),INTENT(IN) :: KR1,KR2,KC1,KC2
INTEGER(KIND=JPIM),INTENT(INOUT) :: KCOUNT
INTEGER(KIND=JPIM) :: IRMID,ICMID

IRMID=(KR1+KR2)/2
ICMID=(KC1+KC2)/2
CALL BUILD_REFINED_BLOCK(KR1,IRMID,KC1,ICMID,KCOUNT)
CALL BUILD_REFINED_BLOCK(KR1,IRMID,ICMID+1,KC2,KCOUNT)
CALL BUILD_REFINED_BLOCK(IRMID+1,KR2,KC1,ICMID,KCOUNT)
CALL BUILD_REFINED_BLOCK(IRMID+1,KR2,ICMID+1,KC2,KCOUNT)
END SUBROUTINE SPLIT_REFINED_BLOCK

SUBROUTINE ENSURE_BLOCK_CAPACITY(KNEEDED,KCOUNT)
INTEGER(KIND=JPIM),INTENT(IN) :: KNEEDED,KCOUNT
INTEGER(KIND=JPIM) :: INEW

IF (KNEEDED <= SIZE(YHYBRID%BLOCKS)) RETURN
INEW=MAX(KNEEDED,2*SIZE(YHYBRID%BLOCKS))
CALL RESIZE_BLOCK_STORAGE(INEW,KCOUNT)
END SUBROUTINE ENSURE_BLOCK_CAPACITY

SUBROUTINE RESIZE_BLOCK_STORAGE(KSIZE,KCOUNT)
INTEGER(KIND=JPIM),INTENT(IN) :: KSIZE,KCOUNT
INTEGER(KIND=JPIM) :: JB
TYPE(HYBRID_BLOCK),ALLOCATABLE :: YBLOCKS(:)

IF (KSIZE == SIZE(YHYBRID%BLOCKS)) RETURN
ALLOCATE(YBLOCKS(KSIZE))
DO JB=1,KCOUNT
  CALL MOVE_HYBRID_BLOCK(YHYBRID%BLOCKS(JB),YBLOCKS(JB))
ENDDO
DEALLOCATE(YHYBRID%BLOCKS)
CALL MOVE_ALLOC(YBLOCKS,YHYBRID%BLOCKS)
END SUBROUTINE RESIZE_BLOCK_STORAGE

SUBROUTINE MOVE_HYBRID_BLOCK(YFROM,YTO)
TYPE(HYBRID_BLOCK),INTENT(INOUT) :: YFROM,YTO

YTO%KIND=YFROM%KIND
YTO%FIRST_ROW=YFROM%FIRST_ROW
YTO%FIRST_COL=YFROM%FIRST_COL
YTO%NROWS=YFROM%NROWS
YTO%NCOLS=YFROM%NCOLS
YTO%DENSE_COST=YFROM%DENSE_COST
YTO%FACTOR_COST=YFROM%FACTOR_COST
YTO%WORK_BASE=YFROM%WORK_BASE
YTO%BUT=YFROM%BUT
NULLIFY(YFROM%BUT%SLEV)
IF (ALLOCATED(YFROM%DENSE)) CALL MOVE_ALLOC(YFROM%DENSE,YTO%DENSE)
END SUBROUTINE MOVE_HYBRID_BLOCK

RECURSIVE SUBROUTINE VISIT_BLOCK(KR1,KR2,KC1,KC2,LFILL,KCOUNT)
INTEGER(KIND=JPIM),INTENT(IN) :: KR1,KR2,KC1,KC2
LOGICAL,INTENT(IN) :: LFILL
INTEGER(KIND=JPIM),INTENT(INOUT) :: KCOUNT
INTEGER(KIND=JPIM) :: IRMID,ICMID,INR,INC,IKIND

INR=KR2-KR1+1
INC=KC2-KC1+1
IF (INR > 2*INC .AND. INR > 1) THEN
  IRMID=(KR1+KR2)/2
  CALL VISIT_BLOCK(KR1,IRMID,KC1,KC2,LFILL,KCOUNT)
  CALL VISIT_BLOCK(IRMID+1,KR2,KC1,KC2,LFILL,KCOUNT)
  RETURN
ELSEIF (INC > 2*INR .AND. INC > 1) THEN
  ICMID=(KC1+KC2)/2
  CALL VISIT_BLOCK(KR1,KR2,KC1,ICMID,LFILL,KCOUNT)
  CALL VISIT_BLOCK(KR1,KR2,ICMID+1,KC2,LFILL,KCOUNT)
  RETURN
ENDIF

IKIND=CLASSIFY_BLOCK(KR1,KR2,KC1,KC2)
IF (IKIND == HYBRID_DENSE .AND. INR > KLEAF .AND. INC > KLEAF) THEN
  IRMID=(KR1+KR2)/2
  ICMID=(KC1+KC2)/2
  CALL VISIT_BLOCK(KR1,IRMID,KC1,ICMID,LFILL,KCOUNT)
  CALL VISIT_BLOCK(KR1,IRMID,ICMID+1,KC2,LFILL,KCOUNT)
  CALL VISIT_BLOCK(IRMID+1,KR2,KC1,ICMID,LFILL,KCOUNT)
  CALL VISIT_BLOCK(IRMID+1,KR2,ICMID+1,KC2,LFILL,KCOUNT)
  RETURN
ENDIF

KCOUNT=KCOUNT+1
IF (LFILL) THEN
  YHYBRID%BLOCKS(KCOUNT)%KIND=IKIND
  YHYBRID%BLOCKS(KCOUNT)%FIRST_ROW=KR1
  YHYBRID%BLOCKS(KCOUNT)%FIRST_COL=KC1
  YHYBRID%BLOCKS(KCOUNT)%NROWS=INR
  YHYBRID%BLOCKS(KCOUNT)%NCOLS=INC
ENDIF
END SUBROUTINE VISIT_BLOCK

INTEGER(KIND=JPIM) FUNCTION CLASSIFY_BLOCK(KR1,KR2,KC1,KC2)
INTEGER(KIND=JPIM),INTENT(IN) :: KR1,KR2,KC1,KC2
REAL(KIND=JPRD) :: ZMIN,ZMAX

ZMIN=PTHETA(KR1)-TURNING_ANGLE(KC2)
ZMAX=PTHETA(KR2)-TURNING_ANGLE(KC1)
IF (ZMIN > 0.0_JPRD) THEN
  CLASSIFY_BLOCK=HYBRID_BUTTERFLY
ELSEIF (ZMAX < 0.0_JPRD) THEN
  CLASSIFY_BLOCK=HYBRID_LOW_RANK
ELSE
  CLASSIFY_BLOCK=HYBRID_DENSE
ENDIF
END FUNCTION CLASSIFY_BLOCK

REAL(KIND=JPRD) FUNCTION TURNING_ANGLE(KCOL)
INTEGER(KIND=JPIM),INTENT(IN) :: KCOL
INTEGER(KIND=JPIM) :: IN
REAL(KIND=JPRD) :: ZRATIO

IN=KFIRST_DEGREE-2*(KCOL-1)
ZRATIO=SQRT(MAX(REAL(KMORDER*KMORDER,JPRD)-0.25_JPRD,0.0_JPRD))/&
  & (REAL(IN,JPRD)+0.5_JPRD)
TURNING_ANGLE=ASIN(MIN(MAX(ZRATIO,0.0_JPRD),1.0_JPRD))
END FUNCTION TURNING_ANGLE

END SUBROUTINE CONSTRUCT_HYBRID
