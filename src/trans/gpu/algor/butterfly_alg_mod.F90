SUBROUTINE CONSTRUCT_HYBRID(PEPS,KCMAX,KLEAF,KMORDER,KFIRST_DEGREE,&
 & KPATH,KUNIT,PTHETA,PMAT,YHYBRID)
REAL(KIND=JPRD),INTENT(IN) :: PEPS
INTEGER(KIND=JPIM),INTENT(IN) :: KCMAX,KLEAF,KMORDER,KFIRST_DEGREE
CHARACTER(LEN=*),INTENT(IN) :: KPATH
INTEGER,INTENT(IN) :: KUNIT
REAL(KIND=JPRD),INTENT(IN) :: PTHETA(:),PMAT(:,:)
TYPE(HYBRID_MATRIX),INTENT(INOUT) :: YHYBRID

INTEGER(KIND=JPIM) :: IBLOCK,ICOUNT,IORIGINAL_KIND,IORIGINAL_LEVELS,ITRIAL_COUNT
INTEGER(KIND=JPIM) :: IRANK_COUNT,IRANK_MIN,IRANK_MAX
INTEGER(KIND=JPIM) :: ICAND_RANK_COUNT,ICAND_RANK_MIN,ICAND_RANK_MAX
INTEGER(KIND=JPIB) :: ICOST,IRANK_SUM,ICAND_RANK_SUM
INTEGER :: ILENGTH,ISTATUS
REAL(KIND=JPRD) :: ZCOST_RATIO,ZEPS,ZRANK_MEAN,ZSELECT_RATIO
REAL(KIND=JPRD),PARAMETER :: ZSELECT_RATIO_DEFAULT=0.75_JPRD
CHARACTER(LEN=32) :: ZVALUE
LOGICAL :: LDETAILS,LDIAGNOSTICS,LREFINE

CALL FREE_HYBRID(YHYBRID)
IF (SIZE(PMAT,1) == 0 .OR. SIZE(PMAT,2) == 0) RETURN
LDIAGNOSTICS=HYBRID_DIAGNOSTICS_REQUESTED()
LDETAILS=HYBRID_DETAIL_DIAGNOSTICS_REQUESTED()
LREFINE=HYBRID_REFINE_REQUESTED()
ZEPS=PEPS
CALL GET_ENVIRONMENT_VARIABLE('ECTRANS_GPU_HYBRID_EPS',ZVALUE,&
  & LENGTH=ILENGTH,STATUS=ISTATUS)
IF (ISTATUS == 0 .AND. ILENGTH > 0) THEN
  READ(ZVALUE(1:ILENGTH),*,IOSTAT=ISTATUS) ZEPS
  IF (ISTATUS /= 0 .OR. ZEPS <= 0.0_JPRD) ZEPS=PEPS
ENDIF
ZSELECT_RATIO=ZSELECT_RATIO_DEFAULT
CALL GET_ENVIRONMENT_VARIABLE('ECTRANS_GPU_HYBRID_SELECT_RATIO',ZVALUE,&
  & LENGTH=ILENGTH,STATUS=ISTATUS)
IF (ISTATUS == 0 .AND. ILENGTH > 0) THEN
  READ(ZVALUE(1:ILENGTH),*,IOSTAT=ISTATUS) ZSELECT_RATIO
  IF (ISTATUS /= 0 .OR. ZSELECT_RATIO <= 0.0_JPRD .OR. &
    & ZSELECT_RATIO >= 1.0_JPRD) ZSELECT_RATIO=ZSELECT_RATIO_DEFAULT
ENDIF

YHYBRID%CONSTRUCTED=.TRUE.
YHYBRID%DENSE_COST=INT(SIZE(PMAT,1),JPIB)*INT(SIZE(PMAT,2),JPIB)
ICAND_RANK_COUNT=0
ICAND_RANK_SUM=0
ICAND_RANK_MIN=HUGE(ICAND_RANK_MIN)
ICAND_RANK_MAX=0

IF (LREFINE) THEN
  ALLOCATE(YHYBRID%BLOCKS(64))
  ICOUNT=0
  ITRIAL_COUNT=0
  CALL BUILD_REFINED_BLOCK(1,SIZE(PMAT,1),1,SIZE(PMAT,2),ICOUNT)
  CALL RESIZE_BLOCK_STORAGE(ICOUNT,ICOUNT)
  YHYBRID%BLOCK_COUNT=ICOUNT
ELSE
  ICOUNT=0
  CALL VISIT_BLOCK(1,SIZE(PMAT,1),1,SIZE(PMAT,2),.FALSE.,ICOUNT)
  ALLOCATE(YHYBRID%BLOCKS(ICOUNT))
  ICOUNT=0
  CALL VISIT_BLOCK(1,SIZE(PMAT,1),1,SIZE(PMAT,2),.TRUE.,ICOUNT)
  YHYBRID%BLOCK_COUNT=ICOUNT

  DO IBLOCK=1,YHYBRID%BLOCK_COUNT
  ASSOCIATE(B=>YHYBRID%BLOCKS(IBLOCK))
  B%DENSE_COST=INT(B%NROWS,JPIB)*INT(B%NCOLS,JPIB)
  IORIGINAL_KIND=B%KIND
  IORIGINAL_LEVELS=0
  ICOST=B%DENSE_COST
  IRANK_COUNT=0
  IRANK_SUM=0
  IRANK_MIN=0
  IRANK_MAX=0
  SELECT CASE(B%KIND)
  CASE(HYBRID_LOW_RANK)
    CALL CONSTRUCT_BUTTERFLY(ZEPS,B%NCOLS,B%NROWS,B%NCOLS,&
      & PMAT(B%FIRST_ROW:B%FIRST_ROW+B%NROWS-1,&
      & B%FIRST_COL:B%FIRST_COL+B%NCOLS-1),B%BUT)
    ICOST=BUTTERFLY_COST(B%BUT)
    IORIGINAL_LEVELS=B%BUT%N_LEVELS
    CALL COLLECT_RANKS(B%BUT,IBLOCK,IORIGINAL_KIND,&
      & IRANK_COUNT,IRANK_SUM,IRANK_MIN,IRANK_MAX)
    IF (ICOST >= B%DENSE_COST) THEN
      CALL FREE_BUTTERFLY(B%BUT)
      B%KIND=HYBRID_DENSE
    ELSE
      B%FACTOR_COST=ICOST
    ENDIF
  CASE(HYBRID_BUTTERFLY)
    CALL CONSTRUCT_BUTTERFLY(ZEPS,MIN(KCMAX,B%NCOLS),B%NROWS,B%NCOLS,&
      & PMAT(B%FIRST_ROW:B%FIRST_ROW+B%NROWS-1,&
      & B%FIRST_COL:B%FIRST_COL+B%NCOLS-1),B%BUT)
    ICOST=BUTTERFLY_COST(B%BUT)
    IORIGINAL_LEVELS=B%BUT%N_LEVELS
    CALL COLLECT_RANKS(B%BUT,IBLOCK,IORIGINAL_KIND,&
      & IRANK_COUNT,IRANK_SUM,IRANK_MIN,IRANK_MAX)
    IF (ICOST >= B%DENSE_COST) THEN
      CALL FREE_BUTTERFLY(B%BUT)
      B%KIND=HYBRID_DENSE
    ELSE
      B%FACTOR_COST=ICOST
    ENDIF
  END SELECT

  IF (B%KIND == HYBRID_DENSE) THEN
    ALLOCATE(B%DENSE(B%NROWS,B%NCOLS))
    B%DENSE=REAL(PMAT(B%FIRST_ROW:B%FIRST_ROW+B%NROWS-1,&
      & B%FIRST_COL:B%FIRST_COL+B%NCOLS-1),JPRBT)
    B%FACTOR_COST=B%DENSE_COST
    YHYBRID%DENSE_BLOCKS=YHYBRID%DENSE_BLOCKS+1
  ELSEIF (B%KIND == HYBRID_LOW_RANK) THEN
    YHYBRID%LOW_RANK_BLOCKS=YHYBRID%LOW_RANK_BLOCKS+1
  ELSE
    YHYBRID%BUTTERFLY_BLOCKS=YHYBRID%BUTTERFLY_BLOCKS+1
  ENDIF
  YHYBRID%HYBRID_COST=YHYBRID%HYBRID_COST+B%FACTOR_COST
  IF (IRANK_COUNT > 0) THEN
    ICAND_RANK_COUNT=ICAND_RANK_COUNT+IRANK_COUNT
    ICAND_RANK_SUM=ICAND_RANK_SUM+IRANK_SUM
    ICAND_RANK_MIN=MIN(ICAND_RANK_MIN,IRANK_MIN)
    ICAND_RANK_MAX=MAX(ICAND_RANK_MAX,IRANK_MAX)
  ENDIF
  IF (LDETAILS) THEN
    ZCOST_RATIO=REAL(ICOST,JPRD)/REAL(B%DENSE_COST,JPRD)
    ZRANK_MEAN=0.0_JPRD
    IF (IRANK_COUNT > 0) ZRANK_MEAN=REAL(IRANK_SUM,JPRD)/REAL(IRANK_COUNT,JPRD)
    WRITE(KUNIT,*) 'GPU_HYBRID_BLOCK path=',TRIM(KPATH),' m=',KMORDER,&
      & ' block=',IBLOCK,' original=',TRIM(HYBRID_KIND_NAME(IORIGINAL_KIND)),&
      & ' final=',TRIM(HYBRID_KIND_NAME(B%KIND)),&
      & ' first_row=',B%FIRST_ROW,' rows=',B%NROWS,&
      & ' first_col=',B%FIRST_COL,' cols=',B%NCOLS,&
      & ' levels=',IORIGINAL_LEVELS,' dense_cost=',B%DENSE_COST,&
      & ' trial_cost=',ICOST,' factor_cost=',B%FACTOR_COST,&
      & ' cost_ratio=',ZCOST_RATIO,' rank_nodes=',IRANK_COUNT,&
      & ' rank_min=',IRANK_MIN,' rank_max=',IRANK_MAX,' rank_mean=',ZRANK_MEAN
  ENDIF
    END ASSOCIATE
  ENDDO
ENDIF

YHYBRID%SELECTED=YHYBRID%LOW_RANK_BLOCKS+YHYBRID%BUTTERFLY_BLOCKS > 0 .AND. &
  & REAL(YHYBRID%HYBRID_COST,JPRD) < ZSELECT_RATIO*REAL(YHYBRID%DENSE_COST,JPRD)
IF (LDIAGNOSTICS) THEN
  ZCOST_RATIO=REAL(YHYBRID%HYBRID_COST,JPRD)/REAL(YHYBRID%DENSE_COST,JPRD)
  ZRANK_MEAN=0.0_JPRD
  IF (ICAND_RANK_COUNT > 0) THEN
    ZRANK_MEAN=REAL(ICAND_RANK_SUM,JPRD)/REAL(ICAND_RANK_COUNT,JPRD)
  ELSE
    ICAND_RANK_MIN=0
  ENDIF
  WRITE(KUNIT,*) 'GPU_HYBRID_CANDIDATE path=',TRIM(KPATH),' m=',KMORDER,&
    & ' rows=',SIZE(PMAT,1),' cols=',SIZE(PMAT,2),&
    & ' blocks=',YHYBRID%BLOCK_COUNT,' dense_blocks=',YHYBRID%DENSE_BLOCKS,&
    & ' low_rank_blocks=',YHYBRID%LOW_RANK_BLOCKS,&
    & ' butterfly_blocks=',YHYBRID%BUTTERFLY_BLOCKS,&
    & ' dense_cost=',YHYBRID%DENSE_COST,' hybrid_cost=',YHYBRID%HYBRID_COST,&
    & ' cost_ratio=',ZCOST_RATIO,' select_ratio=',ZSELECT_RATIO,' eps=',ZEPS,&
    & ' rank_nodes=',ICAND_RANK_COUNT,' rank_min=',ICAND_RANK_MIN,&
    & ' rank_max=',ICAND_RANK_MAX,' rank_mean=',ZRANK_MEAN,&
    & ' refined=',LREFINE,' selected=',YHYBRID%SELECTED
ENDIF
IF (.NOT.YHYBRID%SELECTED) CALL RELEASE_HYBRID_BLOCKS(YHYBRID)

CONTAINS

LOGICAL FUNCTION HYBRID_DIAGNOSTICS_REQUESTED()
CHARACTER(LEN=16) :: ZVALUE
INTEGER :: ILENGTH,ISTATUS

CALL GET_ENVIRONMENT_VARIABLE('ECTRANS_GPU_HYBRID_DIAGNOSTICS',ZVALUE,&
  & LENGTH=ILENGTH,STATUS=ISTATUS)
HYBRID_DIAGNOSTICS_REQUESTED=ISTATUS == 0 .AND. ILENGTH > 0 .AND. &
  & INDEX('12',ZVALUE(1:1)) > 0
END FUNCTION HYBRID_DIAGNOSTICS_REQUESTED

LOGICAL FUNCTION HYBRID_DETAIL_DIAGNOSTICS_REQUESTED()
CHARACTER(LEN=16) :: ZVALUE
INTEGER :: ILENGTH,ISTATUS

CALL GET_ENVIRONMENT_VARIABLE('ECTRANS_GPU_HYBRID_DIAGNOSTICS',ZVALUE,&
  & LENGTH=ILENGTH,STATUS=ISTATUS)
HYBRID_DETAIL_DIAGNOSTICS_REQUESTED=ISTATUS == 0 .AND. ILENGTH > 0 .AND. &
  & ZVALUE(1:1) == '1'
END FUNCTION HYBRID_DETAIL_DIAGNOSTICS_REQUESTED

LOGICAL FUNCTION HYBRID_REFINE_REQUESTED()
CHARACTER(LEN=16) :: ZVALUE
INTEGER :: ILENGTH,ISTATUS

CALL GET_ENVIRONMENT_VARIABLE('ECTRANS_GPU_HYBRID_REFINE',ZVALUE,&
  & LENGTH=ILENGTH,STATUS=ISTATUS)
HYBRID_REFINE_REQUESTED=ISTATUS == 0 .AND. ILENGTH > 0 .AND. &
  & ZVALUE(1:1) == '1'
END FUNCTION HYBRID_REFINE_REQUESTED

