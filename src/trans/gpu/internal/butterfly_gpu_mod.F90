GROUP%SCRATCH_COLS=0
ALLOCATE(GROUP%SCRATCH_OFFSET(GROUP%COUNT))
DO IG=1,GROUP%COUNT
  GROUP%SCRATCH_OFFSET(IG)=GROUP%SCRATCH_COLS
  GROUP%SCRATCH_COLS=GROUP%SCRATCH_COLS+MAX(0, GROUP%K(IG)-GROUP%N(IG))
  ILIMIT=GROUP%K(IG)
  GROUP%TILE_COUNT=GROUP%TILE_COUNT+(ILIMIT+IOUTPUTS-1)/IOUTPUTS
ENDDO
ALLOCATE(GROUP%TILE_GROUP(GROUP%TILE_COUNT),&
  & GROUP%TILE_START(GROUP%TILE_COUNT))
IT=0
DO IG=1,GROUP%COUNT
  ILIMIT=GROUP%K(IG)
  DO ISTART=0,ILIMIT-1,IOUTPUTS
    IT=IT+1
    GROUP%TILE_GROUP(IT)=IG-1
    GROUP%TILE_START(IT)=ISTART
  ENDDO
ENDDO
CALL ENTER_COMPACT_GROUP_DEVICE(GROUP)
END SUBROUTINE BUILD_COMPACT_TILES

