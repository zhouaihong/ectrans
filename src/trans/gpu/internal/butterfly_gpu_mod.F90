      & .FALSE.,.FALSE.,ZERO,ISTREAM,KBLAS_BASE+2*JL-1,ALLOCATOR)
  ENDIF
ENDDO
CALL COPY_COLUMNS(POUT,PIN,KLD,KOUT_BASE,KIN_BASE,0_JPIB,&
  & PLAN%EVEN_BETA_COLS,KASYNC)
CALL RUN_GROUP(PLAN%FINAL,PLAN,PIN,POUT,KLD,KIN_BASE,0_JPIB,&
  & .FALSE.,.TRUE.,ONE,ISTREAM,KBLAS_BASE+30,ALLOCATOR,.TRUE.)
