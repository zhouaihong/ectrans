SUBROUTINE COLLECT_FUSION_STATS(HYBRID,KCOUNT,KTOTAL_COLS,KMAX_COLS,&
  & KMAX_LEVELS,KFIT1,KFIT2,KFIT4,KFIT8,KFIT16,KFIT32,KFIT64,KFIT100,&
  & KLEVELS,KINTERMEDIATE)
TYPE(HYBRID_MATRIX),INTENT(IN) :: HYBRID
INTEGER(KIND=JPIM),INTENT(INOUT) :: KCOUNT,KMAX_COLS,KMAX_LEVELS
INTEGER(KIND=JPIM),INTENT(INOUT) :: KFIT1,KFIT2,KFIT4,KFIT8
INTEGER(KIND=JPIM),INTENT(INOUT) :: KFIT16,KFIT32,KFIT64,KFIT100,KLEVELS(0:)
INTEGER(KIND=JPIB),INTENT(INOUT) :: KTOTAL_COLS,KINTERMEDIATE
INTEGER(KIND=JPIM) :: JB,JL,ICOLS
INTEGER(KIND=JPIB),PARAMETER :: ISHARED_BYTES=224_JPIB*1024_JPIB

DO JB=1,HYBRID%BLOCK_COUNT
  IF (HYBRID%BLOCKS(JB)%KIND == HYBRID_DENSE) CYCLE
  ICOLS=HYBRID%BLOCKS(JB)%BUT%IBETALEN_MAX
  KCOUNT=KCOUNT+1
  KTOTAL_COLS=KTOTAL_COLS+INT(ICOLS,JPIB)
  KMAX_COLS=MAX(KMAX_COLS,ICOLS)
  KMAX_LEVELS=MAX(KMAX_LEVELS,HYBRID%BLOCKS(JB)%BUT%N_LEVELS)
  KLEVELS(MIN(UBOUND(KLEVELS,1),HYBRID%BLOCKS(JB)%BUT%N_LEVELS))=&
    & KLEVELS(MIN(UBOUND(KLEVELS,1),HYBRID%BLOCKS(JB)%BUT%N_LEVELS))+1
  IF (16_JPIB*INT(ICOLS,JPIB) <= ISHARED_BYTES) KFIT1=KFIT1+1
  IF (32_JPIB*INT(ICOLS,JPIB) <= ISHARED_BYTES) KFIT2=KFIT2+1
  IF (64_JPIB*INT(ICOLS,JPIB) <= ISHARED_BYTES) KFIT4=KFIT4+1
  IF (128_JPIB*INT(ICOLS,JPIB) <= ISHARED_BYTES) KFIT8=KFIT8+1
  IF (256_JPIB*INT(ICOLS,JPIB) <= ISHARED_BYTES) KFIT16=KFIT16+1
  IF (512_JPIB*INT(ICOLS,JPIB) <= ISHARED_BYTES) KFIT32=KFIT32+1
  IF (1024_JPIB*INT(ICOLS,JPIB) <= ISHARED_BYTES) KFIT64=KFIT64+1
  IF (1600_JPIB*INT(ICOLS,JPIB) <= ISHARED_BYTES) KFIT100=KFIT100+1
  DO JL=0,HYBRID%BLOCKS(JB)%BUT%N_LEVELS
    KINTERMEDIATE=KINTERMEDIATE+INT(HYBRID%BLOCKS(JB)%BUT%SLEV(JL)%IBETALEN,JPIB)
  ENDDO
ENDDO
END SUBROUTINE COLLECT_FUSION_STATS

SUBROUTINE BUILD_ONE_PLAN(PLAN,LSYM,LDIRECT)
USE TPM_FLT, ONLY: S
USE TPM_DISTR, ONLY: D

TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
LOGICAL,INTENT(IN) :: LSYM
LOGICAL,INTENT(IN) :: LDIRECT

INTEGER(KIND=JPIM) :: JMLOC,JL,I0,IFN,IDENSE,IFUSED
INTEGER(KIND=JPIM),ALLOCATABLE :: IFW(:),IRO(:),IRE(:)
INTEGER(KIND=JPIB) :: IPOS,IFACTORS,IFACTORS_ALLOC,IBETA,IPIVOTS,IPIVOT_POS
LOGICAL :: LVALIDATE

ALLOCATE(PLAN%USE_HYBRID(D%NUMP))
PLAN%USE_HYBRID=.FALSE.
LVALIDATE=BUTTERFLY_VALIDATION_REQUESTED()
PLAN%COMPACT_ID=BUTTERFLY_COMPACT_ID_REQUESTED()
PLAN%NATIVE_GROUPED=BUTTERFLY_NATIVE_GROUPED_REQUESTED()
PLAN%FUSE_REVERSE=PLAN%COMPACT_ID .AND. PLAN%NATIVE_GROUPED .AND. &
  & BUTTERFLY_FUSE_REVERSE_REQUESTED()
PLAN%DENSE_DISJOINT=.TRUE.
PLAN%FUSE_LEAF=LDIRECT .AND. PLAN%COMPACT_ID .AND. BUTTERFLY_FUSE_LEAF_REQUESTED()
PLAN%FUSE_FINAL=LDIRECT .AND. BUTTERFLY_FUSE_FINAL_REQUESTED()
PLAN%RECOMPRESS_FINAL=LDIRECT .AND. BUTTERFLY_RECOMPRESS_FINAL_REQUESTED()
PLAN%FUSE_FINAL=PLAN%FUSE_FINAL .OR. PLAN%RECOMPRESS_FINAL

DO JMLOC=1,D%NUMP
  IF (LDIRECT .AND. LSYM) THEN
    CALL SCAN_HYBRID(S%FA(JMLOC)%YHYBRID_DIRECT_S,PLAN,JMLOC)
  ELSEIF (LDIRECT) THEN
    CALL SCAN_HYBRID(S%FA(JMLOC)%YHYBRID_DIRECT_A,PLAN,JMLOC)
  ELSEIF (LSYM) THEN
    CALL SCAN_HYBRID(S%FA(JMLOC)%YHYBRID_S,PLAN,JMLOC)
  ELSE
    CALL SCAN_HYBRID(S%FA(JMLOC)%YHYBRID_A,PLAN,JMLOC)
  ENDIF
ENDDO

IF (LVALIDATE) THEN
  CALL KEEP_BEST_MATRIX(PLAN)
ENDIF
PLAN%ENABLED=ANY(PLAN%USE_HYBRID)
IF (.NOT.PLAN%ENABLED) RETURN
IF (LDIRECT) CALL BUILD_DIRECT_INLINE_CROP(PLAN,LSYM)
IF (PLAN%DIRECT_INLINE_CROP) RETURN
IF (LDIRECT) CALL BUILD_DIRECT_NATIVE_BLOCKS(PLAN,LSYM)
IF (PLAN%DIRECT_NATIVE_BLOCKS) RETURN

IBETA=0
DO JMLOC=1,D%NUMP
  IF (.NOT.PLAN%USE_HYBRID(JMLOC)) CYCLE
  IF (LDIRECT .AND. LSYM) THEN
    CALL ASSIGN_WORK(S%FA(JMLOC)%YHYBRID_DIRECT_S,0,IBETA,PLAN%FUSE_LEAF)
  ELSEIF (LDIRECT) THEN
    CALL ASSIGN_WORK(S%FA(JMLOC)%YHYBRID_DIRECT_A,0,IBETA,PLAN%FUSE_LEAF)
  ELSEIF (LSYM) THEN
    CALL ASSIGN_WORK(S%FA(JMLOC)%YHYBRID_S,0,IBETA,PLAN%FUSE_LEAF)
  ELSE
    CALL ASSIGN_WORK(S%FA(JMLOC)%YHYBRID_A,0,IBETA,PLAN%FUSE_LEAF)
  ENDIF
ENDDO
PLAN%EVEN_BETA_COLS=IBETA
DO JMLOC=1,D%NUMP
  IF (.NOT.PLAN%USE_HYBRID(JMLOC)) CYCLE
  IF (LDIRECT .AND. LSYM) THEN
    CALL ASSIGN_WORK(S%FA(JMLOC)%YHYBRID_DIRECT_S,1,IBETA,PLAN%FUSE_LEAF)
  ELSEIF (LDIRECT) THEN
    CALL ASSIGN_WORK(S%FA(JMLOC)%YHYBRID_DIRECT_A,1,IBETA,PLAN%FUSE_LEAF)
  ELSEIF (LSYM) THEN
    CALL ASSIGN_WORK(S%FA(JMLOC)%YHYBRID_S,1,IBETA,PLAN%FUSE_LEAF)
  ELSE
    CALL ASSIGN_WORK(S%FA(JMLOC)%YHYBRID_A,1,IBETA,PLAN%FUSE_LEAF)
  ENDIF
ENDDO
PLAN%BETA_COLS=IBETA
PLAN%WORK_COLS=IBETA

IF (PLAN%MAX_LEVELS > 0) ALLOCATE(PLAN%LEVEL(1:PLAN%MAX_LEVELS))
IFACTORS=0
IPIVOTS=0
DO JMLOC=1,D%NUMP
  IF (.NOT.PLAN%USE_HYBRID(JMLOC)) CYCLE
  IF (LDIRECT .AND. LSYM) THEN
    CALL COUNT_HYBRID(S%FA(JMLOC)%YHYBRID_DIRECT_S,PLAN,IFACTORS,IPIVOTS)
  ELSEIF (LDIRECT) THEN
    CALL COUNT_HYBRID(S%FA(JMLOC)%YHYBRID_DIRECT_A,PLAN,IFACTORS,IPIVOTS)
  ELSEIF (LSYM) THEN
    CALL COUNT_HYBRID(S%FA(JMLOC)%YHYBRID_S,PLAN,IFACTORS,IPIVOTS)
  ELSE
    CALL COUNT_HYBRID(S%FA(JMLOC)%YHYBRID_A,PLAN,IFACTORS,IPIVOTS)
  ENDIF
ENDDO

CALL ALLOC_GROUP(PLAN%LEVEL0)
CALL ALLOC_GROUP(PLAN%FINAL)
CALL ALLOC_GROUP(PLAN%DENSE)
CALL ALLOC_FUSED_LEAF(PLAN%FUSED_LEAF)
DO JL=1,PLAN%MAX_LEVELS
  CALL ALLOC_GROUP(PLAN%LEVEL(JL)%FWD)
  CALL ALLOC_GROUP(PLAN%LEVEL(JL)%REV_ODD)
  CALL ALLOC_GROUP(PLAN%LEVEL(JL)%REV_EVEN)
ENDDO
IFACTORS_ALLOC=IFACTORS
IF (PLAN%FUSE_FINAL) IFACTORS_ALLOC=IFACTORS_ALLOC+PLAN%FINAL_FACTOR_VALUES
ALLOCATE(PLAN%FACTORS(IFACTORS_ALLOC))
PLAN%FACTORS=ZERO
IF (PLAN%COMPACT_ID) ALLOCATE(PLAN%PIVOTS(IPIVOTS))

ALLOCATE(IFW(PLAN%MAX_LEVELS),IRO(PLAN%MAX_LEVELS),IRE(PLAN%MAX_LEVELS))
IFW=0
IRO=0
IRE=0
I0=0
IFN=0
IDENSE=0
IFUSED=0
IPOS=1
IPIVOT_POS=1
DO JMLOC=1,D%NUMP
  IF (.NOT.PLAN%USE_HYBRID(JMLOC)) CYCLE
  IF (LDIRECT .AND. LSYM) THEN
    CALL FILL_HYBRID(S%FA(JMLOC)%YHYBRID_DIRECT_S,JMLOC,PLAN,&
      & IPOS,IPIVOT_POS,I0,IFN,IDENSE,IFUSED,IFW,IRO,IRE,LDIRECT)
  ELSEIF (LDIRECT) THEN
    CALL FILL_HYBRID(S%FA(JMLOC)%YHYBRID_DIRECT_A,JMLOC,PLAN,&
      & IPOS,IPIVOT_POS,I0,IFN,IDENSE,IFUSED,IFW,IRO,IRE,LDIRECT)
  ELSEIF (LSYM) THEN
    CALL FILL_HYBRID(S%FA(JMLOC)%YHYBRID_S,JMLOC,PLAN,IPOS,IPIVOT_POS,I0,IFN,&
      & IDENSE,IFUSED,IFW,IRO,IRE,LDIRECT)
  ELSE
    CALL FILL_HYBRID(S%FA(JMLOC)%YHYBRID_A,JMLOC,PLAN,IPOS,IPIVOT_POS,I0,IFN,&
      & IDENSE,IFUSED,IFW,IRO,IRE,LDIRECT)
  ENDIF
ENDDO
DEALLOCATE(IFW,IRO,IRE)
IF (PLAN%COMPACT_ID) THEN
  CALL BUILD_COMPACT_GROUPS(PLAN)
  IF (.NOT.(LDIRECT .AND. PLAN%NATIVE_GROUPED)) &
    & PLAN%WORK_COLS=PLAN%BETA_COLS+PLAN%COMPACT_SCRATCH_COLS
ENDIF
IF (PLAN%FUSE_FINAL) CALL BUILD_FUSED_FINAL(PLAN,IPOS)
IF (PLAN%NATIVE_GROUPED) CALL ENTER_NATIVE_GROUPS_DEVICE(PLAN)
IF (PLAN%FUSE_LEAF) CALL ENTER_FUSED_LEAF_DEVICE(PLAN%FUSED_LEAF)

#ifdef ACCGPU
!$ACC ENTER DATA COPYIN(PLAN%FACTORS)
IF (ALLOCATED(PLAN%PIVOTS)) THEN
!$ACC ENTER DATA COPYIN(PLAN%PIVOTS)
ENDIF
IF (ALLOCATED(PLAN%FINAL_GATHER_SRC)) THEN
!$ACC ENTER DATA COPYIN(PLAN%FINAL_GATHER_SRC,PLAN%FINAL_GATHER_DST)
ENDIF
#endif
#ifdef OMPGPU
!$OMP TARGET ENTER DATA MAP(TO:PLAN%FACTORS)
IF (ALLOCATED(PLAN%PIVOTS)) THEN
!$OMP TARGET ENTER DATA MAP(TO:PLAN%PIVOTS)
ENDIF
IF (ALLOCATED(PLAN%FINAL_GATHER_SRC)) THEN
!$OMP TARGET ENTER DATA MAP(TO:PLAN%FINAL_GATHER_SRC,PLAN%FINAL_GATHER_DST)
ENDIF
#endif
END SUBROUTINE BUILD_ONE_PLAN

SUBROUTINE BUILD_DIRECT_INLINE_CROP(PLAN,LSYM)
USE TPM_FLT, ONLY: S
USE TPM_DISTR, ONLY: D
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
LOGICAL,INTENT(IN) :: LSYM
INTEGER(KIND=JPIM) :: JMLOC
LOGICAL :: LVALID

PLAN%DIRECT_INLINE_CROP=PLAN%DENSE_DISJOINT .AND. &
  & PLAN%DENSE_BLOCKS == PLAN%SELECTED_COUNT .AND. &
  & PLAN%LOW_RANK_BLOCKS == 0 .AND. PLAN%BUTTERFLY_BLOCKS == 0
IF (.NOT.PLAN%DIRECT_INLINE_CROP) RETURN
ALLOCATE(PLAN%DIRECT_CROP_FIRST(D%NUMP),PLAN%DIRECT_CROP_COUNT(D%NUMP))
PLAN%DIRECT_CROP_FIRST=1
PLAN%DIRECT_CROP_COUNT=0
LVALID=.TRUE.
DO JMLOC=1,D%NUMP
  IF (.NOT.PLAN%USE_HYBRID(JMLOC)) CYCLE
  IF (LSYM) THEN
    CALL SET_DIRECT_INLINE_CROP(S%FA(JMLOC)%YHYBRID_DIRECT_S,PLAN,JMLOC,LVALID)
  ELSE
    CALL SET_DIRECT_INLINE_CROP(S%FA(JMLOC)%YHYBRID_DIRECT_A,PLAN,JMLOC,LVALID)
  ENDIF
ENDDO
IF (.NOT.LVALID) THEN
  DEALLOCATE(PLAN%DIRECT_CROP_FIRST,PLAN%DIRECT_CROP_COUNT)
  PLAN%DIRECT_INLINE_CROP=.FALSE.
ENDIF
END SUBROUTINE BUILD_DIRECT_INLINE_CROP

SUBROUTINE SET_DIRECT_INLINE_CROP(HYBRID,PLAN,KMLOC,LVALID)
TYPE(HYBRID_MATRIX),INTENT(IN) :: HYBRID
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIM),INTENT(IN) :: KMLOC
LOGICAL,INTENT(INOUT) :: LVALID

IF (.NOT.LVALID) RETURN
IF (HYBRID%BLOCK_COUNT /= 1 .OR. HYBRID%BLOCKS(1)%KIND /= HYBRID_DENSE .OR. &
  & HYBRID%BLOCKS(1)%FIRST_ROW /= 1 .OR. HYBRID%BLOCKS(1)%FIRST_COL < 1 .OR. &
  & HYBRID%BLOCKS(1)%NCOLS < 1) THEN
  LVALID=.FALSE.
  RETURN
ENDIF
PLAN%DIRECT_CROP_FIRST(KMLOC)=HYBRID%BLOCKS(1)%FIRST_COL
PLAN%DIRECT_CROP_COUNT(KMLOC)=HYBRID%BLOCKS(1)%NCOLS
END SUBROUTINE SET_DIRECT_INLINE_CROP

SUBROUTINE BUILD_DIRECT_NATIVE_BLOCKS(PLAN,LSYM)
USE TPM_DIM, ONLY: R
USE TPM_DISTR, ONLY: D
USE TPM_FLT, ONLY: S
USE TPM_GEOMETRY, ONLY: G
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
LOGICAL,INTENT(IN) :: LSYM
INTEGER(KIND=JPIM) :: ICOUNT,JMLOC,KM
LOGICAL :: LVALID

PLAN%DIRECT_NATIVE_BLOCKS=PLAN%DENSE_DISJOINT .AND. &
  & PLAN%DENSE_BLOCKS > PLAN%SELECTED_COUNT .AND. &
  & PLAN%LOW_RANK_BLOCKS == 0 .AND. PLAN%BUTTERFLY_BLOCKS == 0
IF (.NOT.PLAN%DIRECT_NATIVE_BLOCKS) RETURN

ICOUNT=0
DO JMLOC=1,D%NUMP
  KM=D%MYMS(JMLOC)
  IF (KM == 0) CYCLE
  IF (PLAN%USE_HYBRID(JMLOC)) THEN
    IF (LSYM) THEN
      ICOUNT=ICOUNT+S%FA(JMLOC)%YHYBRID_DIRECT_S%BLOCK_COUNT
    ELSE
      ICOUNT=ICOUNT+S%FA(JMLOC)%YHYBRID_DIRECT_A%BLOCK_COUNT
    ENDIF
  ELSE
    ICOUNT=ICOUNT+1
  ENDIF
ENDDO
IF (ICOUNT <= 0) THEN
  PLAN%DIRECT_NATIVE_BLOCKS=.FALSE.
  RETURN
ENDIF

PLAN%DIRECT_GROUP_COUNT=ICOUNT
ALLOCATE(PLAN%DIRECT_GROUP_MLOC(ICOUNT),PLAN%DIRECT_GROUP_FIRST_ROW(ICOUNT),&
  & PLAN%DIRECT_GROUP_FIRST_COL(ICOUNT),PLAN%DIRECT_GROUP_N(ICOUNT),&
  & PLAN%DIRECT_GROUP_K(ICOUNT))
ICOUNT=0
LVALID=.TRUE.
DO JMLOC=1,D%NUMP
  KM=D%MYMS(JMLOC)
  IF (KM == 0) CYCLE
  IF (PLAN%USE_HYBRID(JMLOC)) THEN
    IF (LSYM) THEN
      CALL APPEND_DIRECT_NATIVE_BLOCKS(S%FA(JMLOC)%YHYBRID_DIRECT_S,&
        & PLAN,JMLOC,ICOUNT,LVALID)
    ELSE
      CALL APPEND_DIRECT_NATIVE_BLOCKS(S%FA(JMLOC)%YHYBRID_DIRECT_A,&
        & PLAN,JMLOC,ICOUNT,LVALID)
    ENDIF
  ELSE
    ICOUNT=ICOUNT+1
    PLAN%DIRECT_GROUP_MLOC(ICOUNT)=JMLOC
    PLAN%DIRECT_GROUP_FIRST_ROW(ICOUNT)=1
    PLAN%DIRECT_GROUP_FIRST_COL(ICOUNT)=1
    PLAN%DIRECT_GROUP_N(ICOUNT)=MERGE((R%NSMAX-KM+3)/2,&
      & (R%NSMAX-KM+2)/2,LSYM)
    PLAN%DIRECT_GROUP_K(ICOUNT)=G%NDGLU(KM)
  ENDIF
ENDDO
IF (.NOT.LVALID .OR. ICOUNT /= PLAN%DIRECT_GROUP_COUNT) THEN
  DEALLOCATE(PLAN%DIRECT_GROUP_MLOC,PLAN%DIRECT_GROUP_FIRST_ROW,&
    & PLAN%DIRECT_GROUP_FIRST_COL,PLAN%DIRECT_GROUP_N,PLAN%DIRECT_GROUP_K)
  PLAN%DIRECT_GROUP_COUNT=0
  PLAN%DIRECT_NATIVE_BLOCKS=.FALSE.
ENDIF
END SUBROUTINE BUILD_DIRECT_NATIVE_BLOCKS

SUBROUTINE APPEND_DIRECT_NATIVE_BLOCKS(HYBRID,PLAN,KMLOC,KCOUNT,LVALID)
TYPE(HYBRID_MATRIX),INTENT(IN) :: HYBRID
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIM),INTENT(IN) :: KMLOC
INTEGER(KIND=JPIM),INTENT(INOUT) :: KCOUNT
LOGICAL,INTENT(INOUT) :: LVALID
INTEGER(KIND=JPIM) :: JB

IF (.NOT.LVALID) RETURN
DO JB=1,HYBRID%BLOCK_COUNT
  ASSOCIATE(B=>HYBRID%BLOCKS(JB))
  IF (B%KIND /= HYBRID_DENSE .OR. B%FIRST_ROW < 1 .OR. B%FIRST_COL < 1 .OR. &
    & B%NROWS < 1 .OR. B%NCOLS < 1) THEN
    LVALID=.FALSE.
    RETURN
  ENDIF
  KCOUNT=KCOUNT+1
  PLAN%DIRECT_GROUP_MLOC(KCOUNT)=KMLOC
  PLAN%DIRECT_GROUP_FIRST_ROW(KCOUNT)=B%FIRST_ROW
  PLAN%DIRECT_GROUP_FIRST_COL(KCOUNT)=B%FIRST_COL
  PLAN%DIRECT_GROUP_N(KCOUNT)=B%NROWS
  PLAN%DIRECT_GROUP_K(KCOUNT)=B%NCOLS
  END ASSOCIATE
ENDDO
END SUBROUTINE APPEND_DIRECT_NATIVE_BLOCKS

SUBROUTINE SCAN_HYBRID(HYBRID,PLAN,KMLOC)
TYPE(HYBRID_MATRIX),INTENT(IN) :: HYBRID
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIM),INTENT(IN) :: KMLOC
INTEGER(KIND=JPIM) :: JB

IF (HYBRID%CONSTRUCTED) PLAN%CANDIDATE_COUNT=PLAN%CANDIDATE_COUNT+1
PLAN%USE_HYBRID(KMLOC)=HYBRID%SELECTED
IF (HYBRID%DENSE_EXEC_COST > 0) THEN
  PLAN%DENSE_EXEC_COST=PLAN%DENSE_EXEC_COST+HYBRID%DENSE_EXEC_COST
  IF (HYBRID%SELECTED) THEN
    PLAN%HYBRID_EXEC_COST=PLAN%HYBRID_EXEC_COST+HYBRID%HYBRID_EXEC_COST
  ELSE
    PLAN%HYBRID_EXEC_COST=PLAN%HYBRID_EXEC_COST+HYBRID%DENSE_EXEC_COST
  ENDIF
ENDIF
IF (.NOT.HYBRID%SELECTED) RETURN
PLAN%DENSE_DISJOINT=PLAN%DENSE_DISJOINT .AND. HYBRID%DISJOINT_OUTPUT
PLAN%SELECTED_COUNT=PLAN%SELECTED_COUNT+1
PLAN%DENSE_BLOCKS=PLAN%DENSE_BLOCKS+HYBRID%DENSE_BLOCKS
PLAN%LOW_RANK_BLOCKS=PLAN%LOW_RANK_BLOCKS+HYBRID%LOW_RANK_BLOCKS
PLAN%BUTTERFLY_BLOCKS=PLAN%BUTTERFLY_BLOCKS+HYBRID%BUTTERFLY_BLOCKS
PLAN%DENSE_COST=PLAN%DENSE_COST+HYBRID%DENSE_COST
PLAN%HYBRID_COST=PLAN%HYBRID_COST+HYBRID%HYBRID_COST
DO JB=1,HYBRID%BLOCK_COUNT
  IF (HYBRID%BLOCKS(JB)%KIND /= HYBRID_DENSE) &
    PLAN%MAX_LEVELS=MAX(PLAN%MAX_LEVELS,HYBRID%BLOCKS(JB)%BUT%N_LEVELS)
ENDDO
END SUBROUTINE SCAN_HYBRID

SUBROUTINE KEEP_BEST_MATRIX(PLAN)
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIM) :: JBEST,JMLOC

JBEST=0
DO JMLOC=1,SIZE(PLAN%USE_HYBRID)
  IF (PLAN%USE_HYBRID(JMLOC)) THEN
    JBEST=JMLOC
    EXIT
  ENDIF
ENDDO
PLAN%USE_HYBRID=.FALSE.
IF (JBEST > 0) PLAN%USE_HYBRID(JBEST)=.TRUE.
END SUBROUTINE KEEP_BEST_MATRIX

SUBROUTINE ASSIGN_WORK(HYBRID,KPARITY,KBASE,LFUSE_LEAF)
TYPE(HYBRID_MATRIX),INTENT(INOUT) :: HYBRID
INTEGER(KIND=JPIM),INTENT(IN) :: KPARITY
INTEGER(KIND=JPIB),INTENT(INOUT) :: KBASE
LOGICAL,INTENT(IN) :: LFUSE_LEAF
INTEGER(KIND=JPIM) :: JB

DO JB=1,HYBRID%BLOCK_COUNT
  IF (HYBRID%BLOCKS(JB)%KIND == HYBRID_DENSE) CYCLE
  IF (LFUSE_LEAF .AND. HYBRID%BLOCKS(JB)%BUT%N_LEVELS == 0 .AND. &
    & HYBRID%BLOCKS(JB)%BUT%SLEV(0)%IJ == 1) CYCLE
  IF (MOD(HYBRID%BLOCKS(JB)%BUT%N_LEVELS,2) /= KPARITY) CYCLE
  HYBRID%BLOCKS(JB)%WORK_BASE=KBASE
  KBASE=KBASE+HYBRID%BLOCKS(JB)%BUT%IBETALEN_MAX
ENDDO
END SUBROUTINE ASSIGN_WORK

SUBROUTINE COUNT_HYBRID(HYBRID,PLAN,KFACTORS,KPIVOTS)
TYPE(HYBRID_MATRIX),INTENT(IN) :: HYBRID
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIB),INTENT(INOUT) :: KFACTORS,KPIVOTS
INTEGER(KIND=JPIM) :: JB

DO JB=1,HYBRID%BLOCK_COUNT
  IF (HYBRID%BLOCKS(JB)%KIND == HYBRID_DENSE) THEN
    PLAN%DENSE%COUNT=PLAN%DENSE%COUNT+1
    KFACTORS=KFACTORS+HYBRID%BLOCKS(JB)%DENSE_COST
  ELSEIF (FUSIBLE_LEAF(PLAN,HYBRID%BLOCKS(JB)%BUT)) THEN
    CALL COUNT_FUSED_LEAF(HYBRID%BLOCKS(JB)%BUT,PLAN,KFACTORS,KPIVOTS)
  ELSE
    CALL COUNT_MATRIX(HYBRID%BLOCKS(JB)%BUT,PLAN,KFACTORS,KPIVOTS)
  ENDIF
ENDDO
END SUBROUTINE COUNT_HYBRID

LOGICAL FUNCTION FUSIBLE_LEAF(PLAN,BUT)
TYPE(BUTTERFLY_GPU_PLAN),INTENT(IN) :: PLAN
TYPE(BUTTERFLY_STRUCT),INTENT(IN) :: BUT
FUSIBLE_LEAF=PLAN%FUSE_LEAF .AND. BUT%N_LEVELS == 0 .AND. &
  & BUT%SLEV(0)%IJ == 1
END FUNCTION FUSIBLE_LEAF

SUBROUTINE COUNT_FUSED_LEAF(BUT,PLAN,KFACTORS,KPIVOTS)
TYPE(BUTTERFLY_STRUCT),INTENT(IN) :: BUT
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIB),INTENT(INOUT) :: KFACTORS,KPIVOTS
INTEGER(KIND=JPIM) :: JK
TYPE(NODE_TYPE),POINTER :: YNODE

DO JK=1,BUT%SLEV(0)%IK
  YNODE=>BUT%SLEV(0)%NODE(1,JK)
  PLAN%FUSED_LEAF%COUNT=PLAN%FUSED_LEAF%COUNT+1
  PLAN%FUSED_LEAF%MAX_RANK=MAX(PLAN%FUSED_LEAF%MAX_RANK,YNODE%IRANK)
  KFACTORS=KFACTORS+INT(YNODE%ICOLS-YNODE%IRANK,JPIB)*&
    & INT(YNODE%IRANK,JPIB)+INT(YNODE%IROWS,JPIB)*INT(YNODE%IRANK,JPIB)
  KPIVOTS=KPIVOTS+YNODE%ICOLS
  PLAN%PROJECTION_FULL_VALUES=PLAN%PROJECTION_FULL_VALUES+&
    & INT(YNODE%ICOLS,JPIB)*INT(YNODE%IRANK,JPIB)
  PLAN%PROJECTION_COMPACT_VALUES=PLAN%PROJECTION_COMPACT_VALUES+&
    & INT(YNODE%ICOLS-YNODE%IRANK,JPIB)*INT(YNODE%IRANK,JPIB)
  PLAN%FINAL_FACTOR_VALUES=PLAN%FINAL_FACTOR_VALUES+&
    & INT(YNODE%IROWS,JPIB)*INT(YNODE%IRANK,JPIB)
ENDDO
END SUBROUTINE COUNT_FUSED_LEAF

SUBROUTINE COUNT_MATRIX(BUT,PLAN,KFACTORS,KPIVOTS)
TYPE(BUTTERFLY_STRUCT),INTENT(IN) :: BUT
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIB),INTENT(INOUT) :: KFACTORS,KPIVOTS
INTEGER(KIND=JPIM) :: JL,JJ,JK,IRANKL,IRANKR
TYPE(NODE_TYPE),POINTER :: YNODE

DO JK=1,BUT%SLEV(0)%IK
  YNODE=>BUT%SLEV(0)%NODE(1,JK)
  PLAN%LEVEL0%COUNT=PLAN%LEVEL0%COUNT+1
  PLAN%PROJECTION_FULL_VALUES=PLAN%PROJECTION_FULL_VALUES+&
    & INT(YNODE%ICOLS,JPIB)*INT(YNODE%IRANK,JPIB)
  PLAN%PROJECTION_COMPACT_VALUES=PLAN%PROJECTION_COMPACT_VALUES+&
    & INT(YNODE%ICOLS-YNODE%IRANK,JPIB)*INT(YNODE%IRANK,JPIB)
  IF (PLAN%COMPACT_ID) THEN
    KFACTORS=KFACTORS+INT(YNODE%ICOLS-YNODE%IRANK,JPIB)*&
      & INT(YNODE%IRANK,JPIB)
    KPIVOTS=KPIVOTS+YNODE%ICOLS
  ELSE
    KFACTORS=KFACTORS+INT(YNODE%ICOLS,JPIB)*INT(YNODE%IRANK,JPIB)
  ENDIF
ENDDO
DO JL=1,BUT%N_LEVELS
  DO JK=1,BUT%SLEV(JL)%IK
    DO JJ=1,BUT%SLEV(JL)%IJ
      YNODE=>BUT%SLEV(JL)%NODE(JJ,JK)
      IRANKL=BUT%SLEV(JL-1)%NODE((JJ+1)/2,2*JK-1)%IRANK
      IRANKR=0
      IF (2*JK <= BUT%SLEV(JL-1)%IK) &
        IRANKR=BUT%SLEV(JL-1)%NODE((JJ+1)/2,2*JK)%IRANK
      PLAN%LEVEL(JL)%FWD%COUNT=PLAN%LEVEL(JL)%FWD%COUNT+1
      IF (MOD(JJ,2) == 1) THEN
        PLAN%LEVEL(JL)%REV_ODD%COUNT=PLAN%LEVEL(JL)%REV_ODD%COUNT+1
      ELSE
        PLAN%LEVEL(JL)%REV_EVEN%COUNT=PLAN%LEVEL(JL)%REV_EVEN%COUNT+1
      ENDIF
      PLAN%PROJECTION_FULL_VALUES=PLAN%PROJECTION_FULL_VALUES+&
        & INT(IRANKL+IRANKR,JPIB)*INT(YNODE%IRANK,JPIB)
      PLAN%PROJECTION_COMPACT_VALUES=PLAN%PROJECTION_COMPACT_VALUES+&
        & INT(IRANKL+IRANKR-YNODE%IRANK,JPIB)*INT(YNODE%IRANK,JPIB)
      IF (PLAN%COMPACT_ID) THEN
        KFACTORS=KFACTORS+INT(IRANKL+IRANKR-YNODE%IRANK,JPIB)*&
          & INT(YNODE%IRANK,JPIB)
        KPIVOTS=KPIVOTS+IRANKL+IRANKR
      ELSE
        KFACTORS=KFACTORS+INT(IRANKL+IRANKR,JPIB)*INT(YNODE%IRANK,JPIB)
      ENDIF
    ENDDO
  ENDDO
ENDDO
JL=BUT%N_LEVELS
DO JK=1,BUT%SLEV(JL)%IK
  DO JJ=1,BUT%SLEV(JL)%IJ
    YNODE=>BUT%SLEV(JL)%NODE(JJ,JK)
    PLAN%FINAL%COUNT=PLAN%FINAL%COUNT+1
    KFACTORS=KFACTORS+INT(YNODE%IROWS,JPIB)*INT(YNODE%IRANK,JPIB)
    PLAN%FINAL_FACTOR_VALUES=PLAN%FINAL_FACTOR_VALUES+&
      & INT(YNODE%IROWS,JPIB)*INT(YNODE%IRANK,JPIB)
  ENDDO
ENDDO
END SUBROUTINE COUNT_MATRIX

