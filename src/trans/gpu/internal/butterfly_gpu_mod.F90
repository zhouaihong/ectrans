SUBROUTINE APPLY_BUTTERFLY_DIRECT_FORWARD(PLAN,PIN,POUT,KLD,KWORK_BASE,&
  & KASYNC,KBLAS_BASE,ALLOCATOR)
USE BUFFERED_ALLOCATOR_MOD, ONLY: BUFFERED_ALLOCATOR
#ifdef ACCGPU
USE OPENACC_LIB, ONLY: ACC_GET_HIP_STREAM
#endif
USE ISO_C_BINDING, ONLY: C_INT,C_INTPTR_T
TYPE(BUTTERFLY_GPU_PLAN),INTENT(IN) :: PLAN
REAL(KIND=JPRBT),POINTER,INTENT(IN) :: PIN(:)
REAL(KIND=JPRBT),POINTER,INTENT(INOUT) :: POUT(:)
INTEGER(KIND=JPIM),INTENT(IN) :: KLD,KASYNC,KBLAS_BASE
INTEGER(KIND=JPIB),INTENT(IN) :: KWORK_BASE
TYPE(BUFFERED_ALLOCATOR),INTENT(IN) :: ALLOCATOR
INTEGER(KIND=JPIM) :: JL
INTEGER(C_INTPTR_T) :: ISTREAM

IF (.NOT.PLAN%ENABLED) RETURN
#ifdef ACCGPU
ISTREAM=INT(ACC_GET_HIP_STREAM(INT(KASYNC,C_INT)),C_INTPTR_T)
