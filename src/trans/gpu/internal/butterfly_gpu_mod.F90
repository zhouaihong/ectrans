SUBROUTINE RUN_PROJECTION(GROUP,PLAN,PA,PC,KLD,KADD_A,KADD_C,KADD_SCRATCH,LREVERSE,&
  & LFACTOR_TRANSPOSED,PBETA,KSTREAM,KBLAS,ALLOCATOR,LORDERED)
USE BUFFERED_ALLOCATOR_MOD, ONLY: BUFFERED_ALLOCATOR
USE HICBLAS_MOD, ONLY: HIP_DGEMM_GROUPED_ASYNC
USE TPM_GEN, ONLY: NCUR_RESOL
USE ISO_C_BINDING, ONLY: C_LOC,C_INT,C_INT64_T,C_INTPTR_T
TYPE(BUTTERFLY_GPU_GROUPS),INTENT(IN) :: GROUP
TYPE(BUTTERFLY_GPU_PLAN),INTENT(IN) :: PLAN
REAL(KIND=JPRBT),POINTER,INTENT(IN) :: PA(:)
REAL(KIND=JPRBT),POINTER,INTENT(INOUT) :: PC(:)
INTEGER(KIND=JPIM),INTENT(IN) :: KLD,KBLAS
INTEGER(KIND=JPIB),INTENT(IN) :: KADD_A,KADD_C,KADD_SCRATCH
LOGICAL,INTENT(IN) :: LREVERSE,LFACTOR_TRANSPOSED
REAL(KIND=JPRBT),INTENT(IN) :: PBETA
INTEGER(C_INTPTR_T),INTENT(IN) :: KSTREAM
TYPE(BUFFERED_ALLOCATOR),INTENT(IN) :: ALLOCATOR
LOGICAL,INTENT(IN),OPTIONAL :: LORDERED
INTEGER(KIND=JPIM) :: IN(GROUP%COUNT),IK(GROUP%COUNT),ILDB(GROUP%COUNT),IMAX_N,IMAX_K
INTEGER(KIND=JPIB) :: IOFFA(GROUP%COUNT),IOFFB(GROUP%COUNT),IOFFC(GROUP%COUNT)

IF (GROUP%COUNT <= 0) RETURN
IMAX_N=MAXVAL(GROUP%N)
IMAX_K=MAXVAL(GROUP%K)
IF (.NOT.PLAN%COMPACT_ID .OR. LFACTOR_TRANSPOSED) THEN
  IF (PRESENT(LORDERED)) THEN
    CALL RUN_GROUP(GROUP,PLAN,PA,PC,KLD,KADD_A,KADD_C,LREVERSE,&
      & LFACTOR_TRANSPOSED,PBETA,KSTREAM,KBLAS,ALLOCATOR,LORDERED)
  ELSE
    CALL RUN_GROUP(GROUP,PLAN,PA,PC,KLD,KADD_A,KADD_C,LREVERSE,&
      & LFACTOR_TRANSPOSED,PBETA,KSTREAM,KBLAS,ALLOCATOR)
  ENDIF
  RETURN
ENDIF

#ifdef CUDAGPU
ASSOCIATE(PFACTORS=>PLAN%FACTORS,PPIVOTS=>PLAN%PIVOTS,&
  & GN=>GROUP%N,GK=>GROUP%K,GS=>GROUP%SRC_COL,GD=>GROUP%DST_COL,&
  & GF=>GROUP%FACTOR_OFFSET,GP=>GROUP%PIVOT_OFFSET,GW=>GROUP%SCRATCH_OFFSET,&
  & GTG=>GROUP%TILE_GROUP,GTS=>GROUP%TILE_START)
ILDB=GROUP%N
IOFFB=GROUP%FACTOR_OFFSET
IF (LREVERSE) THEN
  IN=GROUP%K-GROUP%N
  IK=GROUP%N
  IOFFA=(GROUP%DST_COL+KADD_A)*KLD
  IOFFC=(KADD_SCRATCH+GROUP%SCRATCH_OFFSET)*KLD
ELSE
  IN=GROUP%N
  IK=GROUP%K-GROUP%N
  IOFFA=(KADD_SCRATCH+GROUP%SCRATCH_OFFSET)*KLD
  IOFFC=(GROUP%DST_COL+KADD_C)*KLD
ENDIF
#ifdef ACCGPU
!$ACC HOST_DATA USE_DEVICE(PA,PC,PFACTORS,PPIVOTS,GN,GK,GS,GD,GF,GP,GW,GTG,GTS)
#endif
#ifdef OMPGPU
!$OMP TARGET DATA USE_DEVICE_ADDR(PA,PC,PFACTORS,PPIVOTS,GN,GK,GS,GD,GF,GP,GW,GTG,GTS)
#endif
IF (LREVERSE .AND. PLAN%FUSE_REVERSE) THEN
  CALL BUTTERFLY_COMPACT_REVERSE_C(C_LOC(PA),C_LOC(PFACTORS),C_LOC(PC),&
    & INT(KLD,C_INT),GN,GK,GS,GD,GP,GF,PPIVOTS,INT(KADD_A,C_INT64_T),&
    & INT(KADD_C,C_INT64_T),INT(GROUP%COUNT,C_INT),INT(IMAX_K,C_INT),&
    & PBETA,KSTREAM)
ELSEIF (.NOT.LREVERSE .AND. PLAN%NATIVE_GROUPED) THEN
  CALL BUTTERFLY_COMPACT_PROJECTION_C(C_LOC(PA),C_LOC(PFACTORS),C_LOC(PC),&
    & INT(KLD,C_INT),GN,GK,GS,GD,GP,GF,PPIVOTS,INT(KADD_A,C_INT64_T),&
    & INT(KADD_C,C_INT64_T),INT(GROUP%COUNT,C_INT),INT(IMAX_N,C_INT),PBETA,KSTREAM)
ELSE
  IF (.NOT.LREVERSE) &
    & CALL BUTTERFLY_PROJECTION_C(C_LOC(PA),C_LOC(PC),INT(KLD,C_INT),GN,GK,GS,GD,&
    & GP,GW,GTG,GTS,PPIVOTS,INT(KADD_A,C_INT64_T),INT(KADD_C,C_INT64_T),&
    & INT(KADD_SCRATCH,C_INT64_T),INT(GROUP%TILE_COUNT,C_INT),0_C_INT,PBETA,KSTREAM)
  IF (GROUP%SCRATCH_COLS > 0 .AND. LREVERSE) THEN
    CALL HIP_DGEMM_GROUPED_ASYNC(NCUR_RESOL,KBLAS,'N','N',KLD,IN,IK,ONE,&
      & C_LOC(PA),KLD,IOFFA,C_LOC(PFACTORS),ILDB,IOFFB,ZERO,C_LOC(PC),KLD,&
      & IOFFC,GROUP%COUNT,KSTREAM,C_LOC(ALLOCATOR%PTR))
  ELSEIF (GROUP%SCRATCH_COLS > 0) THEN
    CALL HIP_DGEMM_GROUPED_ASYNC(NCUR_RESOL,KBLAS,'N','T',KLD,IN,IK,ONE,&
      & C_LOC(PC),KLD,IOFFA,C_LOC(PFACTORS),ILDB,IOFFB,ONE,C_LOC(PC),KLD,&
      & IOFFC,GROUP%COUNT,KSTREAM,C_LOC(ALLOCATOR%PTR))
  ENDIF
  IF (LREVERSE) &
    & CALL BUTTERFLY_PROJECTION_C(C_LOC(PA),C_LOC(PC),INT(KLD,C_INT),GN,GK,GS,GD,&
    & GP,GW,GTG,GTS,PPIVOTS,INT(KADD_A,C_INT64_T),INT(KADD_C,C_INT64_T),&
    & INT(KADD_SCRATCH,C_INT64_T),INT(GROUP%TILE_COUNT,C_INT),1_C_INT,PBETA,KSTREAM)
ENDIF
#ifdef OMPGPU
!$OMP END TARGET DATA
#endif
#ifdef ACCGPU
!$ACC END HOST_DATA
#endif
END ASSOCIATE
#else
IF (PRESENT(LORDERED)) THEN
  CALL RUN_GROUP(GROUP,PLAN,PA,PC,KLD,KADD_A,KADD_C,LREVERSE,&
    & LFACTOR_TRANSPOSED,PBETA,KSTREAM,KBLAS,ALLOCATOR,LORDERED)
ELSE
  CALL RUN_GROUP(GROUP,PLAN,PA,PC,KLD,KADD_A,KADD_C,LREVERSE,&
    & LFACTOR_TRANSPOSED,PBETA,KSTREAM,KBLAS,ALLOCATOR)
ENDIF
#endif
END SUBROUTINE RUN_PROJECTION

SUBROUTINE RUN_GROUP(GROUP,PLAN,PA,PC,KLD,KADD_A,KADD_C,LREVERSE,&
  & LFACTOR_TRANSPOSED,PBETA,KSTREAM,KBLAS,ALLOCATOR,LORDERED)
USE BUFFERED_ALLOCATOR_MOD, ONLY: BUFFERED_ALLOCATOR
USE HICBLAS_MOD, ONLY: HIP_DGEMM_GROUPED_ASYNC,HIP_SGEMM_GROUPED_ASYNC,&
  & HIP_DGEMM_GROUPED_ORDERED_ASYNC
USE TPM_GEN, ONLY: NCUR_RESOL
USE ISO_C_BINDING, ONLY: C_LOC,C_INT,C_INT64_T,C_INTPTR_T
TYPE(BUTTERFLY_GPU_GROUPS),INTENT(IN) :: GROUP
TYPE(BUTTERFLY_GPU_PLAN),INTENT(IN) :: PLAN
REAL(KIND=JPRBT),POINTER,INTENT(IN) :: PA(:)
REAL(KIND=JPRBT),POINTER,INTENT(INOUT) :: PC(:)
INTEGER(KIND=JPIM),INTENT(IN) :: KLD,KBLAS
INTEGER(KIND=JPIB),INTENT(IN) :: KADD_A,KADD_C
LOGICAL,INTENT(IN) :: LREVERSE,LFACTOR_TRANSPOSED
REAL(KIND=JPRBT),INTENT(IN) :: PBETA
INTEGER(C_INTPTR_T),INTENT(IN) :: KSTREAM
TYPE(BUFFERED_ALLOCATOR),INTENT(IN) :: ALLOCATOR
LOGICAL,INTENT(IN),OPTIONAL :: LORDERED
INTEGER(KIND=JPIM) :: IN(GROUP%COUNT),IK(GROUP%COUNT)
INTEGER(KIND=JPIB) :: IOFFA(GROUP%COUNT),IOFFC(GROUP%COUNT)
CHARACTER(LEN=1) :: CTB
LOGICAL :: LLORDERED

IF (GROUP%COUNT <= 0) RETURN
LLORDERED=.FALSE.
IF (PRESENT(LORDERED)) LLORDERED=LORDERED
#ifdef CUDAGPU
IF (PLAN%NATIVE_GROUPED .AND. .NOT.LREVERSE .AND. &
  & (.NOT.LLORDERED .OR. PBETA == ONE)) THEN
  ASSOCIATE(PFACTORS=>PLAN%FACTORS,GN=>GROUP%N,GK=>GROUP%K,&
    & GLDB=>GROUP%LDB,GS=>GROUP%SRC_COL,GD=>GROUP%DST_COL,&
    & GF=>GROUP%FACTOR_OFFSET)
#ifdef ACCGPU
  !$ACC HOST_DATA USE_DEVICE(PA,PFACTORS,PC,GN,GK,GLDB,GS,GD,GF)
#endif
#ifdef OMPGPU
  !$OMP TARGET DATA USE_DEVICE_ADDR(PA,PFACTORS,PC,GN,GK,GLDB,GS,GD,GF)
#endif
  CALL BUTTERFLY_GROUPED_GEMM_C(C_LOC(PA),C_LOC(PFACTORS),C_LOC(PC),&
    & INT(KLD,C_INT),GN,GK,GLDB,GS,GD,GF,INT(KADD_A,C_INT64_T),&
    & INT(KADD_C,C_INT64_T),INT(GROUP%COUNT,C_INT),&
    & INT(MAXVAL(GROUP%N),C_INT),MERGE(1_C_INT,0_C_INT,LFACTOR_TRANSPOSED),&
    & MERGE(1_C_INT,0_C_INT,LLORDERED),PBETA,KSTREAM)
#ifdef OMPGPU
  !$OMP END TARGET DATA
#endif
#ifdef ACCGPU
  !$ACC END HOST_DATA
#endif
  END ASSOCIATE
  RETURN
ENDIF
#endif
IF (LREVERSE) THEN
  IN=GROUP%K
  IK=GROUP%N
  IOFFA=(GROUP%DST_COL+KADD_A)*KLD
  IOFFC=(GROUP%SRC_COL+KADD_C)*KLD
  IF (LFACTOR_TRANSPOSED) THEN
    CTB='N'
  ELSE
    CTB='T'
  ENDIF
ELSE
  IN=GROUP%N
  IK=GROUP%K
  IOFFA=(GROUP%SRC_COL+KADD_A)*KLD
  IOFFC=(GROUP%DST_COL+KADD_C)*KLD
  IF (LFACTOR_TRANSPOSED) THEN
    CTB='T'
  ELSE
    CTB='N'
  ENDIF
ENDIF

ASSOCIATE(PFACTORS=>PLAN%FACTORS)
#ifdef OMPGPU
!$OMP TARGET DATA USE_DEVICE_ADDR(PA,PFACTORS,PC)
#endif
#ifdef ACCGPU
!$ACC HOST_DATA USE_DEVICE(PA,PFACTORS,PC)
#endif
#ifdef TRANS_SINGLE
CALL HIP_SGEMM_GROUPED_ASYNC(NCUR_RESOL,KBLAS,'N',CTB,KLD,IN,IK,ONE,&
  & C_LOC(PA),KLD,IOFFA,C_LOC(PFACTORS),GROUP%LDB,GROUP%FACTOR_OFFSET,PBETA,&
  & C_LOC(PC),KLD,IOFFC,GROUP%COUNT,KSTREAM,C_LOC(ALLOCATOR%PTR))
#else
IF (LLORDERED) THEN
  CALL HIP_DGEMM_GROUPED_ORDERED_ASYNC(NCUR_RESOL,KBLAS,'N',CTB,KLD,IN,IK,ONE,&
    & C_LOC(PA),KLD,IOFFA,C_LOC(PFACTORS),GROUP%LDB,GROUP%FACTOR_OFFSET,PBETA,&
    & C_LOC(PC),KLD,IOFFC,GROUP%COUNT,KSTREAM,C_LOC(ALLOCATOR%PTR))
ELSE
  CALL HIP_DGEMM_GROUPED_ASYNC(NCUR_RESOL,KBLAS,'N',CTB,KLD,IN,IK,ONE,&
    & C_LOC(PA),KLD,IOFFA,C_LOC(PFACTORS),GROUP%LDB,GROUP%FACTOR_OFFSET,PBETA,&
    & C_LOC(PC),KLD,IOFFC,GROUP%COUNT,KSTREAM,C_LOC(ALLOCATOR%PTR))
ENDIF
#endif
#ifdef ACCGPU
!$ACC END HOST_DATA
#endif
#ifdef OMPGPU
!$OMP END TARGET DATA
#endif
END ASSOCIATE
END SUBROUTINE RUN_GROUP

