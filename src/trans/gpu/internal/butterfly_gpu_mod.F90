SUBROUTINE BUILD_FUSED_FINAL(PLAN,KPOS)
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIB),INTENT(INOUT) :: KPOS

INTEGER(KIND=JPIM),ALLOCATABLE :: IORDER(:),ITEMP(:)
INTEGER(KIND=JPIM) :: IN,IWIDTH,ILEFT,IMID,IRIGHT,IOUT,I1,I2,I,ISTART,IEND
INTEGER(KIND=JPIM) :: IDX,IPREV,IGROUP,INOUT,IKTOTAL,JK
INTEGER(KIND=JPIB) :: ICOUNT,IGATHER,IPACK_COL,IGROUP_SRC,ISOURCE

IN=PLAN%FINAL%COUNT
IF (IN <= 0) RETURN
ALLOCATE(IORDER(IN),ITEMP(IN))
DO I=1,IN
  IORDER(I)=I
ENDDO

! Sort final factors by output range so equal destinations can share one GEMM.
IWIDTH=1
DO WHILE(IWIDTH < IN)
  DO ILEFT=1,IN,2*IWIDTH
    IMID=MIN(ILEFT+IWIDTH-1,IN)
    IRIGHT=MIN(ILEFT+2*IWIDTH-1,IN)
    I1=ILEFT
    I2=IMID+1
    DO IOUT=ILEFT,IRIGHT
      IF (I1 > IMID) THEN
        ITEMP(IOUT)=IORDER(I2)
        I2=I2+1
      ELSEIF (I2 > IRIGHT) THEN
        ITEMP(IOUT)=IORDER(I1)
        I1=I1+1
      ELSEIF (FINAL_GROUP_LESS(PLAN%FINAL,IORDER(I1),IORDER(I2))) THEN
        ITEMP(IOUT)=IORDER(I1)
        I1=I1+1
      ELSE
        ITEMP(IOUT)=IORDER(I2)
        I2=I2+1
      ENDIF
    ENDDO
  ENDDO
  IORDER=ITEMP
  IWIDTH=2*IWIDTH
ENDDO

IGROUP=1
IPREV=IORDER(1)
DO I=2,IN
  IDX=IORDER(I)
  IF (.NOT.FINAL_GROUP_SAME(PLAN%FINAL,IPREV,IDX)) IGROUP=IGROUP+1
  IPREV=IDX
ENDDO
PLAN%FINAL_FUSED%COUNT=IGROUP
PLAN%FINAL_ORIGINAL_COST=SUM(INT(PLAN%FINAL%N,JPIB)*INT(PLAN%FINAL%K,JPIB))
PLAN%FINAL_EXEC_COST=PLAN%FINAL_ORIGINAL_COST
PLAN%FINAL_DIRECT_GROUPS=IGROUP
IF (.NOT.PLAN%RECOMPRESS_FINAL .AND. IGROUP == IN) THEN
  PLAN%FUSE_FINAL=.FALSE.
  PLAN%FINAL_FUSED%COUNT=0
  DEALLOCATE(IORDER,ITEMP)
  RETURN
ENDIF
IF (PLAN%RECOMPRESS_FINAL) THEN
  CALL BUILD_RECOMPRESSED_FINAL(PLAN,KPOS,IORDER,IGROUP)
  DEALLOCATE(IORDER,ITEMP)
  RETURN
ENDIF
CALL ALLOC_GROUP(PLAN%FINAL_FUSED)
PLAN%FINAL_GATHER_COUNT=SUM(INT(PLAN%FINAL%K,JPIB))
ALLOCATE(PLAN%FINAL_GATHER_SRC(PLAN%FINAL_GATHER_COUNT),&
  & PLAN%FINAL_GATHER_DST(PLAN%FINAL_GATHER_COUNT))

I=1
IGROUP=0
IGATHER=0
IPACK_COL=0
DO WHILE(I <= IN)
  ISTART=I
  IDX=IORDER(I)
  INOUT=PLAN%FINAL%N(IDX)
  IKTOTAL=0
  DO WHILE(I <= IN)
    IF (.NOT.FINAL_GROUP_SAME(PLAN%FINAL,IORDER(ISTART),IORDER(I))) EXIT
    IKTOTAL=IKTOTAL+PLAN%FINAL%K(IORDER(I))
    I=I+1
  ENDDO
  IEND=I-1
  IGROUP=IGROUP+1
  IGROUP_SRC=IPACK_COL
  CALL SET_GROUP(PLAN%FINAL_FUSED,IGROUP,INOUT,IKTOTAL,INOUT,&
    & IGROUP_SRC,PLAN%FINAL%DST_COL(IDX),KPOS-1)
  DO IOUT=ISTART,IEND
    IDX=IORDER(IOUT)
    ICOUNT=INT(INOUT,JPIB)*INT(PLAN%FINAL%K(IDX),JPIB)
    ISOURCE=PLAN%FINAL%FACTOR_OFFSET(IDX)+1
    PLAN%FACTORS(KPOS:KPOS+ICOUNT-1)=&
      & PLAN%FACTORS(ISOURCE:ISOURCE+ICOUNT-1)
    KPOS=KPOS+ICOUNT
    DO JK=0,PLAN%FINAL%K(IDX)-1
      IGATHER=IGATHER+1
      PLAN%FINAL_GATHER_SRC(IGATHER)=PLAN%FINAL%SRC_COL(IDX)+JK
      PLAN%FINAL_GATHER_DST(IGATHER)=IPACK_COL
      IPACK_COL=IPACK_COL+1
    ENDDO
  ENDDO
ENDDO
DEALLOCATE(IORDER,ITEMP)
END SUBROUTINE BUILD_FUSED_FINAL

SUBROUTINE BUILD_RECOMPRESSED_FINAL(PLAN,KPOS,KORDER,KGROUPS)
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIB),INTENT(INOUT) :: KPOS
INTEGER(KIND=JPIM),INTENT(IN) :: KORDER(:),KGROUPS

INTEGER(KIND=JPIM) :: I,ISTART,IEND,IDX,INOUT,IKTOTAL,IRANK
INTEGER(KIND=JPIM) :: J,JK,JI,IC,IGROUP,IPROJECT,IBASIS,IDIRECT
INTEGER(KIND=JPIM),ALLOCATABLE :: ICLIST(:)
INTEGER(KIND=JPIB) :: IGATHER,IPACK_COL,IGAMMA_COL,ISOURCE,ICOUNT
INTEGER(KIND=JPIB) :: IORIGINAL_COST,IRECOMPRESSED_COST,IOFF
REAL(KIND=JPRD) :: ZEPS,ZSELECT_RATIO
REAL(KIND=JPRD),ALLOCATABLE :: ZB(:,:),ZPNONIM(:,:),ZPROJ(:,:)
LOGICAL :: LSELECT

PLAN%FINAL_FUSED%COUNT=KGROUPS
PLAN%FINAL_PROJECT%COUNT=KGROUPS
PLAN%FINAL_BASIS%COUNT=KGROUPS
CALL ALLOC_GROUP(PLAN%FINAL_FUSED)
CALL ALLOC_GROUP(PLAN%FINAL_PROJECT)
CALL ALLOC_GROUP(PLAN%FINAL_BASIS)
PLAN%FINAL_GATHER_COUNT=SUM(INT(PLAN%FINAL%K,JPIB))
ALLOCATE(PLAN%FINAL_GATHER_SRC(PLAN%FINAL_GATHER_COUNT),&
  & PLAN%FINAL_GATHER_DST(PLAN%FINAL_GATHER_COUNT))

ZEPS=BUTTERFLY_FINAL_EPS()
ZSELECT_RATIO=BUTTERFLY_FINAL_SELECT_RATIO()
I=1
IGROUP=0
IPROJECT=0
IBASIS=0
IDIRECT=0
IGATHER=0
IPACK_COL=0
IGAMMA_COL=0
PLAN%FINAL_EXEC_COST=0
PLAN%FINAL_RECOMPRESSED_GROUPS=0
PLAN%FINAL_DIRECT_GROUPS=0
DO WHILE(I <= SIZE(KORDER))
  ISTART=I
  IDX=KORDER(I)
  INOUT=PLAN%FINAL%N(IDX)
  IKTOTAL=0
  DO WHILE(I <= SIZE(KORDER))
    IF (.NOT.FINAL_GROUP_SAME(PLAN%FINAL,KORDER(ISTART),KORDER(I))) EXIT
    IKTOTAL=IKTOTAL+PLAN%FINAL%K(KORDER(I))
    I=I+1
  ENDDO
  IEND=I-1
  IGROUP=IGROUP+1
  ALLOCATE(ZB(INOUT,IKTOTAL),ICLIST(IKTOTAL),&
    & ZPNONIM(MAX(1,MIN(INOUT,IKTOTAL)),MAX(1,IKTOTAL)))
  J=0
  DO JI=ISTART,IEND
    IDX=KORDER(JI)
    ISOURCE=PLAN%FINAL%FACTOR_OFFSET(IDX)+1
    DO JK=1,PLAN%FINAL%K(IDX)
      J=J+1
      ZB(:,J)=REAL(PLAN%FACTORS(ISOURCE+(JK-1)*INOUT:&
        & ISOURCE+JK*INOUT-1),JPRD)
      IGATHER=IGATHER+1
      PLAN%FINAL_GATHER_SRC(IGATHER)=PLAN%FINAL%SRC_COL(IDX)+JK-1
      PLAN%FINAL_GATHER_DST(IGATHER)=IPACK_COL
      IPACK_COL=IPACK_COL+1
    ENDDO
  ENDDO

  CALL COMPUTE_ID(ZEPS,INOUT,IKTOTAL,ZB,IRANK,ICLIST,ZPNONIM)
  IORIGINAL_COST=INT(INOUT,JPIB)*INT(IKTOTAL,JPIB)
  IRECOMPRESSED_COST=INT(IRANK,JPIB)*INT(INOUT+IKTOTAL,JPIB)
  LSELECT=IRANK < MIN(INOUT,IKTOTAL) .AND. &
    & REAL(IRECOMPRESSED_COST,JPRD) < ZSELECT_RATIO*REAL(IORIGINAL_COST,JPRD)
  IF (LSELECT) THEN
    ALLOCATE(ZPROJ(IKTOTAL,IRANK))
    ZPROJ=0.0_JPRD
    DO JI=1,IKTOTAL
      IC=ICLIST(JI)
      IF (JI <= IRANK) THEN
        ZPROJ(IC,JI)=1.0_JPRD
      ELSE
        ZPROJ(IC,1:IRANK)=ZPNONIM(1:IRANK,JI-IRANK)
      ENDIF
    ENDDO
    IOFF=KPOS-1
    ICOUNT=INT(IKTOTAL,JPIB)*INT(IRANK,JPIB)
    PLAN%FACTORS(KPOS:KPOS+ICOUNT-1)=&
      & RESHAPE(REAL(ZPROJ,JPRBT),[ICOUNT])
    KPOS=KPOS+ICOUNT
    IPROJECT=IPROJECT+1
    CALL SET_GROUP(PLAN%FINAL_PROJECT,IPROJECT,IRANK,IKTOTAL,IKTOTAL,&
      & IPACK_COL-IKTOTAL,IGAMMA_COL,IOFF)

    IOFF=KPOS-1
    ICOUNT=INT(INOUT,JPIB)*INT(IRANK,JPIB)
    PLAN%FACTORS(KPOS:KPOS+ICOUNT-1)=&
      & RESHAPE(REAL(ZB(:,ICLIST(1:IRANK)),JPRBT),[ICOUNT])
    KPOS=KPOS+ICOUNT
    IBASIS=IBASIS+1
    CALL SET_GROUP(PLAN%FINAL_BASIS,IBASIS,INOUT,IRANK,INOUT,&
      & IGAMMA_COL,PLAN%FINAL%DST_COL(IDX),IOFF)
    IGAMMA_COL=IGAMMA_COL+IRANK
    PLAN%FINAL_EXEC_COST=PLAN%FINAL_EXEC_COST+IRECOMPRESSED_COST
    PLAN%FINAL_RECOMPRESSED_GROUPS=PLAN%FINAL_RECOMPRESSED_GROUPS+1
    DEALLOCATE(ZPROJ)
  ELSE
    IOFF=KPOS-1
    PLAN%FACTORS(KPOS:KPOS+IORIGINAL_COST-1)=&
      & RESHAPE(REAL(ZB,JPRBT),[IORIGINAL_COST])
    KPOS=KPOS+IORIGINAL_COST
    IDIRECT=IDIRECT+1
    CALL SET_GROUP(PLAN%FINAL_FUSED,IDIRECT,INOUT,IKTOTAL,INOUT,&
      & IPACK_COL-IKTOTAL,PLAN%FINAL%DST_COL(IDX),IOFF)
    PLAN%FINAL_EXEC_COST=PLAN%FINAL_EXEC_COST+IORIGINAL_COST
    PLAN%FINAL_DIRECT_GROUPS=PLAN%FINAL_DIRECT_GROUPS+1
  ENDIF
  DEALLOCATE(ZB,ICLIST,ZPNONIM)
ENDDO
PLAN%FINAL_PROJECT%COUNT=IPROJECT
PLAN%FINAL_BASIS%COUNT=IBASIS
PLAN%FINAL_FUSED%COUNT=IDIRECT
IF (IPROJECT == 0 .AND. IDIRECT == PLAN%FINAL%COUNT) THEN
  PLAN%FUSE_FINAL=.FALSE.
  PLAN%RECOMPRESS_FINAL=.FALSE.
ENDIF
END SUBROUTINE BUILD_RECOMPRESSED_FINAL

LOGICAL FUNCTION FINAL_GROUP_LESS(GROUP,KI,KJ)
TYPE(BUTTERFLY_GPU_GROUPS),INTENT(IN) :: GROUP
INTEGER(KIND=JPIM),INTENT(IN) :: KI,KJ
FINAL_GROUP_LESS=GROUP%DST_COL(KI) < GROUP%DST_COL(KJ) .OR. &
  & (GROUP%DST_COL(KI) == GROUP%DST_COL(KJ) .AND. &
  & GROUP%N(KI) <= GROUP%N(KJ))
END FUNCTION FINAL_GROUP_LESS

LOGICAL FUNCTION FINAL_GROUP_SAME(GROUP,KI,KJ)
TYPE(BUTTERFLY_GPU_GROUPS),INTENT(IN) :: GROUP
INTEGER(KIND=JPIM),INTENT(IN) :: KI,KJ
FINAL_GROUP_SAME=GROUP%DST_COL(KI) == GROUP%DST_COL(KJ) .AND. &
  & GROUP%N(KI) == GROUP%N(KJ)
END FUNCTION FINAL_GROUP_SAME

SUBROUTINE FILL_HYBRID(HYBRID,KMLOC,PLAN,KPOS,KPIVOT_POS,K0,KFINAL,KDENSE,&
  & KFUSED,KFW,KRO,KRE,LTRANSPOSED)
TYPE(HYBRID_MATRIX),INTENT(IN) :: HYBRID
INTEGER(KIND=JPIM),INTENT(IN) :: KMLOC
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIB),INTENT(INOUT) :: KPOS,KPIVOT_POS
INTEGER(KIND=JPIM),INTENT(INOUT) :: K0,KFINAL,KDENSE,KFUSED,KFW(:),KRO(:),KRE(:)
LOGICAL,INTENT(IN) :: LTRANSPOSED
INTEGER(KIND=JPIM) :: JB

DO JB=1,HYBRID%BLOCK_COUNT
  IF (HYBRID%BLOCKS(JB)%KIND == HYBRID_DENSE) THEN
    CALL FILL_DENSE(HYBRID%BLOCKS(JB),KMLOC,PLAN,KPOS,KDENSE,LTRANSPOSED)
  ELSEIF (FUSIBLE_LEAF(PLAN,HYBRID%BLOCKS(JB)%BUT)) THEN
    CALL FILL_FUSED_LEAF(HYBRID%BLOCKS(JB),KMLOC,PLAN,KPOS,KPIVOT_POS,KFUSED)
  ELSE
    CALL FILL_MATRIX(HYBRID%BLOCKS(JB)%BUT,KMLOC,&
      & HYBRID%BLOCKS(JB)%FIRST_ROW,HYBRID%BLOCKS(JB)%FIRST_COL,&
      & HYBRID%BLOCKS(JB)%WORK_BASE,PLAN,KPOS,KPIVOT_POS,K0,KFINAL,KFW,KRO,KRE,&
      & LTRANSPOSED)
  ENDIF
ENDDO
END SUBROUTINE FILL_HYBRID

SUBROUTINE FILL_FUSED_LEAF(BLOCK,KMLOC,PLAN,KPOS,KPIVOT_POS,KFUSED)
USE TPM_DISTR, ONLY: D
TYPE(HYBRID_BLOCK),INTENT(IN) :: BLOCK
INTEGER(KIND=JPIM),INTENT(IN) :: KMLOC
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIB),INTENT(INOUT) :: KPOS,KPIVOT_POS
INTEGER(KIND=JPIM),INTENT(INOUT) :: KFUSED
INTEGER(KIND=JPIM) :: JK
INTEGER(KIND=JPIB) :: IPROJECTION,IPIVOT,IFINAL,ICOUNT
TYPE(NODE_TYPE),POINTER :: YNODE

DO JK=1,BLOCK%BUT%SLEV(0)%IK
  YNODE=>BLOCK%BUT%SLEV(0)%NODE(1,JK)
  CALL PACK_PLAN_PROJECTION(YNODE,PLAN,KPOS,KPIVOT_POS,IPROJECTION,IPIVOT)
  IFINAL=KPOS-1
  ICOUNT=INT(YNODE%IROWS,JPIB)*INT(YNODE%IRANK,JPIB)
  PLAN%FACTORS(KPOS:KPOS+ICOUNT-1)=RESHAPE(REAL(YNODE%B,JPRBT),[ICOUNT])
  KPOS=KPOS+ICOUNT
  KFUSED=KFUSED+1
  PLAN%FUSED_LEAF%ROWS(KFUSED)=YNODE%IROWS
  PLAN%FUSED_LEAF%RANKS(KFUSED)=YNODE%IRANK
  PLAN%FUSED_LEAF%COLUMNS(KFUSED)=YNODE%ICOLS
  PLAN%FUSED_LEAF%INPUT_COL(KFUSED)=D%OFFSETS_GEMM1(KMLOC)+&
    & BLOCK%FIRST_COL+YNODE%IFCOL-2
  PLAN%FUSED_LEAF%OUTPUT_COL(KFUSED)=D%OFFSETS_GEMM2(KMLOC)+&
    & BLOCK%FIRST_ROW+YNODE%IFROW-2
  PLAN%FUSED_LEAF%FINAL_FACTOR_OFFSET(KFUSED)=IFINAL
  PLAN%FUSED_LEAF%PROJECTION_FACTOR_OFFSET(KFUSED)=IPROJECTION
  PLAN%FUSED_LEAF%PIVOT_OFFSET(KFUSED)=IPIVOT
ENDDO
END SUBROUTINE FILL_FUSED_LEAF

SUBROUTINE FILL_DENSE(BLOCK,KMLOC,PLAN,KPOS,KDENSE,LTRANSPOSED)
USE TPM_DISTR, ONLY: D
TYPE(HYBRID_BLOCK),INTENT(IN) :: BLOCK
INTEGER(KIND=JPIM),INTENT(IN) :: KMLOC
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIB),INTENT(INOUT) :: KPOS
INTEGER(KIND=JPIM),INTENT(INOUT) :: KDENSE
LOGICAL,INTENT(IN) :: LTRANSPOSED
INTEGER(KIND=JPIB) :: IOFF
REAL(KIND=JPRBT),ALLOCATABLE :: ZT(:,:)

ALLOCATE(ZT(BLOCK%NCOLS,BLOCK%NROWS))
ZT=TRANSPOSE(BLOCK%DENSE)
IOFF=KPOS-1
PLAN%FACTORS(KPOS:KPOS+BLOCK%DENSE_COST-1)=RESHAPE(ZT,[BLOCK%DENSE_COST])
KPOS=KPOS+BLOCK%DENSE_COST
KDENSE=KDENSE+1
IF (LTRANSPOSED) THEN
  CALL SET_GROUP(PLAN%DENSE,KDENSE,BLOCK%NROWS,BLOCK%NCOLS,BLOCK%NCOLS,&
    & D%OFFSETS_GEMM1(KMLOC)+BLOCK%FIRST_COL-1,&
    & D%OFFSETS_GEMM2(KMLOC)+BLOCK%FIRST_ROW-1,IOFF)
ELSE
  CALL SET_GROUP(PLAN%DENSE,KDENSE,BLOCK%NROWS,BLOCK%NCOLS,BLOCK%NCOLS,&
    & D%OFFSETS_GEMM2(KMLOC)+BLOCK%FIRST_COL-1,&
    & D%OFFSETS_GEMM1(KMLOC)+BLOCK%FIRST_ROW-1,IOFF)
ENDIF
DEALLOCATE(ZT)
END SUBROUTINE FILL_DENSE

SUBROUTINE FILL_MATRIX(BUT,KMLOC,KFIRST_ROW,KFIRST_COL,KWORK_BASE,&
  & PLAN,KPOS,KPIVOT_POS,K0,KFINAL,KFW,KRO,KRE,LTRANSPOSED)
USE TPM_DISTR, ONLY: D
TYPE(BUTTERFLY_STRUCT),INTENT(IN) :: BUT
INTEGER(KIND=JPIM),INTENT(IN) :: KMLOC,KFIRST_ROW,KFIRST_COL
INTEGER(KIND=JPIB),INTENT(IN) :: KWORK_BASE
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIB),INTENT(INOUT) :: KPOS,KPIVOT_POS
INTEGER(KIND=JPIM),INTENT(INOUT) :: K0,KFINAL,KFW(:),KRO(:),KRE(:)
LOGICAL,INTENT(IN) :: LTRANSPOSED
INTEGER(KIND=JPIM) :: JL,JJ,JK,IRANKL,IRANKR
INTEGER(KIND=JPIB) :: IOFF,IPIVOT_OFF,ISRC,IDST
TYPE(NODE_TYPE),POINTER :: YNODE,YLEFT,YRIGHT

DO JK=1,BUT%SLEV(0)%IK
  YNODE=>BUT%SLEV(0)%NODE(1,JK)
  CALL PACK_PLAN_PROJECTION(YNODE,PLAN,KPOS,KPIVOT_POS,IOFF,IPIVOT_OFF)
  K0=K0+1
  IF (LTRANSPOSED) THEN
    ISRC=D%OFFSETS_GEMM1(KMLOC)+KFIRST_COL+YNODE%IFCOL-2
  ELSE
    ISRC=D%OFFSETS_GEMM2(KMLOC)+KFIRST_COL+YNODE%IFCOL-2
  ENDIF
  IDST=KWORK_BASE+YNODE%IOFFBETA
  CALL SET_GROUP(PLAN%LEVEL0,K0,YNODE%IRANK,YNODE%ICOLS,YNODE%ICOLS,&
    & ISRC,IDST,IOFF,IPIVOT_OFF)
ENDDO

DO JL=1,BUT%N_LEVELS
  DO JK=1,BUT%SLEV(JL)%IK
    DO JJ=1,BUT%SLEV(JL)%IJ
      YNODE=>BUT%SLEV(JL)%NODE(JJ,JK)
      YLEFT=>BUT%SLEV(JL-1)%NODE((JJ+1)/2,2*JK-1)
      IRANKL=YLEFT%IRANK
      IRANKR=0
      IF (2*JK <= BUT%SLEV(JL-1)%IK) THEN
        YRIGHT=>BUT%SLEV(JL-1)%NODE((JJ+1)/2,2*JK)
        IRANKR=YRIGHT%IRANK
      ENDIF
      CALL PACK_PLAN_PROJECTION(YNODE,PLAN,KPOS,KPIVOT_POS,IOFF,IPIVOT_OFF)
      ISRC=KWORK_BASE+YLEFT%IOFFBETA
      IDST=KWORK_BASE+YNODE%IOFFBETA
      KFW(JL)=KFW(JL)+1
      CALL SET_GROUP(PLAN%LEVEL(JL)%FWD,KFW(JL),YNODE%IRANK,IRANKL+IRANKR,&
        & IRANKL+IRANKR,ISRC,IDST,IOFF,IPIVOT_OFF)
      IF (MOD(JJ,2) == 1) THEN
        KRO(JL)=KRO(JL)+1
        CALL SET_GROUP(PLAN%LEVEL(JL)%REV_ODD,KRO(JL),YNODE%IRANK,&
          & IRANKL+IRANKR,IRANKL+IRANKR,ISRC,IDST,IOFF,IPIVOT_OFF)
      ELSE
        KRE(JL)=KRE(JL)+1
        CALL SET_GROUP(PLAN%LEVEL(JL)%REV_EVEN,KRE(JL),YNODE%IRANK,&
          & IRANKL+IRANKR,IRANKL+IRANKR,ISRC,IDST,IOFF,IPIVOT_OFF)
      ENDIF
    ENDDO
  ENDDO
ENDDO

JL=BUT%N_LEVELS
DO JK=1,BUT%SLEV(JL)%IK
  DO JJ=1,BUT%SLEV(JL)%IJ
    YNODE=>BUT%SLEV(JL)%NODE(JJ,JK)
    IOFF=KPOS-1
    PLAN%FACTORS(KPOS:KPOS+INT(YNODE%IROWS,JPIB)*YNODE%IRANK-1)=&
      & RESHAPE(REAL(YNODE%B,JPRBT),[YNODE%IROWS*YNODE%IRANK])
    KPOS=KPOS+INT(YNODE%IROWS,JPIB)*YNODE%IRANK
    KFINAL=KFINAL+1
    IF (LTRANSPOSED) THEN
      CALL SET_GROUP(PLAN%FINAL,KFINAL,YNODE%IROWS,YNODE%IRANK,YNODE%IROWS,&
        & KWORK_BASE+YNODE%IOFFBETA,&
        & D%OFFSETS_GEMM2(KMLOC)+KFIRST_ROW+YNODE%IFROW-2,IOFF)
    ELSE
      CALL SET_GROUP(PLAN%FINAL,KFINAL,YNODE%IROWS,YNODE%IRANK,YNODE%IROWS,&
        & KWORK_BASE+YNODE%IOFFBETA,&
        & D%OFFSETS_GEMM1(KMLOC)+KFIRST_ROW+YNODE%IFROW-2,IOFF)
    ENDIF
  ENDDO
ENDDO
END SUBROUTINE FILL_MATRIX

SUBROUTINE PACK_PLAN_PROJECTION(NODE,PLAN,KPOS,KPIVOT_POS,KOFFSET,KPIVOT_OFFSET)
TYPE(NODE_TYPE),INTENT(IN) :: NODE
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIB),INTENT(INOUT) :: KPOS,KPIVOT_POS
INTEGER(KIND=JPIB),INTENT(OUT) :: KOFFSET,KPIVOT_OFFSET
INTEGER(KIND=JPIB) :: ICOUNT

IF (.NOT.PLAN%COMPACT_ID) THEN
  CALL PACK_PROJECTION(NODE,PLAN%FACTORS,KPOS,KOFFSET)
  KPIVOT_OFFSET=-1_JPIB
  RETURN
ENDIF

KOFFSET=KPOS-1
ICOUNT=INT(NODE%IRANK,JPIB)*INT(NODE%ICOLS-NODE%IRANK,JPIB)
IF (ICOUNT > 0) THEN
  PLAN%FACTORS(KPOS:KPOS+ICOUNT-1)=NODE%PNONIM(1:ICOUNT)
  KPOS=KPOS+ICOUNT
ENDIF
KPIVOT_OFFSET=KPIVOT_POS-1
PLAN%PIVOTS(KPIVOT_POS:KPIVOT_POS+NODE%ICOLS-1)=NODE%ICLIST-1
KPIVOT_POS=KPIVOT_POS+NODE%ICOLS
END SUBROUTINE PACK_PLAN_PROJECTION

SUBROUTINE PACK_PROJECTION(NODE,PFACTORS,KPOS,KOFFSET)
TYPE(NODE_TYPE),INTENT(IN) :: NODE
REAL(KIND=JPRBT),INTENT(INOUT) :: PFACTORS(:)
INTEGER(KIND=JPIB),INTENT(INOUT) :: KPOS
INTEGER(KIND=JPIB),INTENT(OUT) :: KOFFSET
REAL(KIND=JPRBT),ALLOCATABLE :: ZT(:,:)
INTEGER(KIND=JPIM) :: JI,JR,IC

ALLOCATE(ZT(NODE%ICOLS,NODE%IRANK))
ZT=ZERO
DO JI=1,NODE%ICOLS
  IC=NODE%ICLIST(JI)
  IF (JI <= NODE%IRANK) THEN
    ZT(IC,JI)=ONE
  ELSE
    DO JR=1,NODE%IRANK
      ZT(IC,JR)=NODE%PNONIM((JI-NODE%IRANK-1)*NODE%IRANK+JR)
    ENDDO
  ENDIF
ENDDO
KOFFSET=KPOS-1
PFACTORS(KPOS:KPOS+INT(NODE%ICOLS,JPIB)*NODE%IRANK-1)=&
  & RESHAPE(ZT,[NODE%ICOLS*NODE%IRANK])
KPOS=KPOS+INT(NODE%ICOLS,JPIB)*NODE%IRANK
DEALLOCATE(ZT)
END SUBROUTINE PACK_PROJECTION

