SUBROUTINE RUN_PROJECTION(GROUP,PLAN,PA,PC,KLD,KADD_A,KADD_C,LREVERSE,&
  & LFACTOR_TRANSPOSED,PBETA,KSTREAM,KBLAS,ALLOCATOR,LORDERED)
USE BUFFERED_ALLOCATOR_MOD, ONLY: BUFFERED_ALLOCATOR
USE ISO_C_BINDING, ONLY: C_LOC,C_INT,C_INT64_T,C_INTPTR_T
TYPE(BUTTERFLY_GPU_GROUPS),INTENT(IN) :: GROUP
TYPE(BUTTERFLY_GPU_PLAN),INTENT(IN) :: PLAN
REAL(KIND=JPRBT),POINTER,INTENT(IN) :: PA(:)
REAL(KIND=JPRBT),POINTER,INTENT(INOUT) :: PC(:)
INTEGER(KIND=JPIM),INTENT(IN) :: KLD,KBLAS
INTEGER(KIND=JPIB),INTENT(IN) :: KADD_A,KADD_C
LOGICAL,INTENT(IN) :: LREVERSE,LFACTOR_TRANSPOSED
REAL(KIND=JPRBT),INTENT(IN) :: PBETA
INTEGER(C_INTPTR_T),INTENT(IN) :: KSTREAM
TYPE(BUFFERED_ALLOCATOR),INTENT(IN) :: ALLOCATOR
LOGICAL,INTENT(IN),OPTIONAL :: LORDERED

IF (GROUP%COUNT <= 0) RETURN
IF (.NOT.PLAN%COMPACT_ID .OR. LFACTOR_TRANSPOSED) THEN
  IF (PRESENT(LORDERED)) THEN
    CALL RUN_GROUP(GROUP,PLAN,PA,PC,KLD,KADD_A,KADD_C,LREVERSE,&
      & LFACTOR_TRANSPOSED,PBETA,KSTREAM,KBLAS,ALLOCATOR,LORDERED)
  ELSE
    CALL RUN_GROUP(GROUP,PLAN,PA,PC,KLD,KADD_A,KADD_C,LREVERSE,&
      & LFACTOR_TRANSPOSED,PBETA,KSTREAM,KBLAS,ALLOCATOR)
  ENDIF
  RETURN
ENDIF

#ifdef CUDAGPU
ASSOCIATE(PFACTORS=>PLAN%FACTORS,PPIVOTS=>PLAN%PIVOTS,&
  & GN=>GROUP%N,GK=>GROUP%K,GS=>GROUP%SRC_COL,GD=>GROUP%DST_COL,&
  & GF=>GROUP%FACTOR_OFFSET,GP=>GROUP%PIVOT_OFFSET,&
  & GTG=>GROUP%TILE_GROUP,GTS=>GROUP%TILE_START)
#ifdef ACCGPU
!$ACC HOST_DATA USE_DEVICE(PA,PC,PFACTORS,PPIVOTS,GN,GK,GS,GD,GF,GP,GTG,GTS)
#endif
#ifdef OMPGPU
!$OMP TARGET DATA USE_DEVICE_ADDR(PA,PC,PFACTORS,PPIVOTS,GN,GK,GS,GD,GF,GP,GTG,GTS)
#endif
CALL BUTTERFLY_PROJECTION_C(C_LOC(PA),C_LOC(PC),INT(KLD,C_INT),GN,GK,GS,GD,&
  & GF,GP,GTG,GTS,PPIVOTS,C_LOC(PFACTORS),INT(KADD_A,C_INT64_T),&
  & INT(KADD_C,C_INT64_T),INT(GROUP%TILE_COUNT,C_INT),&
  & MERGE(1_C_INT,0_C_INT,LREVERSE),PBETA,KSTREAM)
#ifdef OMPGPU
!$OMP END TARGET DATA
#endif
#ifdef ACCGPU
!$ACC END HOST_DATA
#endif
END ASSOCIATE
#else
IF (PRESENT(LORDERED)) THEN
  CALL RUN_GROUP(GROUP,PLAN,PA,PC,KLD,KADD_A,KADD_C,LREVERSE,&
    & LFACTOR_TRANSPOSED,PBETA,KSTREAM,KBLAS,ALLOCATOR,LORDERED)
ELSE
  CALL RUN_GROUP(GROUP,PLAN,PA,PC,KLD,KADD_A,KADD_C,LREVERSE,&
    & LFACTOR_TRANSPOSED,PBETA,KSTREAM,KBLAS,ALLOCATOR)
ENDIF
#endif
END SUBROUTINE RUN_PROJECTION

SUBROUTINE RUN_GROUP(GROUP,PLAN,PA,PC,KLD,KADD_A,KADD_C,LREVERSE,&
  & LFACTOR_TRANSPOSED,PBETA,KSTREAM,KBLAS,ALLOCATOR,LORDERED)
USE BUFFERED_ALLOCATOR_MOD, ONLY: BUFFERED_ALLOCATOR
USE HICBLAS_MOD, ONLY: HIP_DGEMM_GROUPED_ASYNC,HIP_SGEMM_GROUPED_ASYNC,&
  & HIP_DGEMM_GROUPED_ORDERED_ASYNC
USE TPM_GEN, ONLY: NCUR_RESOL
USE ISO_C_BINDING, ONLY: C_LOC,C_INTPTR_T
TYPE(BUTTERFLY_GPU_GROUPS),INTENT(IN) :: GROUP
TYPE(BUTTERFLY_GPU_PLAN),INTENT(IN) :: PLAN
REAL(KIND=JPRBT),POINTER,INTENT(IN) :: PA(:)
REAL(KIND=JPRBT),POINTER,INTENT(INOUT) :: PC(:)
INTEGER(KIND=JPIM),INTENT(IN) :: KLD,KBLAS
INTEGER(KIND=JPIB),INTENT(IN) :: KADD_A,KADD_C
LOGICAL,INTENT(IN) :: LREVERSE,LFACTOR_TRANSPOSED
REAL(KIND=JPRBT),INTENT(IN) :: PBETA
INTEGER(C_INTPTR_T),INTENT(IN) :: KSTREAM
TYPE(BUFFERED_ALLOCATOR),INTENT(IN) :: ALLOCATOR
LOGICAL,INTENT(IN),OPTIONAL :: LORDERED
INTEGER(KIND=JPIM) :: IN(GROUP%COUNT),IK(GROUP%COUNT)
INTEGER(KIND=JPIB) :: IOFFA(GROUP%COUNT),IOFFC(GROUP%COUNT)
CHARACTER(LEN=1) :: CTB
LOGICAL :: LLORDERED

IF (GROUP%COUNT <= 0) RETURN
LLORDERED=.FALSE.
IF (PRESENT(LORDERED)) LLORDERED=LORDERED
IF (LREVERSE) THEN
  IN=GROUP%K
  IK=GROUP%N
  IOFFA=(GROUP%DST_COL+KADD_A)*KLD
  IOFFC=(GROUP%SRC_COL+KADD_C)*KLD
  IF (LFACTOR_TRANSPOSED) THEN
    CTB='N'
  ELSE
    CTB='T'
  ENDIF
ELSE
  IN=GROUP%N
  IK=GROUP%K
  IOFFA=(GROUP%SRC_COL+KADD_A)*KLD
  IOFFC=(GROUP%DST_COL+KADD_C)*KLD
  IF (LFACTOR_TRANSPOSED) THEN
    CTB='T'
  ELSE
    CTB='N'
  ENDIF
ENDIF

ASSOCIATE(PFACTORS=>PLAN%FACTORS)
#ifdef OMPGPU
!$OMP TARGET DATA USE_DEVICE_ADDR(PA,PFACTORS,PC)
#endif
#ifdef ACCGPU
!$ACC HOST_DATA USE_DEVICE(PA,PFACTORS,PC)
#endif
#ifdef TRANS_SINGLE
CALL HIP_SGEMM_GROUPED_ASYNC(NCUR_RESOL,KBLAS,'N',CTB,KLD,IN,IK,ONE,&
  & C_LOC(PA),KLD,IOFFA,C_LOC(PFACTORS),GROUP%LDB,GROUP%FACTOR_OFFSET,PBETA,&
  & C_LOC(PC),KLD,IOFFC,GROUP%COUNT,KSTREAM,C_LOC(ALLOCATOR%PTR))
#else
IF (LLORDERED) THEN
  CALL HIP_DGEMM_GROUPED_ORDERED_ASYNC(NCUR_RESOL,KBLAS,'N',CTB,KLD,IN,IK,ONE,&
    & C_LOC(PA),KLD,IOFFA,C_LOC(PFACTORS),GROUP%LDB,GROUP%FACTOR_OFFSET,PBETA,&
    & C_LOC(PC),KLD,IOFFC,GROUP%COUNT,KSTREAM,C_LOC(ALLOCATOR%PTR))
ELSE
  CALL HIP_DGEMM_GROUPED_ASYNC(NCUR_RESOL,KBLAS,'N',CTB,KLD,IN,IK,ONE,&
    & C_LOC(PA),KLD,IOFFA,C_LOC(PFACTORS),GROUP%LDB,GROUP%FACTOR_OFFSET,PBETA,&
    & C_LOC(PC),KLD,IOFFC,GROUP%COUNT,KSTREAM,C_LOC(ALLOCATOR%PTR))
ENDIF
#endif
#ifdef ACCGPU
!$ACC END HOST_DATA
#endif
#ifdef OMPGPU
!$OMP END TARGET DATA
#endif
END ASSOCIATE
END SUBROUTINE RUN_GROUP

SUBROUTINE FREE_GPU_BUTTERFLY_PLANS
USE TPM_FLT, ONLY: S
USE TPM_DISTR, ONLY: D
INTEGER(KIND=JPIM) :: JMLOC

CALL FREE_ONE_PLAN(S%PLAN_A)
CALL FREE_ONE_PLAN(S%PLAN_S)
CALL FREE_ONE_PLAN(S%PLAN_DIRECT_A)
CALL FREE_ONE_PLAN(S%PLAN_DIRECT_S)
IF (ALLOCATED(S%FA)) THEN
  DO JMLOC=1,D%NUMP
    CALL FREE_HYBRID(S%FA(JMLOC)%YHYBRID_A)
    CALL FREE_HYBRID(S%FA(JMLOC)%YHYBRID_S)
    CALL FREE_HYBRID(S%FA(JMLOC)%YHYBRID_DIRECT_A)
    CALL FREE_HYBRID(S%FA(JMLOC)%YHYBRID_DIRECT_S)
  ENDDO
ENDIF
END SUBROUTINE FREE_GPU_BUTTERFLY_PLANS

SUBROUTINE FREE_ONE_PLAN(PLAN)
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIM) :: JL
IF (PLAN%COMPACT_ID) CALL EXIT_COMPACT_GROUPS_DEVICE(PLAN)
#ifdef ACCGPU
IF (ALLOCATED(PLAN%FINAL_GATHER_SRC)) THEN
!$ACC EXIT DATA DELETE(PLAN%FINAL_GATHER_SRC,PLAN%FINAL_GATHER_DST)
ENDIF
!$ACC EXIT DATA DELETE(PLAN%FACTORS) IF(ASSOCIATED(PLAN%FACTORS))
IF (ALLOCATED(PLAN%PIVOTS)) THEN
!$ACC EXIT DATA DELETE(PLAN%PIVOTS)
ENDIF
#endif
#ifdef OMPGPU
IF (ALLOCATED(PLAN%FINAL_GATHER_SRC)) THEN
!$OMP TARGET EXIT DATA MAP(DELETE:PLAN%FINAL_GATHER_SRC,PLAN%FINAL_GATHER_DST)
ENDIF
!$OMP TARGET EXIT DATA MAP(DELETE:PLAN%FACTORS) IF(ASSOCIATED(PLAN%FACTORS))
IF (ALLOCATED(PLAN%PIVOTS)) THEN
!$OMP TARGET EXIT DATA MAP(DELETE:PLAN%PIVOTS)
ENDIF
#endif
CALL FREE_GROUP(PLAN%LEVEL0)
CALL FREE_GROUP(PLAN%FINAL)
CALL FREE_GROUP(PLAN%FINAL_FUSED)
CALL FREE_GROUP(PLAN%FINAL_PROJECT)
CALL FREE_GROUP(PLAN%FINAL_BASIS)
CALL FREE_GROUP(PLAN%DENSE)
IF (ALLOCATED(PLAN%LEVEL)) THEN
  DO JL=1,SIZE(PLAN%LEVEL)
    CALL FREE_GROUP(PLAN%LEVEL(JL)%FWD)
    CALL FREE_GROUP(PLAN%LEVEL(JL)%REV_ODD)
    CALL FREE_GROUP(PLAN%LEVEL(JL)%REV_EVEN)
  ENDDO
  DEALLOCATE(PLAN%LEVEL)
ENDIF
IF (ASSOCIATED(PLAN%FACTORS)) DEALLOCATE(PLAN%FACTORS)
IF (ALLOCATED(PLAN%PIVOTS)) DEALLOCATE(PLAN%PIVOTS)
IF (ALLOCATED(PLAN%FINAL_GATHER_SRC)) DEALLOCATE(PLAN%FINAL_GATHER_SRC)
IF (ALLOCATED(PLAN%FINAL_GATHER_DST)) DEALLOCATE(PLAN%FINAL_GATHER_DST)
IF (ALLOCATED(PLAN%USE_HYBRID)) DEALLOCATE(PLAN%USE_HYBRID)
PLAN%ENABLED=.FALSE.
PLAN%COMPACT_ID=.FALSE.
PLAN%FUSE_FINAL=.FALSE.
PLAN%RECOMPRESS_FINAL=.FALSE.
PLAN%MAX_LEVELS=0
PLAN%CANDIDATE_COUNT=0
PLAN%SELECTED_COUNT=0
PLAN%DENSE_BLOCKS=0
PLAN%LOW_RANK_BLOCKS=0
PLAN%BUTTERFLY_BLOCKS=0
PLAN%BETA_COLS=0
PLAN%EVEN_BETA_COLS=0
PLAN%WORK_COLS=0
PLAN%DENSE_COST=0
PLAN%HYBRID_COST=0
PLAN%FINAL_FACTOR_VALUES=0
PLAN%FINAL_GATHER_COUNT=0
PLAN%FINAL_ORIGINAL_COST=0
PLAN%FINAL_EXEC_COST=0
PLAN%FINAL_RECOMPRESSED_GROUPS=0
PLAN%FINAL_DIRECT_GROUPS=0
END SUBROUTINE FREE_ONE_PLAN

SUBROUTINE EXIT_COMPACT_GROUPS_DEVICE(PLAN)
TYPE(BUTTERFLY_GPU_PLAN),INTENT(IN) :: PLAN
INTEGER(KIND=JPIM) :: JL

CALL EXIT_COMPACT_GROUP_DEVICE(PLAN%LEVEL0)
DO JL=1,PLAN%MAX_LEVELS
  CALL EXIT_COMPACT_GROUP_DEVICE(PLAN%LEVEL(JL)%FWD)
  CALL EXIT_COMPACT_GROUP_DEVICE(PLAN%LEVEL(JL)%REV_ODD)
  CALL EXIT_COMPACT_GROUP_DEVICE(PLAN%LEVEL(JL)%REV_EVEN)
ENDDO
END SUBROUTINE EXIT_COMPACT_GROUPS_DEVICE

SUBROUTINE EXIT_COMPACT_GROUP_DEVICE(GROUP)
TYPE(BUTTERFLY_GPU_GROUPS),INTENT(IN) :: GROUP
IF (.NOT.ALLOCATED(GROUP%TILE_GROUP)) RETURN
ASSOCIATE(GN=>GROUP%N,GK=>GROUP%K,GS=>GROUP%SRC_COL,GD=>GROUP%DST_COL,&
  & GF=>GROUP%FACTOR_OFFSET,GP=>GROUP%PIVOT_OFFSET,&
  & GTG=>GROUP%TILE_GROUP,GTS=>GROUP%TILE_START)
#ifdef ACCGPU
!$ACC EXIT DATA DELETE(GN,GK,GS,GD,GF,GP,GTG,GTS)
#endif
#ifdef OMPGPU
!$OMP TARGET EXIT DATA MAP(DELETE:GN,GK,GS,GD,GF,GP,GTG,GTS)
#endif
END ASSOCIATE
END SUBROUTINE EXIT_COMPACT_GROUP_DEVICE

SUBROUTINE FREE_GROUP(GROUP)
TYPE(BUTTERFLY_GPU_GROUPS),INTENT(INOUT) :: GROUP
IF (ALLOCATED(GROUP%N)) DEALLOCATE(GROUP%N)
IF (ALLOCATED(GROUP%K)) DEALLOCATE(GROUP%K)
IF (ALLOCATED(GROUP%LDB)) DEALLOCATE(GROUP%LDB)
IF (ALLOCATED(GROUP%SRC_COL)) DEALLOCATE(GROUP%SRC_COL)
IF (ALLOCATED(GROUP%DST_COL)) DEALLOCATE(GROUP%DST_COL)
IF (ALLOCATED(GROUP%FACTOR_OFFSET)) DEALLOCATE(GROUP%FACTOR_OFFSET)
IF (ALLOCATED(GROUP%PIVOT_OFFSET)) DEALLOCATE(GROUP%PIVOT_OFFSET)
IF (ALLOCATED(GROUP%TILE_GROUP)) DEALLOCATE(GROUP%TILE_GROUP)
IF (ALLOCATED(GROUP%TILE_START)) DEALLOCATE(GROUP%TILE_START)
GROUP%COUNT=0
GROUP%TILE_COUNT=0
END SUBROUTINE FREE_GROUP

