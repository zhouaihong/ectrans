LOGICAL FUNCTION BUTTERFLY_REQUESTED()
CHARACTER(LEN=16) :: ZVALUE
INTEGER :: ILENGTH,ISTATUS
CALL GET_ENVIRONMENT_VARIABLE('ECTRANS_GPU_BUTTERFLY',ZVALUE,LENGTH=ILENGTH,&
  & STATUS=ISTATUS)
BUTTERFLY_REQUESTED=ISTATUS == 0 .AND. ILENGTH > 0 .AND. ZVALUE(1:1) == '1'
END FUNCTION BUTTERFLY_REQUESTED

LOGICAL FUNCTION BUTTERFLY_VALIDATION_REQUESTED()
CHARACTER(LEN=16) :: ZVALUE
INTEGER :: ILENGTH,ISTATUS
CALL GET_ENVIRONMENT_VARIABLE('ECTRANS_GPU_BUTTERFLY_VALIDATE',ZVALUE,LENGTH=ILENGTH,&
  & STATUS=ISTATUS)
BUTTERFLY_VALIDATION_REQUESTED=ISTATUS == 0 .AND. ILENGTH > 0 .AND. ZVALUE(1:1) == '1'
END FUNCTION BUTTERFLY_VALIDATION_REQUESTED

SUBROUTINE BUILD_GPU_BUTTERFLY_PLANS
USE TPM_FLT, ONLY: S
USE TPM_GEN, ONLY: NOUT

CALL BUILD_ONE_PLAN(S%PLAN_A,.FALSE.)
CALL BUILD_ONE_PLAN(S%PLAN_S,.TRUE.)

WRITE(NOUT,'(A,L1,A,L1)') 'GPU butterfly requested=',BUTTERFLY_REQUESTED(),&
  & ' validation=',BUTTERFLY_VALIDATION_REQUESTED()
WRITE(NOUT,'(A,L1,A,I0,A,I0,A,I0)') 'GPU butterfly anti=',S%PLAN_A%ENABLED,&
  & ' candidates=',S%PLAN_A%CANDIDATE_COUNT,&
  & ' selected=',COUNT(S%PLAN_A%USE_BUTTERFLY),' beta_cols=',S%PLAN_A%BETA_COLS
WRITE(NOUT,'(A,L1,A,I0,A,I0,A,I0)') 'GPU butterfly sym =',S%PLAN_S%ENABLED,&
  & ' candidates=',S%PLAN_S%CANDIDATE_COUNT,&
  & ' selected=',COUNT(S%PLAN_S%USE_BUTTERFLY),' beta_cols=',S%PLAN_S%BETA_COLS
END SUBROUTINE BUILD_GPU_BUTTERFLY_PLANS

SUBROUTINE BUILD_ONE_PLAN(PLAN,LSYM)
USE TPM_FLT, ONLY: S
USE TPM_DISTR, ONLY: D

TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
LOGICAL,INTENT(IN) :: LSYM

INTEGER(KIND=JPIM) :: JMLOC,JL,JJ,JK,ILEV,I0,IFN,JBEST
INTEGER(KIND=JPIM),ALLOCATABLE :: IFL(:),IFR(:),IRO(:),IRE(:)
INTEGER(KIND=JPIB) :: IPOS,IFACTORS,IBETA
REAL :: ZRATIO,ZBEST
LOGICAL :: LVALIDATE,LCANDIDATE

ALLOCATE(PLAN%USE_BUTTERFLY(D%NUMP),PLAN%BETA_BASE(D%NUMP))
PLAN%USE_BUTTERFLY=.FALSE.
PLAN%BETA_BASE=0
PLAN%CANDIDATE_COUNT=0
LVALIDATE=BUTTERFLY_VALIDATION_REQUESTED()
JBEST=0
ZBEST=HUGE(ZBEST)

DO JMLOC=1,D%NUMP
  IF (LSYM) THEN
    LCANDIDATE=ASSOCIATED(S%FA(JMLOC)%YBUT_STRUCT_S%SLEV)
    IF (LCANDIDATE) LCANDIDATE=S%FA(JMLOC)%YBUT_STRUCT_S%N_LEVELS > 0
    CALL SELECT_MATRIX(S%FA(JMLOC)%YBUT_STRUCT_S,PLAN%USE_BUTTERFLY(JMLOC),ZRATIO)
  ELSE
    LCANDIDATE=ASSOCIATED(S%FA(JMLOC)%YBUT_STRUCT_A%SLEV)
    IF (LCANDIDATE) LCANDIDATE=S%FA(JMLOC)%YBUT_STRUCT_A%N_LEVELS > 0
    CALL SELECT_MATRIX(S%FA(JMLOC)%YBUT_STRUCT_A,PLAN%USE_BUTTERFLY(JMLOC),ZRATIO)
  ENDIF
  IF (LCANDIDATE) THEN
    PLAN%CANDIDATE_COUNT=PLAN%CANDIDATE_COUNT+1
    IF (ZRATIO < ZBEST) THEN
      ZBEST=ZRATIO
      JBEST=JMLOC
    ENDIF
  ENDIF
ENDDO

IF (LVALIDATE) THEN
  PLAN%USE_BUTTERFLY=.FALSE.
  IF (JBEST > 0) PLAN%USE_BUTTERFLY(JBEST)=.TRUE.
ENDIF

DO JMLOC=1,D%NUMP
  IF (.NOT.PLAN%USE_BUTTERFLY(JMLOC)) CYCLE
  IF (LSYM) THEN
    PLAN%MAX_LEVELS=MAX(PLAN%MAX_LEVELS,S%FA(JMLOC)%YBUT_STRUCT_S%N_LEVELS)
  ELSE
    PLAN%MAX_LEVELS=MAX(PLAN%MAX_LEVELS,S%FA(JMLOC)%YBUT_STRUCT_A%N_LEVELS)
  ENDIF
ENDDO

IBETA=0
DO JMLOC=1,D%NUMP
  IF (.NOT.PLAN%USE_BUTTERFLY(JMLOC)) CYCLE
  IF (LSYM) THEN
    ILEV=S%FA(JMLOC)%YBUT_STRUCT_S%N_LEVELS
    IF (MOD(ILEV,2) /= 0) CYCLE
    PLAN%BETA_BASE(JMLOC)=IBETA
    IBETA=IBETA+S%FA(JMLOC)%YBUT_STRUCT_S%IBETALEN_MAX
  ELSE
    ILEV=S%FA(JMLOC)%YBUT_STRUCT_A%N_LEVELS
    IF (MOD(ILEV,2) /= 0) CYCLE
    PLAN%BETA_BASE(JMLOC)=IBETA
    IBETA=IBETA+S%FA(JMLOC)%YBUT_STRUCT_A%IBETALEN_MAX
  ENDIF
ENDDO
PLAN%EVEN_BETA_COLS=IBETA
DO JMLOC=1,D%NUMP
  IF (.NOT.PLAN%USE_BUTTERFLY(JMLOC)) CYCLE
  IF (LSYM) THEN
    ILEV=S%FA(JMLOC)%YBUT_STRUCT_S%N_LEVELS
    IF (MOD(ILEV,2) == 0) CYCLE
    PLAN%BETA_BASE(JMLOC)=IBETA
    IBETA=IBETA+S%FA(JMLOC)%YBUT_STRUCT_S%IBETALEN_MAX
  ELSE
    ILEV=S%FA(JMLOC)%YBUT_STRUCT_A%N_LEVELS
    IF (MOD(ILEV,2) == 0) CYCLE
    PLAN%BETA_BASE(JMLOC)=IBETA
    IBETA=IBETA+S%FA(JMLOC)%YBUT_STRUCT_A%IBETALEN_MAX
  ENDIF
ENDDO
PLAN%BETA_COLS=IBETA
PLAN%ENABLED=ANY(PLAN%USE_BUTTERFLY)
IF (.NOT.PLAN%ENABLED) RETURN

ALLOCATE(PLAN%LEVEL(1:PLAN%MAX_LEVELS))
IFACTORS=0
DO JMLOC=1,D%NUMP
  IF (.NOT.PLAN%USE_BUTTERFLY(JMLOC)) CYCLE
  IF (LSYM) THEN
    CALL COUNT_MATRIX(S%FA(JMLOC)%YBUT_STRUCT_S,PLAN,IFACTORS)
  ELSE
    CALL COUNT_MATRIX(S%FA(JMLOC)%YBUT_STRUCT_A,PLAN,IFACTORS)
  ENDIF
ENDDO

CALL ALLOC_GROUP(PLAN%LEVEL0)
CALL ALLOC_GROUP(PLAN%FINAL)
DO JL=1,PLAN%MAX_LEVELS
  CALL ALLOC_GROUP(PLAN%LEVEL(JL)%FWD_LEFT)
  CALL ALLOC_GROUP(PLAN%LEVEL(JL)%FWD_RIGHT)
  CALL ALLOC_GROUP(PLAN%LEVEL(JL)%REV_ODD)
  CALL ALLOC_GROUP(PLAN%LEVEL(JL)%REV_EVEN)
ENDDO
ALLOCATE(PLAN%FACTORS(IFACTORS))
PLAN%FACTORS=ZERO

ALLOCATE(IFL(PLAN%MAX_LEVELS),IFR(PLAN%MAX_LEVELS),&
  & IRO(PLAN%MAX_LEVELS),IRE(PLAN%MAX_LEVELS))
IFL=0
IFR=0
IRO=0
IRE=0
I0=0
IFN=0
IPOS=1
DO JMLOC=1,D%NUMP
  IF (.NOT.PLAN%USE_BUTTERFLY(JMLOC)) CYCLE
  IF (LSYM) THEN
    CALL FILL_MATRIX(S%FA(JMLOC)%YBUT_STRUCT_S,JMLOC,PLAN,IPOS,I0,IFN,IFL,IFR,IRO,IRE)
  ELSE
    CALL FILL_MATRIX(S%FA(JMLOC)%YBUT_STRUCT_A,JMLOC,PLAN,IPOS,I0,IFN,IFL,IFR,IRO,IRE)
  ENDIF
ENDDO
DEALLOCATE(IFL,IFR,IRO,IRE)

#ifdef ACCGPU
!$ACC ENTER DATA COPYIN(PLAN%FACTORS)
#endif
#ifdef OMPGPU
!$OMP TARGET ENTER DATA MAP(TO:PLAN%FACTORS)
#endif
END SUBROUTINE BUILD_ONE_PLAN

SUBROUTINE SELECT_MATRIX(BUT,LUSELECTED,PRATIO)
TYPE(BUTTERFLY_STRUCT),INTENT(IN) :: BUT
LOGICAL,INTENT(OUT) :: LUSELECTED
REAL,INTENT(OUT) :: PRATIO
INTEGER(KIND=JPIB) :: ICOST,IDENSE
INTEGER(KIND=JPIM) :: JL,JJ,JK,IRANKL,IRANKR

LUSELECTED=.FALSE.
PRATIO=1.0
IF (.NOT.ASSOCIATED(BUT%SLEV)) RETURN
IF (BUT%N_LEVELS <= 0) RETURN

ICOST=0
DO JK=1,BUT%SLEV(0)%IK
  ICOST=ICOST+INT(BUT%SLEV(0)%NODE(1,JK)%ICOLS,JPIB)*&
    & INT(BUT%SLEV(0)%NODE(1,JK)%IRANK,JPIB)
ENDDO
DO JL=1,BUT%N_LEVELS
  DO JK=1,BUT%SLEV(JL)%IK
    DO JJ=1,BUT%SLEV(JL)%IJ
      IRANKL=BUT%SLEV(JL-1)%NODE((JJ+1)/2,2*JK-1)%IRANK
      IRANKR=0
      IF (2*JK <= BUT%SLEV(JL-1)%IK) &
        IRANKR=BUT%SLEV(JL-1)%NODE((JJ+1)/2,2*JK)%IRANK
      ICOST=ICOST+INT(IRANKL+IRANKR,JPIB)*&
        & INT(BUT%SLEV(JL)%NODE(JJ,JK)%IRANK,JPIB)
    ENDDO
  ENDDO
ENDDO
JL=BUT%N_LEVELS
DO JK=1,BUT%SLEV(JL)%IK
  DO JJ=1,BUT%SLEV(JL)%IJ
    ICOST=ICOST+INT(BUT%SLEV(JL)%NODE(JJ,JK)%IROWS,JPIB)*&
      & INT(BUT%SLEV(JL)%NODE(JJ,JK)%IRANK,JPIB)
  ENDDO
ENDDO
IDENSE=INT(BUT%M_ORDER,JPIB)*INT(BUT%N_ORDER,JPIB)
IF (IDENSE > 0) PRATIO=REAL(ICOST)/REAL(IDENSE)
LUSELECTED=PRATIO < 0.75
END SUBROUTINE SELECT_MATRIX

SUBROUTINE COUNT_MATRIX(BUT,PLAN,KFACTORS)
TYPE(BUTTERFLY_STRUCT),INTENT(IN) :: BUT
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIB),INTENT(INOUT) :: KFACTORS
INTEGER(KIND=JPIM) :: JL,JJ,JK,IRANKL,IRANKR
TYPE(NODE_TYPE),POINTER :: YNODE

DO JK=1,BUT%SLEV(0)%IK
  YNODE=>BUT%SLEV(0)%NODE(1,JK)
  PLAN%LEVEL0%COUNT=PLAN%LEVEL0%COUNT+1
  KFACTORS=KFACTORS+INT(YNODE%ICOLS,JPIB)*INT(YNODE%IRANK,JPIB)
ENDDO
DO JL=1,BUT%N_LEVELS
  DO JK=1,BUT%SLEV(JL)%IK
    DO JJ=1,BUT%SLEV(JL)%IJ
      YNODE=>BUT%SLEV(JL)%NODE(JJ,JK)
      IRANKL=BUT%SLEV(JL-1)%NODE((JJ+1)/2,2*JK-1)%IRANK
      IRANKR=0
      IF (2*JK <= BUT%SLEV(JL-1)%IK) &
        IRANKR=BUT%SLEV(JL-1)%NODE((JJ+1)/2,2*JK)%IRANK
      PLAN%LEVEL(JL)%FWD_LEFT%COUNT=PLAN%LEVEL(JL)%FWD_LEFT%COUNT+1
      IF (IRANKR > 0) PLAN%LEVEL(JL)%FWD_RIGHT%COUNT=&
        & PLAN%LEVEL(JL)%FWD_RIGHT%COUNT+1
      IF (MOD(JJ,2) == 1) THEN
        PLAN%LEVEL(JL)%REV_ODD%COUNT=PLAN%LEVEL(JL)%REV_ODD%COUNT+1
        IF (IRANKR > 0) PLAN%LEVEL(JL)%REV_ODD%COUNT=&
          & PLAN%LEVEL(JL)%REV_ODD%COUNT+1
      ELSE
        PLAN%LEVEL(JL)%REV_EVEN%COUNT=PLAN%LEVEL(JL)%REV_EVEN%COUNT+1
        IF (IRANKR > 0) PLAN%LEVEL(JL)%REV_EVEN%COUNT=&
          & PLAN%LEVEL(JL)%REV_EVEN%COUNT+1
      ENDIF
      KFACTORS=KFACTORS+INT(IRANKL+IRANKR,JPIB)*INT(YNODE%IRANK,JPIB)
    ENDDO
  ENDDO
ENDDO
JL=BUT%N_LEVELS
DO JK=1,BUT%SLEV(JL)%IK
  DO JJ=1,BUT%SLEV(JL)%IJ
    YNODE=>BUT%SLEV(JL)%NODE(JJ,JK)
    PLAN%FINAL%COUNT=PLAN%FINAL%COUNT+1
    KFACTORS=KFACTORS+INT(YNODE%IROWS,JPIB)*INT(YNODE%IRANK,JPIB)
  ENDDO
ENDDO
END SUBROUTINE COUNT_MATRIX

SUBROUTINE ALLOC_GROUP(GROUP)
TYPE(BUTTERFLY_GPU_GROUPS),INTENT(INOUT) :: GROUP
IF (GROUP%COUNT <= 0) RETURN
ALLOCATE(GROUP%N(GROUP%COUNT),GROUP%K(GROUP%COUNT),GROUP%LDB(GROUP%COUNT))
ALLOCATE(GROUP%SRC_COL(GROUP%COUNT),GROUP%DST_COL(GROUP%COUNT),&
  & GROUP%FACTOR_OFFSET(GROUP%COUNT))
END SUBROUTINE ALLOC_GROUP

SUBROUTINE SET_GROUP(GROUP,KI,KN,KK,KLDB,KSRC,KDST,KFACTOR)
TYPE(BUTTERFLY_GPU_GROUPS),INTENT(INOUT) :: GROUP
INTEGER(KIND=JPIM),INTENT(IN) :: KI,KN,KK,KLDB
INTEGER(KIND=JPIB),INTENT(IN) :: KSRC,KDST,KFACTOR
GROUP%N(KI)=KN
GROUP%K(KI)=KK
GROUP%LDB(KI)=KLDB
GROUP%SRC_COL(KI)=KSRC
GROUP%DST_COL(KI)=KDST
GROUP%FACTOR_OFFSET(KI)=KFACTOR
END SUBROUTINE SET_GROUP

SUBROUTINE FILL_MATRIX(BUT,KMLOC,PLAN,KPOS,K0,KFINAL,KFL,KFR,KRO,KRE)
USE TPM_DISTR, ONLY: D
TYPE(BUTTERFLY_STRUCT),INTENT(IN) :: BUT
INTEGER(KIND=JPIM),INTENT(IN) :: KMLOC
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIB),INTENT(INOUT) :: KPOS
INTEGER(KIND=JPIM),INTENT(INOUT) :: K0,KFINAL,KFL(:),KFR(:),KRO(:),KRE(:)
INTEGER(KIND=JPIM) :: JL,JJ,JK,IRANKL,IRANKR
INTEGER(KIND=JPIB) :: IOFF,IOFFL,IOFFR,ISRC,IDST,IBASE
TYPE(NODE_TYPE),POINTER :: YNODE,YLEFT,YRIGHT

IBASE=PLAN%BETA_BASE(KMLOC)
DO JK=1,BUT%SLEV(0)%IK
  YNODE=>BUT%SLEV(0)%NODE(1,JK)
  CALL PACK_PROJECTION(YNODE,PLAN%FACTORS,KPOS,IOFF)
  K0=K0+1
  ISRC=D%OFFSETS_GEMM2(KMLOC)+YNODE%IFCOL-1
  IDST=IBASE+YNODE%IOFFBETA
  CALL SET_GROUP(PLAN%LEVEL0,K0,YNODE%IRANK,YNODE%ICOLS,YNODE%ICOLS,&
    & ISRC,IDST,IOFF)
ENDDO

DO JL=1,BUT%N_LEVELS
  DO JK=1,BUT%SLEV(JL)%IK
    DO JJ=1,BUT%SLEV(JL)%IJ
      YNODE=>BUT%SLEV(JL)%NODE(JJ,JK)
      YLEFT=>BUT%SLEV(JL-1)%NODE((JJ+1)/2,2*JK-1)
      IRANKL=YLEFT%IRANK
      IRANKR=0
      IF (2*JK <= BUT%SLEV(JL-1)%IK) THEN
        YRIGHT=>BUT%SLEV(JL-1)%NODE((JJ+1)/2,2*JK)
        IRANKR=YRIGHT%IRANK
      ENDIF
      CALL PACK_SPLIT_PROJECTION(YNODE,IRANKL,IRANKR,PLAN%FACTORS,KPOS,IOFFL,IOFFR)
      ISRC=IBASE+YLEFT%IOFFBETA
      IDST=IBASE+YNODE%IOFFBETA
      KFL(JL)=KFL(JL)+1
      CALL SET_GROUP(PLAN%LEVEL(JL)%FWD_LEFT,KFL(JL),YNODE%IRANK,IRANKL,IRANKL,&
        & ISRC,IDST,IOFFL)
      IF (IRANKR > 0) THEN
        ISRC=IBASE+YRIGHT%IOFFBETA
        KFR(JL)=KFR(JL)+1
        CALL SET_GROUP(PLAN%LEVEL(JL)%FWD_RIGHT,KFR(JL),YNODE%IRANK,IRANKR,IRANKR,&
          & ISRC,IDST,IOFFR)
      ENDIF
      IF (MOD(JJ,2) == 1) THEN
        KRO(JL)=KRO(JL)+1
        CALL SET_GROUP(PLAN%LEVEL(JL)%REV_ODD,KRO(JL),YNODE%IRANK,IRANKL,IRANKL,&
          & IBASE+YLEFT%IOFFBETA,IDST,IOFFL)
        IF (IRANKR > 0) THEN
          KRO(JL)=KRO(JL)+1
          CALL SET_GROUP(PLAN%LEVEL(JL)%REV_ODD,KRO(JL),YNODE%IRANK,IRANKR,IRANKR,&
            & IBASE+YRIGHT%IOFFBETA,IDST,IOFFR)
        ENDIF
      ELSE
        KRE(JL)=KRE(JL)+1
        CALL SET_GROUP(PLAN%LEVEL(JL)%REV_EVEN,KRE(JL),YNODE%IRANK,IRANKL,IRANKL,&
          & IBASE+YLEFT%IOFFBETA,IDST,IOFFL)
        IF (IRANKR > 0) THEN
          KRE(JL)=KRE(JL)+1
          CALL SET_GROUP(PLAN%LEVEL(JL)%REV_EVEN,KRE(JL),YNODE%IRANK,IRANKR,IRANKR,&
            & IBASE+YRIGHT%IOFFBETA,IDST,IOFFR)
        ENDIF
      ENDIF
    ENDDO
  ENDDO
ENDDO

JL=BUT%N_LEVELS
DO JK=1,BUT%SLEV(JL)%IK
  DO JJ=1,BUT%SLEV(JL)%IJ
    YNODE=>BUT%SLEV(JL)%NODE(JJ,JK)
    IOFF=KPOS-1
    PLAN%FACTORS(KPOS:KPOS+INT(YNODE%IROWS,JPIB)*YNODE%IRANK-1)=&
      & RESHAPE(REAL(YNODE%B,JPRBT),[YNODE%IROWS*YNODE%IRANK])
    KPOS=KPOS+INT(YNODE%IROWS,JPIB)*YNODE%IRANK
    KFINAL=KFINAL+1
    CALL SET_GROUP(PLAN%FINAL,KFINAL,YNODE%IROWS,YNODE%IRANK,YNODE%IROWS,&
      & IBASE+YNODE%IOFFBETA,D%OFFSETS_GEMM1(KMLOC)+YNODE%IFROW-1,IOFF)
  ENDDO
ENDDO
END SUBROUTINE FILL_MATRIX

SUBROUTINE PACK_PROJECTION(NODE,PFACTORS,KPOS,KOFFSET)
TYPE(NODE_TYPE),INTENT(IN) :: NODE
REAL(KIND=JPRBT),INTENT(INOUT) :: PFACTORS(:)
INTEGER(KIND=JPIB),INTENT(INOUT) :: KPOS
INTEGER(KIND=JPIB),INTENT(OUT) :: KOFFSET
REAL(KIND=JPRBT),ALLOCATABLE :: ZT(:,:)
INTEGER(KIND=JPIM) :: JI,JR,IC

ALLOCATE(ZT(NODE%ICOLS,NODE%IRANK))
ZT=ZERO
DO JI=1,NODE%ICOLS
  IC=NODE%ICLIST(JI)
  IF (JI <= NODE%IRANK) THEN
    ZT(IC,JI)=ONE
  ELSE
    DO JR=1,NODE%IRANK
      ZT(IC,JR)=NODE%PNONIM((JI-NODE%IRANK-1)*NODE%IRANK+JR)
    ENDDO
  ENDIF
ENDDO
KOFFSET=KPOS-1
PFACTORS(KPOS:KPOS+INT(NODE%ICOLS,JPIB)*NODE%IRANK-1)=&
  & RESHAPE(ZT,[NODE%ICOLS*NODE%IRANK])
KPOS=KPOS+INT(NODE%ICOLS,JPIB)*NODE%IRANK
DEALLOCATE(ZT)
END SUBROUTINE PACK_PROJECTION

SUBROUTINE PACK_SPLIT_PROJECTION(NODE,KRANKL,KRANKR,PFACTORS,KPOS,KOFFL,KOFFR)
TYPE(NODE_TYPE),INTENT(IN) :: NODE
INTEGER(KIND=JPIM),INTENT(IN) :: KRANKL,KRANKR
REAL(KIND=JPRBT),INTENT(INOUT) :: PFACTORS(:)
INTEGER(KIND=JPIB),INTENT(INOUT) :: KPOS
INTEGER(KIND=JPIB),INTENT(OUT) :: KOFFL,KOFFR
REAL(KIND=JPRBT),ALLOCATABLE :: ZT(:,:)
INTEGER(KIND=JPIM) :: JI,JR,IC

ALLOCATE(ZT(KRANKL+KRANKR,NODE%IRANK))
ZT=ZERO
DO JI=1,NODE%ICOLS
  IC=NODE%ICLIST(JI)
  IF (JI <= NODE%IRANK) THEN
    ZT(IC,JI)=ONE
  ELSE
    DO JR=1,NODE%IRANK
      ZT(IC,JR)=NODE%PNONIM((JI-NODE%IRANK-1)*NODE%IRANK+JR)
    ENDDO
  ENDIF
ENDDO
KOFFL=KPOS-1
PFACTORS(KPOS:KPOS+INT(KRANKL,JPIB)*NODE%IRANK-1)=&
  & RESHAPE(ZT(1:KRANKL,:),[KRANKL*NODE%IRANK])
KPOS=KPOS+INT(KRANKL,JPIB)*NODE%IRANK
KOFFR=KPOS-1
IF (KRANKR > 0) THEN
  PFACTORS(KPOS:KPOS+INT(KRANKR,JPIB)*NODE%IRANK-1)=&
    & RESHAPE(ZT(KRANKL+1:KRANKL+KRANKR,:),[KRANKR*NODE%IRANK])
  KPOS=KPOS+INT(KRANKR,JPIB)*NODE%IRANK
ENDIF
DEALLOCATE(ZT)
END SUBROUTINE PACK_SPLIT_PROJECTION

FUNCTION BUTTERFLY_WORK_COLUMNS() RESULT(KCOLS)
USE TPM_FLT, ONLY: S
INTEGER(KIND=JPIB) :: KCOLS
KCOLS=MAX(S%PLAN_A%BETA_COLS,S%PLAN_S%BETA_COLS)
END FUNCTION BUTTERFLY_WORK_COLUMNS

SUBROUTINE APPLY_BUTTERFLY_INVERSE(PLAN,PIN,POUT,KLD,KIN_BASE,KOUT_BASE,&
  & KASYNC,KBLAS_BASE,ALLOCATOR)
USE BUFFERED_ALLOCATOR_MOD, ONLY: BUFFERED_ALLOCATOR
#ifdef ACCGPU
USE OPENACC_LIB, ONLY: ACC_GET_HIP_STREAM
#endif
USE ISO_C_BINDING, ONLY: C_INT,C_INTPTR_T
TYPE(BUTTERFLY_GPU_PLAN),INTENT(IN) :: PLAN
REAL(KIND=JPRBT),POINTER,INTENT(INOUT) :: PIN(:),POUT(:)
INTEGER(KIND=JPIM),INTENT(IN) :: KLD,KASYNC,KBLAS_BASE
INTEGER(KIND=JPIB),INTENT(IN) :: KIN_BASE,KOUT_BASE
TYPE(BUFFERED_ALLOCATOR),INTENT(IN) :: ALLOCATOR
INTEGER(KIND=JPIM) :: JL
INTEGER(C_INTPTR_T) :: ISTREAM

IF (.NOT.PLAN%ENABLED) RETURN
#ifdef ACCGPU
ISTREAM=INT(ACC_GET_HIP_STREAM(INT(KASYNC,C_INT)),C_INTPTR_T)
#else
ISTREAM=0_C_INTPTR_T
#endif

CALL RUN_GROUP(PLAN%LEVEL0,PLAN,PIN,POUT,KLD,0_JPIB,KOUT_BASE,&
  & .FALSE.,.FALSE.,ZERO,ISTREAM,KBLAS_BASE,ALLOCATOR)
DO JL=1,PLAN%MAX_LEVELS
  IF (MOD(JL,2) == 1) THEN
    CALL RUN_GROUP(PLAN%LEVEL(JL)%FWD_LEFT,PLAN,POUT,PIN,KLD,KOUT_BASE,KIN_BASE,&
      & .FALSE.,.FALSE.,ZERO,ISTREAM,KBLAS_BASE+2*JL-1,ALLOCATOR)
    CALL RUN_GROUP(PLAN%LEVEL(JL)%FWD_RIGHT,PLAN,POUT,PIN,KLD,KOUT_BASE,KIN_BASE,&
      & .FALSE.,.FALSE.,ONE,ISTREAM,KBLAS_BASE+2*JL,ALLOCATOR)
  ELSE
    CALL RUN_GROUP(PLAN%LEVEL(JL)%FWD_LEFT,PLAN,PIN,POUT,KLD,KIN_BASE,KOUT_BASE,&
      & .FALSE.,.FALSE.,ZERO,ISTREAM,KBLAS_BASE+2*JL-1,ALLOCATOR)
    CALL RUN_GROUP(PLAN%LEVEL(JL)%FWD_RIGHT,PLAN,PIN,POUT,KLD,KIN_BASE,KOUT_BASE,&
      & .FALSE.,.FALSE.,ONE,ISTREAM,KBLAS_BASE+2*JL,ALLOCATOR)
  ENDIF
ENDDO
CALL COPY_COLUMNS(POUT,PIN,KLD,KOUT_BASE,KIN_BASE,0_JPIB,&
  & PLAN%EVEN_BETA_COLS,KASYNC)
CALL RUN_GROUP(PLAN%FINAL,PLAN,PIN,POUT,KLD,KIN_BASE,0_JPIB,&
  & .FALSE.,.TRUE.,ZERO,ISTREAM,KBLAS_BASE+30,ALLOCATOR)
END SUBROUTINE APPLY_BUTTERFLY_INVERSE

SUBROUTINE APPLY_BUTTERFLY_DIRECT(PLAN,PIN,POUT,KLD,KWORK_BASE,&
  & KASYNC,KBLAS_BASE,ALLOCATOR)
USE BUFFERED_ALLOCATOR_MOD, ONLY: BUFFERED_ALLOCATOR
#ifdef ACCGPU
USE OPENACC_LIB, ONLY: ACC_GET_HIP_STREAM
#endif
USE ISO_C_BINDING, ONLY: C_INT,C_INTPTR_T
TYPE(BUTTERFLY_GPU_PLAN),INTENT(IN) :: PLAN
REAL(KIND=JPRBT),POINTER,INTENT(IN) :: PIN(:)
REAL(KIND=JPRBT),POINTER,INTENT(INOUT) :: POUT(:)
INTEGER(KIND=JPIM),INTENT(IN) :: KLD,KASYNC,KBLAS_BASE
INTEGER(KIND=JPIB),INTENT(IN) :: KWORK_BASE
TYPE(BUFFERED_ALLOCATOR),INTENT(IN) :: ALLOCATOR
INTEGER(KIND=JPIM) :: JL
INTEGER(C_INTPTR_T) :: ISTREAM

IF (.NOT.PLAN%ENABLED) RETURN
#ifdef ACCGPU
ISTREAM=INT(ACC_GET_HIP_STREAM(INT(KASYNC,C_INT)),C_INTPTR_T)
#else
ISTREAM=0_C_INTPTR_T
#endif

CALL RUN_GROUP(PLAN%FINAL,PLAN,PIN,POUT,KLD,0_JPIB,KWORK_BASE,&
  & .TRUE.,.TRUE.,ZERO,ISTREAM,KBLAS_BASE+40,ALLOCATOR)
CALL COPY_COLUMNS_INPLACE(POUT,KLD,KWORK_BASE,KWORK_BASE+PLAN%BETA_COLS,&
  & PLAN%EVEN_BETA_COLS,&
  & PLAN%BETA_COLS-PLAN%EVEN_BETA_COLS,KASYNC)
DO JL=PLAN%MAX_LEVELS,1,-1
  IF (MOD(JL,2) == 1) THEN
    CALL RUN_GROUP(PLAN%LEVEL(JL)%REV_ODD,PLAN,POUT,POUT,KLD,&
      & KWORK_BASE+PLAN%BETA_COLS,KWORK_BASE,&
      & .TRUE.,.FALSE.,ZERO,ISTREAM,KBLAS_BASE+40+2*JL-1,ALLOCATOR)
    CALL RUN_GROUP(PLAN%LEVEL(JL)%REV_EVEN,PLAN,POUT,POUT,KLD,&
      & KWORK_BASE+PLAN%BETA_COLS,KWORK_BASE,&
      & .TRUE.,.FALSE.,ONE,ISTREAM,KBLAS_BASE+40+2*JL,ALLOCATOR)
  ELSE
    CALL RUN_GROUP(PLAN%LEVEL(JL)%REV_ODD,PLAN,POUT,POUT,KLD,&
      & KWORK_BASE,KWORK_BASE+PLAN%BETA_COLS,&
      & .TRUE.,.FALSE.,ZERO,ISTREAM,KBLAS_BASE+40+2*JL-1,ALLOCATOR)
    CALL RUN_GROUP(PLAN%LEVEL(JL)%REV_EVEN,PLAN,POUT,POUT,KLD,&
      & KWORK_BASE,KWORK_BASE+PLAN%BETA_COLS,&
      & .TRUE.,.FALSE.,ONE,ISTREAM,KBLAS_BASE+40+2*JL,ALLOCATOR)
  ENDIF
ENDDO
CALL RUN_GROUP(PLAN%LEVEL0,PLAN,POUT,POUT,KLD,KWORK_BASE,0_JPIB,&
  & .TRUE.,.FALSE.,ZERO,ISTREAM,KBLAS_BASE+70,ALLOCATOR)
END SUBROUTINE APPLY_BUTTERFLY_DIRECT

SUBROUTINE COPY_COLUMNS(PSRC,PDST,KLD,KSRC_BASE,KDST_BASE,KFIRST,KCOUNT,KASYNC)
REAL(KIND=JPRBT),POINTER,INTENT(IN) :: PSRC(:)
REAL(KIND=JPRBT),POINTER,INTENT(INOUT) :: PDST(:)
INTEGER(KIND=JPIM),INTENT(IN) :: KLD,KASYNC
INTEGER(KIND=JPIB),INTENT(IN) :: KSRC_BASE,KDST_BASE,KFIRST,KCOUNT
INTEGER(KIND=JPIB) :: J,JSTART,JEND
IF (KCOUNT <= 0) RETURN
JSTART=KFIRST*KLD+1
JEND=(KFIRST+KCOUNT)*KLD
#ifdef ACCGPU
!$ACC PARALLEL LOOP PRESENT(PSRC,PDST) ASYNC(KASYNC)
#endif
#ifdef OMPGPU
!$OMP TARGET TEAMS DISTRIBUTE PARALLEL DO DEFAULT(NONE) FIRSTPRIVATE(JSTART,JEND) MAP(PRESENT:PSRC,PDST)
#endif
DO J=JSTART,JEND
  PDST(KDST_BASE*KLD+J)=PSRC(KSRC_BASE*KLD+J)
ENDDO
END SUBROUTINE COPY_COLUMNS

SUBROUTINE COPY_COLUMNS_INPLACE(PBUF,KLD,KSRC_BASE,KDST_BASE,KFIRST,KCOUNT,KASYNC)
REAL(KIND=JPRBT),POINTER,INTENT(INOUT) :: PBUF(:)
INTEGER(KIND=JPIM),INTENT(IN) :: KLD,KASYNC
INTEGER(KIND=JPIB),INTENT(IN) :: KSRC_BASE,KDST_BASE,KFIRST,KCOUNT
INTEGER(KIND=JPIB) :: J,JSTART,JEND
IF (KCOUNT <= 0) RETURN
JSTART=KFIRST*KLD+1
JEND=(KFIRST+KCOUNT)*KLD
#ifdef ACCGPU
!$ACC PARALLEL LOOP PRESENT(PBUF) ASYNC(KASYNC)
#endif
#ifdef OMPGPU
!$OMP TARGET TEAMS DISTRIBUTE PARALLEL DO DEFAULT(NONE) FIRSTPRIVATE(JSTART,JEND) MAP(PRESENT:PBUF)
#endif
DO J=JSTART,JEND
  PBUF(KDST_BASE*KLD+J)=PBUF(KSRC_BASE*KLD+J)
ENDDO
END SUBROUTINE COPY_COLUMNS_INPLACE

SUBROUTINE RUN_GROUP(GROUP,PLAN,PA,PC,KLD,KADD_A,KADD_C,LREVERSE,&
  & LFACTOR_TRANSPOSED,PBETA,KSTREAM,KBLAS,ALLOCATOR)
USE BUFFERED_ALLOCATOR_MOD, ONLY: BUFFERED_ALLOCATOR
USE HICBLAS_MOD, ONLY: HIP_DGEMM_GROUPED_ASYNC,HIP_SGEMM_GROUPED_ASYNC
USE TPM_GEN, ONLY: NCUR_RESOL
USE ISO_C_BINDING, ONLY: C_LOC,C_INTPTR_T
TYPE(BUTTERFLY_GPU_GROUPS),INTENT(IN) :: GROUP
TYPE(BUTTERFLY_GPU_PLAN),INTENT(IN) :: PLAN
REAL(KIND=JPRBT),POINTER,INTENT(IN) :: PA(:)
REAL(KIND=JPRBT),POINTER,INTENT(INOUT) :: PC(:)
INTEGER(KIND=JPIM),INTENT(IN) :: KLD,KBLAS
INTEGER(KIND=JPIB),INTENT(IN) :: KADD_A,KADD_C
LOGICAL,INTENT(IN) :: LREVERSE,LFACTOR_TRANSPOSED
REAL(KIND=JPRBT),INTENT(IN) :: PBETA
INTEGER(C_INTPTR_T),INTENT(IN) :: KSTREAM
TYPE(BUFFERED_ALLOCATOR),INTENT(IN) :: ALLOCATOR
INTEGER(KIND=JPIM) :: IN(GROUP%COUNT),IK(GROUP%COUNT)
INTEGER(KIND=JPIB) :: IOFFA(GROUP%COUNT),IOFFC(GROUP%COUNT)
CHARACTER(LEN=1) :: CTB

IF (GROUP%COUNT <= 0) RETURN
IF (LREVERSE) THEN
  IN=GROUP%K
  IK=GROUP%N
  IOFFA=(GROUP%DST_COL+KADD_A)*KLD
  IOFFC=(GROUP%SRC_COL+KADD_C)*KLD
  IF (LFACTOR_TRANSPOSED) THEN
    CTB='N'
  ELSE
    CTB='T'
  ENDIF
ELSE
  IN=GROUP%N
  IK=GROUP%K
  IOFFA=(GROUP%SRC_COL+KADD_A)*KLD
  IOFFC=(GROUP%DST_COL+KADD_C)*KLD
  IF (LFACTOR_TRANSPOSED) THEN
    CTB='T'
  ELSE
    CTB='N'
  ENDIF
ENDIF

ASSOCIATE(PFACTORS=>PLAN%FACTORS)
#ifdef OMPGPU
!$OMP TARGET DATA USE_DEVICE_ADDR(PA,PFACTORS,PC)
#endif
#ifdef ACCGPU
!$ACC HOST_DATA USE_DEVICE(PA,PFACTORS,PC)
#endif
#ifdef TRANS_SINGLE
CALL HIP_SGEMM_GROUPED_ASYNC(NCUR_RESOL,KBLAS,'N',CTB,KLD,IN,IK,ONE,&
  & C_LOC(PA),KLD,IOFFA,C_LOC(PFACTORS),GROUP%LDB,GROUP%FACTOR_OFFSET,PBETA,&
  & C_LOC(PC),KLD,IOFFC,GROUP%COUNT,KSTREAM,C_LOC(ALLOCATOR%PTR))
#else
CALL HIP_DGEMM_GROUPED_ASYNC(NCUR_RESOL,KBLAS,'N',CTB,KLD,IN,IK,ONE,&
  & C_LOC(PA),KLD,IOFFA,C_LOC(PFACTORS),GROUP%LDB,GROUP%FACTOR_OFFSET,PBETA,&
  & C_LOC(PC),KLD,IOFFC,GROUP%COUNT,KSTREAM,C_LOC(ALLOCATOR%PTR))
#endif
#ifdef ACCGPU
!$ACC END HOST_DATA
#endif
#ifdef OMPGPU
!$OMP END TARGET DATA
#endif
END ASSOCIATE
END SUBROUTINE RUN_GROUP

SUBROUTINE FREE_GPU_BUTTERFLY_PLANS
USE TPM_FLT, ONLY: S
USE TPM_DISTR, ONLY: D
INTEGER(KIND=JPIM) :: JMLOC

CALL FREE_ONE_PLAN(S%PLAN_A)
CALL FREE_ONE_PLAN(S%PLAN_S)
IF (ALLOCATED(S%FA)) THEN
  DO JMLOC=1,D%NUMP
    IF (ASSOCIATED(S%FA(JMLOC)%YBUT_STRUCT_A%SLEV)) &
      CALL FREE_BUTTERFLY(S%FA(JMLOC)%YBUT_STRUCT_A)
    IF (ASSOCIATED(S%FA(JMLOC)%YBUT_STRUCT_S%SLEV)) &
      CALL FREE_BUTTERFLY(S%FA(JMLOC)%YBUT_STRUCT_S)
  ENDDO
ENDIF
END SUBROUTINE FREE_GPU_BUTTERFLY_PLANS

SUBROUTINE FREE_ONE_PLAN(PLAN)
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIM) :: JL
#ifdef ACCGPU
!$ACC EXIT DATA DELETE(PLAN%FACTORS) IF(ASSOCIATED(PLAN%FACTORS))
#endif
#ifdef OMPGPU
!$OMP TARGET EXIT DATA MAP(DELETE:PLAN%FACTORS) IF(ASSOCIATED(PLAN%FACTORS))
#endif
CALL FREE_GROUP(PLAN%LEVEL0)
CALL FREE_GROUP(PLAN%FINAL)
IF (ALLOCATED(PLAN%LEVEL)) THEN
  DO JL=1,SIZE(PLAN%LEVEL)
    CALL FREE_GROUP(PLAN%LEVEL(JL)%FWD_LEFT)
    CALL FREE_GROUP(PLAN%LEVEL(JL)%FWD_RIGHT)
    CALL FREE_GROUP(PLAN%LEVEL(JL)%REV_ODD)
    CALL FREE_GROUP(PLAN%LEVEL(JL)%REV_EVEN)
  ENDDO
  DEALLOCATE(PLAN%LEVEL)
ENDIF
IF (ASSOCIATED(PLAN%FACTORS)) DEALLOCATE(PLAN%FACTORS)
IF (ALLOCATED(PLAN%USE_BUTTERFLY)) DEALLOCATE(PLAN%USE_BUTTERFLY)
IF (ALLOCATED(PLAN%BETA_BASE)) DEALLOCATE(PLAN%BETA_BASE)
PLAN%ENABLED=.FALSE.
PLAN%MAX_LEVELS=0
PLAN%CANDIDATE_COUNT=0
PLAN%BETA_COLS=0
PLAN%EVEN_BETA_COLS=0
END SUBROUTINE FREE_ONE_PLAN

SUBROUTINE FREE_GROUP(GROUP)
TYPE(BUTTERFLY_GPU_GROUPS),INTENT(INOUT) :: GROUP
IF (ALLOCATED(GROUP%N)) DEALLOCATE(GROUP%N)
IF (ALLOCATED(GROUP%K)) DEALLOCATE(GROUP%K)
IF (ALLOCATED(GROUP%LDB)) DEALLOCATE(GROUP%LDB)
IF (ALLOCATED(GROUP%SRC_COL)) DEALLOCATE(GROUP%SRC_COL)
IF (ALLOCATED(GROUP%DST_COL)) DEALLOCATE(GROUP%DST_COL)
IF (ALLOCATED(GROUP%FACTOR_OFFSET)) DEALLOCATE(GROUP%FACTOR_OFFSET)
GROUP%COUNT=0
END SUBROUTINE FREE_GROUP

