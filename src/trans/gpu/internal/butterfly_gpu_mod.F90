INTEGER(KIND=JPIM),INTENT(IN) :: KLD,KASYNC
INTEGER(KIND=JPIB),INTENT(IN) :: KSRC_BASE,KDST_BASE,KCOUNT
INTEGER(KIND=JPIB),INTENT(IN) :: KSRC(:),KDST(:)
INTEGER(KIND=JPIB) :: J,ICOL,IFIELD,JEND

IF (KCOUNT <= 0) RETURN
JEND=INT(KLD,JPIB)*KCOUNT
#ifdef ACCGPU
!$ACC PARALLEL LOOP PRESENT(PBUF,KSRC,KDST) &
!$ACC& ASYNC(KASYNC)
#endif
#ifdef OMPGPU
!$OMP TARGET TEAMS DISTRIBUTE PARALLEL DO DEFAULT(NONE) FIRSTPRIVATE(JEND,KLD,KSRC_BASE,KDST_BASE) &
!$OMP& MAP(PRESENT:PBUF,KSRC,KDST)
#endif
DO J=1,JEND
  ICOL=(J-1)/KLD+1
  IFIELD=MOD(J-1,INT(KLD,JPIB))+1
  PBUF((KDST_BASE+KDST(ICOL))*KLD+IFIELD)=&
    & PBUF((KSRC_BASE+KSRC(ICOL))*KLD+IFIELD)
ENDDO
END SUBROUTINE GATHER_FINAL_COLUMNS

