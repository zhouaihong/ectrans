SUBROUTINE FREE_ONE_PLAN(PLAN)
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIM) :: JL
IF (PLAN%NATIVE_GROUPED) CALL EXIT_NATIVE_GROUPS_DEVICE(PLAN)
IF (PLAN%COMPACT_ID) CALL EXIT_COMPACT_GROUPS_DEVICE(PLAN)
IF (PLAN%FUSE_LEAF) CALL EXIT_FUSED_LEAF_DEVICE(PLAN%FUSED_LEAF)
#ifdef ACCGPU
IF (ALLOCATED(PLAN%FINAL_GATHER_SRC)) THEN
!$ACC EXIT DATA DELETE(PLAN%FINAL_GATHER_SRC,PLAN%FINAL_GATHER_DST)
ENDIF
!$ACC EXIT DATA DELETE(PLAN%FACTORS) IF(ASSOCIATED(PLAN%FACTORS))
IF (ALLOCATED(PLAN%PIVOTS)) THEN
!$ACC EXIT DATA DELETE(PLAN%PIVOTS)
ENDIF
#endif
#ifdef OMPGPU
IF (ALLOCATED(PLAN%FINAL_GATHER_SRC)) THEN
!$OMP TARGET EXIT DATA MAP(DELETE:PLAN%FINAL_GATHER_SRC,PLAN%FINAL_GATHER_DST)
ENDIF
!$OMP TARGET EXIT DATA MAP(DELETE:PLAN%FACTORS) IF(ASSOCIATED(PLAN%FACTORS))
IF (ALLOCATED(PLAN%PIVOTS)) THEN
!$OMP TARGET EXIT DATA MAP(DELETE:PLAN%PIVOTS)
ENDIF
#endif
CALL FREE_GROUP(PLAN%LEVEL0)
CALL FREE_GROUP(PLAN%FINAL)
CALL FREE_GROUP(PLAN%FINAL_FUSED)
CALL FREE_GROUP(PLAN%FINAL_PROJECT)
CALL FREE_GROUP(PLAN%FINAL_BASIS)
CALL FREE_GROUP(PLAN%DENSE)
CALL FREE_FUSED_LEAF(PLAN%FUSED_LEAF)
IF (ALLOCATED(PLAN%LEVEL)) THEN
  DO JL=1,SIZE(PLAN%LEVEL)
    CALL FREE_GROUP(PLAN%LEVEL(JL)%FWD)
    CALL FREE_GROUP(PLAN%LEVEL(JL)%REV_ODD)
    CALL FREE_GROUP(PLAN%LEVEL(JL)%REV_EVEN)
  ENDDO
  DEALLOCATE(PLAN%LEVEL)
ENDIF
IF (ASSOCIATED(PLAN%FACTORS)) DEALLOCATE(PLAN%FACTORS)
IF (ALLOCATED(PLAN%PIVOTS)) DEALLOCATE(PLAN%PIVOTS)
IF (ALLOCATED(PLAN%FINAL_GATHER_SRC)) DEALLOCATE(PLAN%FINAL_GATHER_SRC)
IF (ALLOCATED(PLAN%FINAL_GATHER_DST)) DEALLOCATE(PLAN%FINAL_GATHER_DST)
IF (ALLOCATED(PLAN%USE_HYBRID)) DEALLOCATE(PLAN%USE_HYBRID)
IF (ALLOCATED(PLAN%DIRECT_CROP_FIRST)) DEALLOCATE(PLAN%DIRECT_CROP_FIRST)
IF (ALLOCATED(PLAN%DIRECT_CROP_COUNT)) DEALLOCATE(PLAN%DIRECT_CROP_COUNT)
IF (ALLOCATED(PLAN%DIRECT_GROUP_MLOC)) DEALLOCATE(PLAN%DIRECT_GROUP_MLOC)
IF (ALLOCATED(PLAN%DIRECT_GROUP_FIRST_ROW)) &
  & DEALLOCATE(PLAN%DIRECT_GROUP_FIRST_ROW)
IF (ALLOCATED(PLAN%DIRECT_GROUP_FIRST_COL)) &
  & DEALLOCATE(PLAN%DIRECT_GROUP_FIRST_COL)
IF (ALLOCATED(PLAN%DIRECT_GROUP_N)) DEALLOCATE(PLAN%DIRECT_GROUP_N)
IF (ALLOCATED(PLAN%DIRECT_GROUP_K)) DEALLOCATE(PLAN%DIRECT_GROUP_K)
PLAN%ENABLED=.FALSE.
PLAN%COMPACT_ID=.FALSE.
PLAN%DENSE_DISJOINT=.FALSE.
PLAN%DIRECT_INLINE_CROP=.FALSE.
PLAN%DIRECT_NATIVE_BLOCKS=.FALSE.
PLAN%NATIVE_GROUPED=.FALSE.
PLAN%FUSE_REVERSE=.FALSE.
PLAN%FUSE_FINAL=.FALSE.
PLAN%RECOMPRESS_FINAL=.FALSE.
PLAN%FUSE_LEAF=.FALSE.
PLAN%MAX_LEVELS=0
PLAN%CANDIDATE_COUNT=0
