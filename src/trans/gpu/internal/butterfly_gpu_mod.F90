  & .FALSE.,.FALSE.,MERGE(ZERO,ONE,PLAN%DENSE_DISJOINT),&
  & ISTREAM,KBLAS_BASE-1,ALLOCATOR,&
  & .NOT.PLAN%DENSE_DISJOINT)
CALL RUN_FUSED_LEAF(PLAN,PIN,POUT,KLD,ISTREAM)
CALL RUN_PROJECTION(PLAN%LEVEL0,PLAN,PIN,POUT,KLD,0_JPIB,KWORK_BASE,&
  & KWORK_BASE+2*PLAN%BETA_COLS,&
  & .FALSE.,.FALSE.,ZERO,ISTREAM,KBLAS_BASE,ALLOCATOR)
DO JL=1,PLAN%MAX_LEVELS
  IF (MOD(JL,2) == 1) THEN
    CALL RUN_PROJECTION(PLAN%LEVEL(JL)%FWD,PLAN,POUT,POUT,KLD,KWORK_BASE,&
      & KWORK_BASE+PLAN%BETA_COLS,KWORK_BASE+2*PLAN%BETA_COLS,&
      & .FALSE.,.FALSE.,ZERO,ISTREAM,&
      & KBLAS_BASE+2*JL-1,ALLOCATOR)
  ELSE
    CALL RUN_PROJECTION(PLAN%LEVEL(JL)%FWD,PLAN,POUT,POUT,KLD,&
      & KWORK_BASE+PLAN%BETA_COLS,KWORK_BASE,KWORK_BASE+2*PLAN%BETA_COLS,&
      & .FALSE.,.FALSE.,ZERO,ISTREAM,&
      & KBLAS_BASE+2*JL-1,ALLOCATOR)
  ENDIF
ENDDO
CALL COPY_COLUMNS_INPLACE(POUT,KLD,KWORK_BASE,&
  & KWORK_BASE+PLAN%BETA_COLS,0_JPIB,PLAN%EVEN_BETA_COLS,KASYNC)
IF (PLAN%FUSE_FINAL) THEN
  CALL GATHER_FINAL_COLUMNS(POUT,KLD,KWORK_BASE+PLAN%BETA_COLS,KWORK_BASE,&
    & PLAN%FINAL_GATHER_SRC,PLAN%FINAL_GATHER_DST,&
    & PLAN%FINAL_GATHER_COUNT,KASYNC)
  IF (PLAN%RECOMPRESS_FINAL) THEN
    CALL RUN_GROUP(PLAN%FINAL_PROJECT,PLAN,POUT,POUT,KLD,KWORK_BASE,&
      & KWORK_BASE+PLAN%BETA_COLS,.FALSE.,.FALSE.,ZERO,ISTREAM,&
      & KBLAS_BASE+29,ALLOCATOR)
    CALL RUN_GROUP(PLAN%FINAL_FUSED,PLAN,POUT,POUT,KLD,KWORK_BASE,0_JPIB,&
      & .FALSE.,.TRUE.,ONE,ISTREAM,KBLAS_BASE+30,ALLOCATOR,.TRUE.)
    CALL RUN_GROUP(PLAN%FINAL_BASIS,PLAN,POUT,POUT,KLD,&
      & KWORK_BASE+PLAN%BETA_COLS,0_JPIB,.FALSE.,.TRUE.,ONE,ISTREAM,&
      & KBLAS_BASE+31,ALLOCATOR,.TRUE.)
  ELSE
    CALL RUN_GROUP(PLAN%FINAL_FUSED,PLAN,POUT,POUT,KLD,KWORK_BASE,0_JPIB,&
      & .FALSE.,.TRUE.,ONE,ISTREAM,KBLAS_BASE+30,ALLOCATOR,.TRUE.)
  ENDIF
ELSE
  CALL RUN_GROUP(PLAN%FINAL,PLAN,POUT,POUT,KLD,&
    & KWORK_BASE+PLAN%BETA_COLS,0_JPIB,.FALSE.,.TRUE.,ONE,ISTREAM,&
    & KBLAS_BASE+30,ALLOCATOR,.TRUE.)
ENDIF
END SUBROUTINE APPLY_BUTTERFLY_DIRECT_FORWARD

SUBROUTINE GATHER_FINAL_COLUMNS(PBUF,KLD,KSRC_BASE,KDST_BASE,&
  & KSRC,KDST,KCOUNT,KASYNC)
REAL(KIND=JPRBT),POINTER,INTENT(INOUT) :: PBUF(:)
INTEGER(KIND=JPIM),INTENT(IN) :: KLD,KASYNC
INTEGER(KIND=JPIB),INTENT(IN) :: KSRC_BASE,KDST_BASE,KCOUNT
INTEGER(KIND=JPIB),INTENT(IN) :: KSRC(:),KDST(:)
INTEGER(KIND=JPIB) :: J,ICOL,IFIELD,JEND

IF (KCOUNT <= 0) RETURN
JEND=INT(KLD,JPIB)*KCOUNT
#ifdef ACCGPU
!$ACC PARALLEL LOOP PRESENT(PBUF,KSRC,KDST) &
!$ACC& ASYNC(KASYNC)
#endif
#ifdef OMPGPU
!$OMP TARGET TEAMS DISTRIBUTE PARALLEL DO DEFAULT(NONE) FIRSTPRIVATE(JEND,KLD,KSRC_BASE,KDST_BASE) &
!$OMP& MAP(PRESENT:PBUF,KSRC,KDST)
#endif
DO J=1,JEND
  ICOL=(J-1)/KLD+1
  IFIELD=MOD(J-1,INT(KLD,JPIB))+1
  PBUF((KDST_BASE+KDST(ICOL))*KLD+IFIELD)=&
    & PBUF((KSRC_BASE+KSRC(ICOL))*KLD+IFIELD)
ENDDO
END SUBROUTINE GATHER_FINAL_COLUMNS

