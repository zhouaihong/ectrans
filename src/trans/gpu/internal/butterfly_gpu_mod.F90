SUBROUTINE BUILD_GPU_BUTTERFLY_PLANS
USE TPM_FLT, ONLY: S
USE TPM_GEN, ONLY: NOUT
USE TPM_DISTR, ONLY: D
REAL :: ZRATIO
INTEGER(KIND=JPIM) :: JMLOC

IF (BUTTERFLY_INVERSE_REQUESTED()) THEN
  CALL BUILD_ONE_PLAN(S%PLAN_A,.FALSE.,.FALSE.)
  CALL BUILD_ONE_PLAN(S%PLAN_S,.TRUE.,.FALSE.)
ENDIF
IF (BUTTERFLY_TRANSPOSE_DIRECT_REQUESTED()) THEN
  CALL BUILD_ONE_PLAN(S%PLAN_DIRECT_A,.FALSE.,.TRUE.)
  CALL BUILD_ONE_PLAN(S%PLAN_DIRECT_S,.TRUE.,.TRUE.)
ENDIF

WRITE(NOUT,'(A,L1,A,L1)') 'GPU butterfly requested=',BUTTERFLY_REQUESTED(),&
  & ' validation=',BUTTERFLY_VALIDATION_REQUESTED()
ZRATIO=1.0
IF (S%PLAN_A%DENSE_COST > 0) &
  ZRATIO=REAL(S%PLAN_A%HYBRID_COST)/REAL(S%PLAN_A%DENSE_COST)
WRITE(NOUT,'(A,L1,A,I0,A,I0,A,3(I0,1X),A,F7.4,A,I0)') &
  & 'GPU hybrid anti=',S%PLAN_A%ENABLED,' candidates=',S%PLAN_A%CANDIDATE_COUNT,&
  & ' selected=',S%PLAN_A%SELECTED_COUNT,' blocks(d/l/b)=',S%PLAN_A%DENSE_BLOCKS,&
  & S%PLAN_A%LOW_RANK_BLOCKS,S%PLAN_A%BUTTERFLY_BLOCKS,' cost_ratio=',ZRATIO,&
  & ' work_cols=',S%PLAN_A%WORK_COLS
CALL PRINT_PLAN_PROJECTION_STATS(NOUT,'inverse anti',S%PLAN_A)
CALL PRINT_PLAN_EXEC_STATS(NOUT,'inverse anti',S%PLAN_A)
CALL PRINT_PLAN_FUSION_STATS(NOUT,'inverse anti',S%PLAN_A,.FALSE.,.FALSE.)
ZRATIO=1.0
IF (S%PLAN_S%DENSE_COST > 0) &
  ZRATIO=REAL(S%PLAN_S%HYBRID_COST)/REAL(S%PLAN_S%DENSE_COST)
WRITE(NOUT,'(A,L1,A,I0,A,I0,A,3(I0,1X),A,F7.4,A,I0)') &
  & 'GPU hybrid sym =',S%PLAN_S%ENABLED,' candidates=',S%PLAN_S%CANDIDATE_COUNT,&
  & ' selected=',S%PLAN_S%SELECTED_COUNT,' blocks(d/l/b)=',S%PLAN_S%DENSE_BLOCKS,&
  & S%PLAN_S%LOW_RANK_BLOCKS,S%PLAN_S%BUTTERFLY_BLOCKS,' cost_ratio=',ZRATIO,&
  & ' work_cols=',S%PLAN_S%WORK_COLS
CALL PRINT_PLAN_PROJECTION_STATS(NOUT,'inverse sym',S%PLAN_S)
CALL PRINT_PLAN_EXEC_STATS(NOUT,'inverse sym',S%PLAN_S)
CALL PRINT_PLAN_FUSION_STATS(NOUT,'inverse sym',S%PLAN_S,.TRUE.,.FALSE.)
IF (BUTTERFLY_TRANSPOSE_DIRECT_REQUESTED()) THEN
  ZRATIO=1.0
  IF (S%PLAN_DIRECT_A%DENSE_COST > 0) &
    ZRATIO=REAL(S%PLAN_DIRECT_A%HYBRID_COST)/REAL(S%PLAN_DIRECT_A%DENSE_COST)
  WRITE(NOUT,'(A,L1,A,I0,A,I0,A,F7.4,A,I0,A,I0,A,I0,A,I0,A,F7.4)') &
    & 'GPU transpose direct anti=',S%PLAN_DIRECT_A%ENABLED,&
    & ' candidates=',S%PLAN_DIRECT_A%CANDIDATE_COUNT,&
    & ' selected=',S%PLAN_DIRECT_A%SELECTED_COUNT,' cost_ratio=',ZRATIO,&
    & ' work_cols=',S%PLAN_DIRECT_A%WORK_COLS,&
    & ' final=',S%PLAN_DIRECT_A%FINAL%COUNT,&
    & ' fused_final=',S%PLAN_DIRECT_A%FINAL_FUSED%COUNT,&
    & ' recompressed=',S%PLAN_DIRECT_A%FINAL_RECOMPRESSED_GROUPS,&
    & ' final_cost_ratio=',REAL(S%PLAN_DIRECT_A%FINAL_EXEC_COST,JPRD)/&
    & REAL(MAX(1_JPIB,S%PLAN_DIRECT_A%FINAL_ORIGINAL_COST),JPRD)
  CALL PRINT_PLAN_PROJECTION_STATS(NOUT,'direct anti',S%PLAN_DIRECT_A)
  CALL PRINT_PLAN_EXEC_STATS(NOUT,'direct anti',S%PLAN_DIRECT_A)
  CALL PRINT_PLAN_FUSION_STATS(NOUT,'direct anti',S%PLAN_DIRECT_A,.FALSE.,.TRUE.)
  IF (S%PLAN_DIRECT_A%FUSE_LEAF) WRITE(NOUT,'(A,I0,A,I0)') &
    & 'GPU fused leaf direct anti count=',S%PLAN_DIRECT_A%FUSED_LEAF%COUNT,&
    & ' max_rank=',S%PLAN_DIRECT_A%FUSED_LEAF%MAX_RANK
  WRITE(NOUT,'(A,L1)') 'GPU direct inline crop anti=',&
    & S%PLAN_DIRECT_A%DIRECT_INLINE_CROP
  WRITE(NOUT,'(A,L1,A,I0)') 'GPU direct native blocks anti=',&
    & S%PLAN_DIRECT_A%DIRECT_NATIVE_BLOCKS,' groups=',&
    & S%PLAN_DIRECT_A%DIRECT_GROUP_COUNT
  ZRATIO=1.0
  IF (S%PLAN_DIRECT_S%DENSE_COST > 0) &
    ZRATIO=REAL(S%PLAN_DIRECT_S%HYBRID_COST)/REAL(S%PLAN_DIRECT_S%DENSE_COST)
  WRITE(NOUT,'(A,L1,A,I0,A,I0,A,F7.4,A,I0,A,I0,A,I0,A,I0,A,F7.4)') &
    & 'GPU transpose direct sym =',S%PLAN_DIRECT_S%ENABLED,&
    & ' candidates=',S%PLAN_DIRECT_S%CANDIDATE_COUNT,&
    & ' selected=',S%PLAN_DIRECT_S%SELECTED_COUNT,' cost_ratio=',ZRATIO,&
    & ' work_cols=',S%PLAN_DIRECT_S%WORK_COLS,&
    & ' final=',S%PLAN_DIRECT_S%FINAL%COUNT,&
    & ' fused_final=',S%PLAN_DIRECT_S%FINAL_FUSED%COUNT,&
    & ' recompressed=',S%PLAN_DIRECT_S%FINAL_RECOMPRESSED_GROUPS,&
    & ' final_cost_ratio=',REAL(S%PLAN_DIRECT_S%FINAL_EXEC_COST,JPRD)/&
    & REAL(MAX(1_JPIB,S%PLAN_DIRECT_S%FINAL_ORIGINAL_COST),JPRD)
  CALL PRINT_PLAN_PROJECTION_STATS(NOUT,'direct sym',S%PLAN_DIRECT_S)
  CALL PRINT_PLAN_EXEC_STATS(NOUT,'direct sym',S%PLAN_DIRECT_S)
  CALL PRINT_PLAN_FUSION_STATS(NOUT,'direct sym',S%PLAN_DIRECT_S,.TRUE.,.TRUE.)
  IF (S%PLAN_DIRECT_S%FUSE_LEAF) WRITE(NOUT,'(A,I0,A,I0)') &
    & 'GPU fused leaf direct sym count=',S%PLAN_DIRECT_S%FUSED_LEAF%COUNT,&
    & ' max_rank=',S%PLAN_DIRECT_S%FUSED_LEAF%MAX_RANK
  WRITE(NOUT,'(A,L1)') 'GPU direct inline crop sym =',&
    & S%PLAN_DIRECT_S%DIRECT_INLINE_CROP
  WRITE(NOUT,'(A,L1,A,I0)') 'GPU direct native blocks sym =',&
    & S%PLAN_DIRECT_S%DIRECT_NATIVE_BLOCKS,' groups=',&
    & S%PLAN_DIRECT_S%DIRECT_GROUP_COUNT
ENDIF
DO JMLOC=1,D%NUMP
  CALL FREE_HYBRID(S%FA(JMLOC)%YHYBRID_A)
  CALL FREE_HYBRID(S%FA(JMLOC)%YHYBRID_S)
  CALL FREE_HYBRID(S%FA(JMLOC)%YHYBRID_DIRECT_A)
  CALL FREE_HYBRID(S%FA(JMLOC)%YHYBRID_DIRECT_S)
ENDDO
END SUBROUTINE BUILD_GPU_BUTTERFLY_PLANS

SUBROUTINE PRINT_PLAN_PROJECTION_STATS(KUNIT,CNAME,PLAN)
INTEGER,INTENT(IN) :: KUNIT
CHARACTER(LEN=*),INTENT(IN) :: CNAME
TYPE(BUTTERFLY_GPU_PLAN),INTENT(IN) :: PLAN
INTEGER(KIND=JPIB) :: ICOMPACT_TOTAL
REAL(KIND=JPRD) :: ZRATIO

IF (.NOT.PLAN%ENABLED .OR. PLAN%PROJECTION_FULL_VALUES <= 0) RETURN
ICOMPACT_TOTAL=PLAN%HYBRID_COST-PLAN%PROJECTION_FULL_VALUES+&
  & PLAN%PROJECTION_COMPACT_VALUES
ZRATIO=REAL(ICOMPACT_TOTAL,JPRD)/REAL(MAX(1_JPIB,PLAN%HYBRID_COST),JPRD)
WRITE(KUNIT,'(A,A,A,I0,A,I0,A,I0,A,I0,A,F7.4)') &
  & 'GPU projection plan=',TRIM(CNAME),&
  & ' full=',PLAN%PROJECTION_FULL_VALUES,&
  & ' nonidentity=',PLAN%PROJECTION_COMPACT_VALUES,&
  & ' identity=',PLAN%PROJECTION_FULL_VALUES-PLAN%PROJECTION_COMPACT_VALUES,&
  & ' final=',PLAN%FINAL_FACTOR_VALUES,' compact_total_ratio=',ZRATIO
END SUBROUTINE PRINT_PLAN_PROJECTION_STATS

SUBROUTINE PRINT_PLAN_EXEC_STATS(KUNIT,CNAME,PLAN)
INTEGER,INTENT(IN) :: KUNIT
CHARACTER(LEN=*),INTENT(IN) :: CNAME
TYPE(BUTTERFLY_GPU_PLAN),INTENT(IN) :: PLAN

IF (PLAN%DENSE_EXEC_COST <= 0) RETURN
WRITE(KUNIT,'(A,A,A,I0,A,I0,A,F7.4)') 'GPU tile cost ',TRIM(CNAME),&
  & ' dense=',PLAN%DENSE_EXEC_COST,' selected=',PLAN%HYBRID_EXEC_COST,&
  & ' ratio=',REAL(PLAN%HYBRID_EXEC_COST,JPRD)/REAL(PLAN%DENSE_EXEC_COST,JPRD)
END SUBROUTINE PRINT_PLAN_EXEC_STATS

