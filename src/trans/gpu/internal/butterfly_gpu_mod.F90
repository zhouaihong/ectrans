SUBROUTINE BUILD_GPU_BUTTERFLY_PLANS
USE TPM_FLT, ONLY: S
USE TPM_GEN, ONLY: NOUT
USE TPM_DISTR, ONLY: D
REAL :: ZRATIO
INTEGER(KIND=JPIM) :: JMLOC

IF (BUTTERFLY_INVERSE_REQUESTED()) THEN
  CALL BUILD_ONE_PLAN(S%PLAN_A,.FALSE.,.FALSE.)
  CALL BUILD_ONE_PLAN(S%PLAN_S,.TRUE.,.FALSE.)
ENDIF
IF (BUTTERFLY_TRANSPOSE_DIRECT_REQUESTED()) THEN
  CALL BUILD_ONE_PLAN(S%PLAN_DIRECT_A,.FALSE.,.TRUE.)
  CALL BUILD_ONE_PLAN(S%PLAN_DIRECT_S,.TRUE.,.TRUE.)
ENDIF

WRITE(NOUT,'(A,L1,A,L1)') 'GPU butterfly requested=',BUTTERFLY_REQUESTED(),&
  & ' validation=',BUTTERFLY_VALIDATION_REQUESTED()
ZRATIO=1.0
IF (S%PLAN_A%DENSE_COST > 0) &
  ZRATIO=REAL(S%PLAN_A%HYBRID_COST)/REAL(S%PLAN_A%DENSE_COST)
WRITE(NOUT,'(A,L1,A,I0,A,I0,A,3(I0,1X),A,F7.4,A,I0)') &
  & 'GPU hybrid anti=',S%PLAN_A%ENABLED,' candidates=',S%PLAN_A%CANDIDATE_COUNT,&
  & ' selected=',S%PLAN_A%SELECTED_COUNT,' blocks(d/l/b)=',S%PLAN_A%DENSE_BLOCKS,&
  & S%PLAN_A%LOW_RANK_BLOCKS,S%PLAN_A%BUTTERFLY_BLOCKS,' cost_ratio=',ZRATIO,&
  & ' work_cols=',S%PLAN_A%WORK_COLS
ZRATIO=1.0
IF (S%PLAN_S%DENSE_COST > 0) &
  ZRATIO=REAL(S%PLAN_S%HYBRID_COST)/REAL(S%PLAN_S%DENSE_COST)
WRITE(NOUT,'(A,L1,A,I0,A,I0,A,3(I0,1X),A,F7.4,A,I0)') &
  & 'GPU hybrid sym =',S%PLAN_S%ENABLED,' candidates=',S%PLAN_S%CANDIDATE_COUNT,&
  & ' selected=',S%PLAN_S%SELECTED_COUNT,' blocks(d/l/b)=',S%PLAN_S%DENSE_BLOCKS,&
  & S%PLAN_S%LOW_RANK_BLOCKS,S%PLAN_S%BUTTERFLY_BLOCKS,' cost_ratio=',ZRATIO,&
  & ' work_cols=',S%PLAN_S%WORK_COLS
IF (BUTTERFLY_TRANSPOSE_DIRECT_REQUESTED()) THEN
  ZRATIO=1.0
  IF (S%PLAN_DIRECT_A%DENSE_COST > 0) &
    ZRATIO=REAL(S%PLAN_DIRECT_A%HYBRID_COST)/REAL(S%PLAN_DIRECT_A%DENSE_COST)
  WRITE(NOUT,'(A,L1,A,I0,A,I0,A,F7.4,A,I0,A,I0,A,I0,A,I0,A,F7.4)') &
    & 'GPU transpose direct anti=',S%PLAN_DIRECT_A%ENABLED,&
    & ' candidates=',S%PLAN_DIRECT_A%CANDIDATE_COUNT,&
    & ' selected=',S%PLAN_DIRECT_A%SELECTED_COUNT,' cost_ratio=',ZRATIO,&
    & ' work_cols=',S%PLAN_DIRECT_A%WORK_COLS,&
    & ' final=',S%PLAN_DIRECT_A%FINAL%COUNT,&
    & ' fused_final=',S%PLAN_DIRECT_A%FINAL_FUSED%COUNT,&
    & ' recompressed=',S%PLAN_DIRECT_A%FINAL_RECOMPRESSED_GROUPS,&
    & ' final_cost_ratio=',REAL(S%PLAN_DIRECT_A%FINAL_EXEC_COST,JPRD)/&
    & REAL(MAX(1_JPIB,S%PLAN_DIRECT_A%FINAL_ORIGINAL_COST),JPRD)
  ZRATIO=1.0
  IF (S%PLAN_DIRECT_S%DENSE_COST > 0) &
    ZRATIO=REAL(S%PLAN_DIRECT_S%HYBRID_COST)/REAL(S%PLAN_DIRECT_S%DENSE_COST)
  WRITE(NOUT,'(A,L1,A,I0,A,I0,A,F7.4,A,I0,A,I0,A,I0,A,I0,A,F7.4)') &
    & 'GPU transpose direct sym =',S%PLAN_DIRECT_S%ENABLED,&
    & ' candidates=',S%PLAN_DIRECT_S%CANDIDATE_COUNT,&
    & ' selected=',S%PLAN_DIRECT_S%SELECTED_COUNT,' cost_ratio=',ZRATIO,&
    & ' work_cols=',S%PLAN_DIRECT_S%WORK_COLS,&
    & ' final=',S%PLAN_DIRECT_S%FINAL%COUNT,&
    & ' fused_final=',S%PLAN_DIRECT_S%FINAL_FUSED%COUNT,&
    & ' recompressed=',S%PLAN_DIRECT_S%FINAL_RECOMPRESSED_GROUPS,&
    & ' final_cost_ratio=',REAL(S%PLAN_DIRECT_S%FINAL_EXEC_COST,JPRD)/&
    & REAL(MAX(1_JPIB,S%PLAN_DIRECT_S%FINAL_ORIGINAL_COST),JPRD)
ENDIF
DO JMLOC=1,D%NUMP
  CALL FREE_HYBRID(S%FA(JMLOC)%YHYBRID_A)
  CALL FREE_HYBRID(S%FA(JMLOC)%YHYBRID_S)
  CALL FREE_HYBRID(S%FA(JMLOC)%YHYBRID_DIRECT_A)
  CALL FREE_HYBRID(S%FA(JMLOC)%YHYBRID_DIRECT_S)
ENDDO
END SUBROUTINE BUILD_GPU_BUTTERFLY_PLANS

SUBROUTINE BUILD_ONE_PLAN(PLAN,LSYM,LDIRECT)
USE TPM_FLT, ONLY: S
USE TPM_DISTR, ONLY: D

TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
LOGICAL,INTENT(IN) :: LSYM
LOGICAL,INTENT(IN) :: LDIRECT

INTEGER(KIND=JPIM) :: JMLOC,JL,I0,IFN,IDENSE
INTEGER(KIND=JPIM),ALLOCATABLE :: IFW(:),IRO(:),IRE(:)
INTEGER(KIND=JPIB) :: IPOS,IFACTORS,IFACTORS_ALLOC,IBETA,IPIVOTS,IPIVOT_POS
LOGICAL :: LVALIDATE

ALLOCATE(PLAN%USE_HYBRID(D%NUMP))
PLAN%USE_HYBRID=.FALSE.
LVALIDATE=BUTTERFLY_VALIDATION_REQUESTED()
PLAN%COMPACT_ID=BUTTERFLY_COMPACT_ID_REQUESTED()
PLAN%FUSE_FINAL=LDIRECT .AND. BUTTERFLY_FUSE_FINAL_REQUESTED()
PLAN%RECOMPRESS_FINAL=LDIRECT .AND. BUTTERFLY_RECOMPRESS_FINAL_REQUESTED()
PLAN%FUSE_FINAL=PLAN%FUSE_FINAL .OR. PLAN%RECOMPRESS_FINAL

DO JMLOC=1,D%NUMP
  IF (LDIRECT .AND. LSYM) THEN
    CALL SCAN_HYBRID(S%FA(JMLOC)%YHYBRID_DIRECT_S,PLAN,JMLOC)
  ELSEIF (LDIRECT) THEN
    CALL SCAN_HYBRID(S%FA(JMLOC)%YHYBRID_DIRECT_A,PLAN,JMLOC)
  ELSEIF (LSYM) THEN
    CALL SCAN_HYBRID(S%FA(JMLOC)%YHYBRID_S,PLAN,JMLOC)
  ELSE
    CALL SCAN_HYBRID(S%FA(JMLOC)%YHYBRID_A,PLAN,JMLOC)
  ENDIF
ENDDO

IF (LVALIDATE) THEN
  CALL KEEP_BEST_MATRIX(PLAN)
ENDIF
PLAN%ENABLED=ANY(PLAN%USE_HYBRID)
IF (.NOT.PLAN%ENABLED) RETURN

IBETA=0
DO JMLOC=1,D%NUMP
  IF (.NOT.PLAN%USE_HYBRID(JMLOC)) CYCLE
  IF (LDIRECT .AND. LSYM) THEN
    CALL ASSIGN_WORK(S%FA(JMLOC)%YHYBRID_DIRECT_S,0,IBETA)
  ELSEIF (LDIRECT) THEN
    CALL ASSIGN_WORK(S%FA(JMLOC)%YHYBRID_DIRECT_A,0,IBETA)
  ELSEIF (LSYM) THEN
    CALL ASSIGN_WORK(S%FA(JMLOC)%YHYBRID_S,0,IBETA)
  ELSE
    CALL ASSIGN_WORK(S%FA(JMLOC)%YHYBRID_A,0,IBETA)
  ENDIF
ENDDO
PLAN%EVEN_BETA_COLS=IBETA
DO JMLOC=1,D%NUMP
  IF (.NOT.PLAN%USE_HYBRID(JMLOC)) CYCLE
  IF (LDIRECT .AND. LSYM) THEN
    CALL ASSIGN_WORK(S%FA(JMLOC)%YHYBRID_DIRECT_S,1,IBETA)
  ELSEIF (LDIRECT) THEN
    CALL ASSIGN_WORK(S%FA(JMLOC)%YHYBRID_DIRECT_A,1,IBETA)
  ELSEIF (LSYM) THEN
    CALL ASSIGN_WORK(S%FA(JMLOC)%YHYBRID_S,1,IBETA)
  ELSE
    CALL ASSIGN_WORK(S%FA(JMLOC)%YHYBRID_A,1,IBETA)
  ENDIF
ENDDO
PLAN%BETA_COLS=IBETA
PLAN%WORK_COLS=IBETA

IF (PLAN%MAX_LEVELS > 0) ALLOCATE(PLAN%LEVEL(1:PLAN%MAX_LEVELS))
IFACTORS=0
IPIVOTS=0
DO JMLOC=1,D%NUMP
  IF (.NOT.PLAN%USE_HYBRID(JMLOC)) CYCLE
  IF (LDIRECT .AND. LSYM) THEN
    CALL COUNT_HYBRID(S%FA(JMLOC)%YHYBRID_DIRECT_S,PLAN,IFACTORS,IPIVOTS)
  ELSEIF (LDIRECT) THEN
    CALL COUNT_HYBRID(S%FA(JMLOC)%YHYBRID_DIRECT_A,PLAN,IFACTORS,IPIVOTS)
  ELSEIF (LSYM) THEN
    CALL COUNT_HYBRID(S%FA(JMLOC)%YHYBRID_S,PLAN,IFACTORS,IPIVOTS)
  ELSE
    CALL COUNT_HYBRID(S%FA(JMLOC)%YHYBRID_A,PLAN,IFACTORS,IPIVOTS)
  ENDIF
ENDDO

CALL ALLOC_GROUP(PLAN%LEVEL0)
CALL ALLOC_GROUP(PLAN%FINAL)
CALL ALLOC_GROUP(PLAN%DENSE)
DO JL=1,PLAN%MAX_LEVELS
  CALL ALLOC_GROUP(PLAN%LEVEL(JL)%FWD)
  CALL ALLOC_GROUP(PLAN%LEVEL(JL)%REV_ODD)
  CALL ALLOC_GROUP(PLAN%LEVEL(JL)%REV_EVEN)
ENDDO
IFACTORS_ALLOC=IFACTORS
IF (PLAN%FUSE_FINAL) IFACTORS_ALLOC=IFACTORS_ALLOC+PLAN%FINAL_FACTOR_VALUES
ALLOCATE(PLAN%FACTORS(IFACTORS_ALLOC))
PLAN%FACTORS=ZERO
IF (PLAN%COMPACT_ID) ALLOCATE(PLAN%PIVOTS(IPIVOTS))

ALLOCATE(IFW(PLAN%MAX_LEVELS),IRO(PLAN%MAX_LEVELS),IRE(PLAN%MAX_LEVELS))
IFW=0
IRO=0
IRE=0
I0=0
IFN=0
IDENSE=0
IPOS=1
IPIVOT_POS=1
DO JMLOC=1,D%NUMP
  IF (.NOT.PLAN%USE_HYBRID(JMLOC)) CYCLE
  IF (LDIRECT .AND. LSYM) THEN
    CALL FILL_HYBRID(S%FA(JMLOC)%YHYBRID_DIRECT_S,JMLOC,PLAN,&
      & IPOS,IPIVOT_POS,I0,IFN,IDENSE,IFW,IRO,IRE,LDIRECT)
  ELSEIF (LDIRECT) THEN
    CALL FILL_HYBRID(S%FA(JMLOC)%YHYBRID_DIRECT_A,JMLOC,PLAN,&
      & IPOS,IPIVOT_POS,I0,IFN,IDENSE,IFW,IRO,IRE,LDIRECT)
  ELSEIF (LSYM) THEN
    CALL FILL_HYBRID(S%FA(JMLOC)%YHYBRID_S,JMLOC,PLAN,IPOS,IPIVOT_POS,I0,IFN,&
      & IDENSE,IFW,IRO,IRE,LDIRECT)
  ELSE
    CALL FILL_HYBRID(S%FA(JMLOC)%YHYBRID_A,JMLOC,PLAN,IPOS,IPIVOT_POS,I0,IFN,&
      & IDENSE,IFW,IRO,IRE,LDIRECT)
  ENDIF
ENDDO
DEALLOCATE(IFW,IRO,IRE)
IF (PLAN%COMPACT_ID) CALL BUILD_COMPACT_GROUPS(PLAN)
IF (PLAN%FUSE_FINAL) CALL BUILD_FUSED_FINAL(PLAN,IPOS)

#ifdef ACCGPU
!$ACC ENTER DATA COPYIN(PLAN%FACTORS)
IF (ALLOCATED(PLAN%PIVOTS)) THEN
!$ACC ENTER DATA COPYIN(PLAN%PIVOTS)
ENDIF
IF (ALLOCATED(PLAN%FINAL_GATHER_SRC)) THEN
!$ACC ENTER DATA COPYIN(PLAN%FINAL_GATHER_SRC,PLAN%FINAL_GATHER_DST)
ENDIF
#endif
#ifdef OMPGPU
!$OMP TARGET ENTER DATA MAP(TO:PLAN%FACTORS)
IF (ALLOCATED(PLAN%PIVOTS)) THEN
!$OMP TARGET ENTER DATA MAP(TO:PLAN%PIVOTS)
ENDIF
IF (ALLOCATED(PLAN%FINAL_GATHER_SRC)) THEN
!$OMP TARGET ENTER DATA MAP(TO:PLAN%FINAL_GATHER_SRC,PLAN%FINAL_GATHER_DST)
ENDIF
#endif
END SUBROUTINE BUILD_ONE_PLAN

SUBROUTINE SCAN_HYBRID(HYBRID,PLAN,KMLOC)
TYPE(HYBRID_MATRIX),INTENT(IN) :: HYBRID
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIM),INTENT(IN) :: KMLOC
INTEGER(KIND=JPIM) :: JB

IF (HYBRID%CONSTRUCTED) PLAN%CANDIDATE_COUNT=PLAN%CANDIDATE_COUNT+1
PLAN%USE_HYBRID(KMLOC)=HYBRID%SELECTED
IF (.NOT.HYBRID%SELECTED) RETURN
PLAN%SELECTED_COUNT=PLAN%SELECTED_COUNT+1
PLAN%DENSE_BLOCKS=PLAN%DENSE_BLOCKS+HYBRID%DENSE_BLOCKS
PLAN%LOW_RANK_BLOCKS=PLAN%LOW_RANK_BLOCKS+HYBRID%LOW_RANK_BLOCKS
PLAN%BUTTERFLY_BLOCKS=PLAN%BUTTERFLY_BLOCKS+HYBRID%BUTTERFLY_BLOCKS
PLAN%DENSE_COST=PLAN%DENSE_COST+HYBRID%DENSE_COST
PLAN%HYBRID_COST=PLAN%HYBRID_COST+HYBRID%HYBRID_COST
DO JB=1,HYBRID%BLOCK_COUNT
  IF (HYBRID%BLOCKS(JB)%KIND /= HYBRID_DENSE) &
    PLAN%MAX_LEVELS=MAX(PLAN%MAX_LEVELS,HYBRID%BLOCKS(JB)%BUT%N_LEVELS)
ENDDO
END SUBROUTINE SCAN_HYBRID

SUBROUTINE KEEP_BEST_MATRIX(PLAN)
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIM) :: JBEST,JMLOC

JBEST=0
DO JMLOC=1,SIZE(PLAN%USE_HYBRID)
  IF (PLAN%USE_HYBRID(JMLOC)) THEN
    JBEST=JMLOC
    EXIT
  ENDIF
ENDDO
PLAN%USE_HYBRID=.FALSE.
IF (JBEST > 0) PLAN%USE_HYBRID(JBEST)=.TRUE.
END SUBROUTINE KEEP_BEST_MATRIX

SUBROUTINE ASSIGN_WORK(HYBRID,KPARITY,KBASE)
TYPE(HYBRID_MATRIX),INTENT(INOUT) :: HYBRID
INTEGER(KIND=JPIM),INTENT(IN) :: KPARITY
INTEGER(KIND=JPIB),INTENT(INOUT) :: KBASE
INTEGER(KIND=JPIM) :: JB

DO JB=1,HYBRID%BLOCK_COUNT
  IF (HYBRID%BLOCKS(JB)%KIND == HYBRID_DENSE) CYCLE
  IF (MOD(HYBRID%BLOCKS(JB)%BUT%N_LEVELS,2) /= KPARITY) CYCLE
  HYBRID%BLOCKS(JB)%WORK_BASE=KBASE
  KBASE=KBASE+HYBRID%BLOCKS(JB)%BUT%IBETALEN_MAX
ENDDO
END SUBROUTINE ASSIGN_WORK

SUBROUTINE COUNT_HYBRID(HYBRID,PLAN,KFACTORS,KPIVOTS)
TYPE(HYBRID_MATRIX),INTENT(IN) :: HYBRID
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIB),INTENT(INOUT) :: KFACTORS,KPIVOTS
INTEGER(KIND=JPIM) :: JB

DO JB=1,HYBRID%BLOCK_COUNT
  IF (HYBRID%BLOCKS(JB)%KIND == HYBRID_DENSE) THEN
    PLAN%DENSE%COUNT=PLAN%DENSE%COUNT+1
    KFACTORS=KFACTORS+HYBRID%BLOCKS(JB)%DENSE_COST
  ELSE
    CALL COUNT_MATRIX(HYBRID%BLOCKS(JB)%BUT,PLAN,KFACTORS,KPIVOTS)
  ENDIF
ENDDO
END SUBROUTINE COUNT_HYBRID

SUBROUTINE COUNT_MATRIX(BUT,PLAN,KFACTORS,KPIVOTS)
TYPE(BUTTERFLY_STRUCT),INTENT(IN) :: BUT
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIB),INTENT(INOUT) :: KFACTORS,KPIVOTS
INTEGER(KIND=JPIM) :: JL,JJ,JK,IRANKL,IRANKR
TYPE(NODE_TYPE),POINTER :: YNODE

DO JK=1,BUT%SLEV(0)%IK
  YNODE=>BUT%SLEV(0)%NODE(1,JK)
  PLAN%LEVEL0%COUNT=PLAN%LEVEL0%COUNT+1
  IF (PLAN%COMPACT_ID) THEN
    KFACTORS=KFACTORS+INT(YNODE%ICOLS-YNODE%IRANK,JPIB)*&
      & INT(YNODE%IRANK,JPIB)
    KPIVOTS=KPIVOTS+YNODE%ICOLS
  ELSE
    KFACTORS=KFACTORS+INT(YNODE%ICOLS,JPIB)*INT(YNODE%IRANK,JPIB)
  ENDIF
ENDDO
DO JL=1,BUT%N_LEVELS
  DO JK=1,BUT%SLEV(JL)%IK
    DO JJ=1,BUT%SLEV(JL)%IJ
      YNODE=>BUT%SLEV(JL)%NODE(JJ,JK)
      IRANKL=BUT%SLEV(JL-1)%NODE((JJ+1)/2,2*JK-1)%IRANK
      IRANKR=0
      IF (2*JK <= BUT%SLEV(JL-1)%IK) &
        IRANKR=BUT%SLEV(JL-1)%NODE((JJ+1)/2,2*JK)%IRANK
      PLAN%LEVEL(JL)%FWD%COUNT=PLAN%LEVEL(JL)%FWD%COUNT+1
      IF (MOD(JJ,2) == 1) THEN
        PLAN%LEVEL(JL)%REV_ODD%COUNT=PLAN%LEVEL(JL)%REV_ODD%COUNT+1
      ELSE
        PLAN%LEVEL(JL)%REV_EVEN%COUNT=PLAN%LEVEL(JL)%REV_EVEN%COUNT+1
      ENDIF
      IF (PLAN%COMPACT_ID) THEN
        KFACTORS=KFACTORS+INT(IRANKL+IRANKR-YNODE%IRANK,JPIB)*&
          & INT(YNODE%IRANK,JPIB)
        KPIVOTS=KPIVOTS+IRANKL+IRANKR
      ELSE
        KFACTORS=KFACTORS+INT(IRANKL+IRANKR,JPIB)*INT(YNODE%IRANK,JPIB)
      ENDIF
    ENDDO
  ENDDO
ENDDO
JL=BUT%N_LEVELS
DO JK=1,BUT%SLEV(JL)%IK
  DO JJ=1,BUT%SLEV(JL)%IJ
    YNODE=>BUT%SLEV(JL)%NODE(JJ,JK)
    PLAN%FINAL%COUNT=PLAN%FINAL%COUNT+1
    KFACTORS=KFACTORS+INT(YNODE%IROWS,JPIB)*INT(YNODE%IRANK,JPIB)
    PLAN%FINAL_FACTOR_VALUES=PLAN%FINAL_FACTOR_VALUES+&
      & INT(YNODE%IROWS,JPIB)*INT(YNODE%IRANK,JPIB)
  ENDDO
ENDDO
END SUBROUTINE COUNT_MATRIX

SUBROUTINE ALLOC_GROUP(GROUP)
TYPE(BUTTERFLY_GPU_GROUPS),INTENT(INOUT) :: GROUP
IF (GROUP%COUNT <= 0) RETURN
ALLOCATE(GROUP%N(GROUP%COUNT),GROUP%K(GROUP%COUNT),GROUP%LDB(GROUP%COUNT))
ALLOCATE(GROUP%SRC_COL(GROUP%COUNT),GROUP%DST_COL(GROUP%COUNT),&
  & GROUP%FACTOR_OFFSET(GROUP%COUNT),GROUP%PIVOT_OFFSET(GROUP%COUNT))
END SUBROUTINE ALLOC_GROUP

SUBROUTINE SET_GROUP(GROUP,KI,KN,KK,KLDB,KSRC,KDST,KFACTOR,KPIVOT)
TYPE(BUTTERFLY_GPU_GROUPS),INTENT(INOUT) :: GROUP
INTEGER(KIND=JPIM),INTENT(IN) :: KI,KN,KK,KLDB
INTEGER(KIND=JPIB),INTENT(IN) :: KSRC,KDST,KFACTOR
INTEGER(KIND=JPIB),INTENT(IN),OPTIONAL :: KPIVOT
GROUP%N(KI)=KN
GROUP%K(KI)=KK
GROUP%LDB(KI)=KLDB
GROUP%SRC_COL(KI)=KSRC
GROUP%DST_COL(KI)=KDST
GROUP%FACTOR_OFFSET(KI)=KFACTOR
GROUP%PIVOT_OFFSET(KI)=-1_JPIB
IF (PRESENT(KPIVOT)) GROUP%PIVOT_OFFSET(KI)=KPIVOT
END SUBROUTINE SET_GROUP

SUBROUTINE BUILD_COMPACT_GROUPS(PLAN)
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIM) :: JL

CALL BUILD_COMPACT_TILES(PLAN%LEVEL0,.FALSE.)
DO JL=1,PLAN%MAX_LEVELS
  CALL BUILD_COMPACT_TILES(PLAN%LEVEL(JL)%FWD,.FALSE.)
  CALL BUILD_COMPACT_TILES(PLAN%LEVEL(JL)%REV_ODD,.TRUE.)
  CALL BUILD_COMPACT_TILES(PLAN%LEVEL(JL)%REV_EVEN,.TRUE.)
ENDDO
END SUBROUTINE BUILD_COMPACT_GROUPS

SUBROUTINE BUILD_COMPACT_TILES(GROUP,LREVERSE)
TYPE(BUTTERFLY_GPU_GROUPS),INTENT(INOUT) :: GROUP
LOGICAL,INTENT(IN) :: LREVERSE
INTEGER(KIND=JPIM),PARAMETER :: IOUTPUTS=8
INTEGER(KIND=JPIM) :: IG,IT,ILIMIT,ISTART

IF (GROUP%COUNT <= 0) RETURN
GROUP%TILE_COUNT=0
DO IG=1,GROUP%COUNT
  ILIMIT=MERGE(GROUP%K(IG),GROUP%N(IG),LREVERSE)
  GROUP%TILE_COUNT=GROUP%TILE_COUNT+(ILIMIT+IOUTPUTS-1)/IOUTPUTS
ENDDO
ALLOCATE(GROUP%TILE_GROUP(GROUP%TILE_COUNT),&
  & GROUP%TILE_START(GROUP%TILE_COUNT))
IT=0
DO IG=1,GROUP%COUNT
  ILIMIT=MERGE(GROUP%K(IG),GROUP%N(IG),LREVERSE)
  DO ISTART=0,ILIMIT-1,IOUTPUTS
    IT=IT+1
    GROUP%TILE_GROUP(IT)=IG-1
    GROUP%TILE_START(IT)=ISTART
  ENDDO
ENDDO
CALL ENTER_COMPACT_GROUP_DEVICE(GROUP)
END SUBROUTINE BUILD_COMPACT_TILES

SUBROUTINE ENTER_COMPACT_GROUP_DEVICE(GROUP)
TYPE(BUTTERFLY_GPU_GROUPS),INTENT(IN) :: GROUP
ASSOCIATE(GN=>GROUP%N,GK=>GROUP%K,GS=>GROUP%SRC_COL,GD=>GROUP%DST_COL,&
  & GF=>GROUP%FACTOR_OFFSET,GP=>GROUP%PIVOT_OFFSET,&
  & GTG=>GROUP%TILE_GROUP,GTS=>GROUP%TILE_START)
#ifdef ACCGPU
!$ACC ENTER DATA COPYIN(GN,GK,GS,GD,GF,GP,GTG,GTS)
#endif
#ifdef OMPGPU
!$OMP TARGET ENTER DATA MAP(TO:GN,GK,GS,GD,GF,GP,GTG,GTS)
#endif
END ASSOCIATE
END SUBROUTINE ENTER_COMPACT_GROUP_DEVICE

SUBROUTINE BUILD_FUSED_FINAL(PLAN,KPOS)
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIB),INTENT(INOUT) :: KPOS

INTEGER(KIND=JPIM),ALLOCATABLE :: IORDER(:),ITEMP(:)
INTEGER(KIND=JPIM) :: IN,IWIDTH,ILEFT,IMID,IRIGHT,IOUT,I1,I2,I,ISTART,IEND
INTEGER(KIND=JPIM) :: IDX,IPREV,IGROUP,INOUT,IKTOTAL,JK
INTEGER(KIND=JPIB) :: ICOUNT,IGATHER,IPACK_COL,IGROUP_SRC,ISOURCE

IN=PLAN%FINAL%COUNT
IF (IN <= 0) RETURN
ALLOCATE(IORDER(IN),ITEMP(IN))
DO I=1,IN
  IORDER(I)=I
ENDDO

! Sort final factors by output range so equal destinations can share one GEMM.
IWIDTH=1
DO WHILE(IWIDTH < IN)
  DO ILEFT=1,IN,2*IWIDTH
    IMID=MIN(ILEFT+IWIDTH-1,IN)
    IRIGHT=MIN(ILEFT+2*IWIDTH-1,IN)
    I1=ILEFT
    I2=IMID+1
    DO IOUT=ILEFT,IRIGHT
      IF (I1 > IMID) THEN
        ITEMP(IOUT)=IORDER(I2)
        I2=I2+1
      ELSEIF (I2 > IRIGHT) THEN
        ITEMP(IOUT)=IORDER(I1)
        I1=I1+1
      ELSEIF (FINAL_GROUP_LESS(PLAN%FINAL,IORDER(I1),IORDER(I2))) THEN
        ITEMP(IOUT)=IORDER(I1)
        I1=I1+1
      ELSE
        ITEMP(IOUT)=IORDER(I2)
        I2=I2+1
      ENDIF
    ENDDO
  ENDDO
  IORDER=ITEMP
  IWIDTH=2*IWIDTH
ENDDO

IGROUP=1
IPREV=IORDER(1)
DO I=2,IN
  IDX=IORDER(I)
  IF (.NOT.FINAL_GROUP_SAME(PLAN%FINAL,IPREV,IDX)) IGROUP=IGROUP+1
  IPREV=IDX
ENDDO
PLAN%FINAL_FUSED%COUNT=IGROUP
PLAN%FINAL_ORIGINAL_COST=SUM(INT(PLAN%FINAL%N,JPIB)*INT(PLAN%FINAL%K,JPIB))
PLAN%FINAL_EXEC_COST=PLAN%FINAL_ORIGINAL_COST
PLAN%FINAL_DIRECT_GROUPS=IGROUP
IF (.NOT.PLAN%RECOMPRESS_FINAL .AND. IGROUP == IN) THEN
  PLAN%FUSE_FINAL=.FALSE.
  PLAN%FINAL_FUSED%COUNT=0
  DEALLOCATE(IORDER,ITEMP)
  RETURN
ENDIF
IF (PLAN%RECOMPRESS_FINAL) THEN
  CALL BUILD_RECOMPRESSED_FINAL(PLAN,KPOS,IORDER,IGROUP)
  DEALLOCATE(IORDER,ITEMP)
  RETURN
ENDIF
CALL ALLOC_GROUP(PLAN%FINAL_FUSED)
PLAN%FINAL_GATHER_COUNT=SUM(INT(PLAN%FINAL%K,JPIB))
ALLOCATE(PLAN%FINAL_GATHER_SRC(PLAN%FINAL_GATHER_COUNT),&
  & PLAN%FINAL_GATHER_DST(PLAN%FINAL_GATHER_COUNT))

I=1
IGROUP=0
IGATHER=0
IPACK_COL=0
DO WHILE(I <= IN)
  ISTART=I
  IDX=IORDER(I)
  INOUT=PLAN%FINAL%N(IDX)
  IKTOTAL=0
  DO WHILE(I <= IN)
    IF (.NOT.FINAL_GROUP_SAME(PLAN%FINAL,IORDER(ISTART),IORDER(I))) EXIT
    IKTOTAL=IKTOTAL+PLAN%FINAL%K(IORDER(I))
    I=I+1
  ENDDO
  IEND=I-1
  IGROUP=IGROUP+1
  IGROUP_SRC=IPACK_COL
  CALL SET_GROUP(PLAN%FINAL_FUSED,IGROUP,INOUT,IKTOTAL,INOUT,&
    & IGROUP_SRC,PLAN%FINAL%DST_COL(IDX),KPOS-1)
  DO IOUT=ISTART,IEND
    IDX=IORDER(IOUT)
    ICOUNT=INT(INOUT,JPIB)*INT(PLAN%FINAL%K(IDX),JPIB)
    ISOURCE=PLAN%FINAL%FACTOR_OFFSET(IDX)+1
    PLAN%FACTORS(KPOS:KPOS+ICOUNT-1)=&
      & PLAN%FACTORS(ISOURCE:ISOURCE+ICOUNT-1)
    KPOS=KPOS+ICOUNT
    DO JK=0,PLAN%FINAL%K(IDX)-1
      IGATHER=IGATHER+1
      PLAN%FINAL_GATHER_SRC(IGATHER)=PLAN%FINAL%SRC_COL(IDX)+JK
      PLAN%FINAL_GATHER_DST(IGATHER)=IPACK_COL
      IPACK_COL=IPACK_COL+1
    ENDDO
  ENDDO
ENDDO
DEALLOCATE(IORDER,ITEMP)
END SUBROUTINE BUILD_FUSED_FINAL

SUBROUTINE BUILD_RECOMPRESSED_FINAL(PLAN,KPOS,KORDER,KGROUPS)
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIB),INTENT(INOUT) :: KPOS
INTEGER(KIND=JPIM),INTENT(IN) :: KORDER(:),KGROUPS

INTEGER(KIND=JPIM) :: I,ISTART,IEND,IDX,INOUT,IKTOTAL,IRANK
INTEGER(KIND=JPIM) :: J,JK,JI,IC,IGROUP,IPROJECT,IBASIS,IDIRECT
INTEGER(KIND=JPIM),ALLOCATABLE :: ICLIST(:)
INTEGER(KIND=JPIB) :: IGATHER,IPACK_COL,IGAMMA_COL,ISOURCE,ICOUNT
INTEGER(KIND=JPIB) :: IORIGINAL_COST,IRECOMPRESSED_COST,IOFF
REAL(KIND=JPRD) :: ZEPS,ZSELECT_RATIO
REAL(KIND=JPRD),ALLOCATABLE :: ZB(:,:),ZPNONIM(:,:),ZPROJ(:,:)
LOGICAL :: LSELECT

PLAN%FINAL_FUSED%COUNT=KGROUPS
PLAN%FINAL_PROJECT%COUNT=KGROUPS
PLAN%FINAL_BASIS%COUNT=KGROUPS
CALL ALLOC_GROUP(PLAN%FINAL_FUSED)
CALL ALLOC_GROUP(PLAN%FINAL_PROJECT)
CALL ALLOC_GROUP(PLAN%FINAL_BASIS)
PLAN%FINAL_GATHER_COUNT=SUM(INT(PLAN%FINAL%K,JPIB))
ALLOCATE(PLAN%FINAL_GATHER_SRC(PLAN%FINAL_GATHER_COUNT),&
  & PLAN%FINAL_GATHER_DST(PLAN%FINAL_GATHER_COUNT))

ZEPS=BUTTERFLY_FINAL_EPS()
ZSELECT_RATIO=BUTTERFLY_FINAL_SELECT_RATIO()
I=1
IGROUP=0
IPROJECT=0
IBASIS=0
IDIRECT=0
IGATHER=0
IPACK_COL=0
IGAMMA_COL=0
PLAN%FINAL_EXEC_COST=0
PLAN%FINAL_RECOMPRESSED_GROUPS=0
PLAN%FINAL_DIRECT_GROUPS=0
DO WHILE(I <= SIZE(KORDER))
  ISTART=I
  IDX=KORDER(I)
  INOUT=PLAN%FINAL%N(IDX)
  IKTOTAL=0
  DO WHILE(I <= SIZE(KORDER))
    IF (.NOT.FINAL_GROUP_SAME(PLAN%FINAL,KORDER(ISTART),KORDER(I))) EXIT
    IKTOTAL=IKTOTAL+PLAN%FINAL%K(KORDER(I))
    I=I+1
  ENDDO
  IEND=I-1
  IGROUP=IGROUP+1
  ALLOCATE(ZB(INOUT,IKTOTAL),ICLIST(IKTOTAL),&
    & ZPNONIM(MAX(1,MIN(INOUT,IKTOTAL)),MAX(1,IKTOTAL)))
  J=0
  DO JI=ISTART,IEND
    IDX=KORDER(JI)
    ISOURCE=PLAN%FINAL%FACTOR_OFFSET(IDX)+1
    DO JK=1,PLAN%FINAL%K(IDX)
      J=J+1
      ZB(:,J)=REAL(PLAN%FACTORS(ISOURCE+(JK-1)*INOUT:&
        & ISOURCE+JK*INOUT-1),JPRD)
      IGATHER=IGATHER+1
      PLAN%FINAL_GATHER_SRC(IGATHER)=PLAN%FINAL%SRC_COL(IDX)+JK-1
      PLAN%FINAL_GATHER_DST(IGATHER)=IPACK_COL
      IPACK_COL=IPACK_COL+1
    ENDDO
  ENDDO

  CALL COMPUTE_ID(ZEPS,INOUT,IKTOTAL,ZB,IRANK,ICLIST,ZPNONIM)
  IORIGINAL_COST=INT(INOUT,JPIB)*INT(IKTOTAL,JPIB)
  IRECOMPRESSED_COST=INT(IRANK,JPIB)*INT(INOUT+IKTOTAL,JPIB)
  LSELECT=IRANK < MIN(INOUT,IKTOTAL) .AND. &
    & REAL(IRECOMPRESSED_COST,JPRD) < ZSELECT_RATIO*REAL(IORIGINAL_COST,JPRD)
  IF (LSELECT) THEN
    ALLOCATE(ZPROJ(IKTOTAL,IRANK))
    ZPROJ=0.0_JPRD
    DO JI=1,IKTOTAL
      IC=ICLIST(JI)
      IF (JI <= IRANK) THEN
        ZPROJ(IC,JI)=1.0_JPRD
      ELSE
        ZPROJ(IC,1:IRANK)=ZPNONIM(1:IRANK,JI-IRANK)
      ENDIF
    ENDDO
    IOFF=KPOS-1
    ICOUNT=INT(IKTOTAL,JPIB)*INT(IRANK,JPIB)
    PLAN%FACTORS(KPOS:KPOS+ICOUNT-1)=&
      & RESHAPE(REAL(ZPROJ,JPRBT),[ICOUNT])
    KPOS=KPOS+ICOUNT
    IPROJECT=IPROJECT+1
    CALL SET_GROUP(PLAN%FINAL_PROJECT,IPROJECT,IRANK,IKTOTAL,IKTOTAL,&
      & IPACK_COL-IKTOTAL,IGAMMA_COL,IOFF)

    IOFF=KPOS-1
    ICOUNT=INT(INOUT,JPIB)*INT(IRANK,JPIB)
    PLAN%FACTORS(KPOS:KPOS+ICOUNT-1)=&
      & RESHAPE(REAL(ZB(:,ICLIST(1:IRANK)),JPRBT),[ICOUNT])
    KPOS=KPOS+ICOUNT
    IBASIS=IBASIS+1
    CALL SET_GROUP(PLAN%FINAL_BASIS,IBASIS,INOUT,IRANK,INOUT,&
      & IGAMMA_COL,PLAN%FINAL%DST_COL(IDX),IOFF)
    IGAMMA_COL=IGAMMA_COL+IRANK
    PLAN%FINAL_EXEC_COST=PLAN%FINAL_EXEC_COST+IRECOMPRESSED_COST
    PLAN%FINAL_RECOMPRESSED_GROUPS=PLAN%FINAL_RECOMPRESSED_GROUPS+1
    DEALLOCATE(ZPROJ)
  ELSE
    IOFF=KPOS-1
    PLAN%FACTORS(KPOS:KPOS+IORIGINAL_COST-1)=&
      & RESHAPE(REAL(ZB,JPRBT),[IORIGINAL_COST])
    KPOS=KPOS+IORIGINAL_COST
    IDIRECT=IDIRECT+1
    CALL SET_GROUP(PLAN%FINAL_FUSED,IDIRECT,INOUT,IKTOTAL,INOUT,&
      & IPACK_COL-IKTOTAL,PLAN%FINAL%DST_COL(IDX),IOFF)
    PLAN%FINAL_EXEC_COST=PLAN%FINAL_EXEC_COST+IORIGINAL_COST
    PLAN%FINAL_DIRECT_GROUPS=PLAN%FINAL_DIRECT_GROUPS+1
  ENDIF
  DEALLOCATE(ZB,ICLIST,ZPNONIM)
ENDDO
PLAN%FINAL_PROJECT%COUNT=IPROJECT
PLAN%FINAL_BASIS%COUNT=IBASIS
PLAN%FINAL_FUSED%COUNT=IDIRECT
IF (IPROJECT == 0 .AND. IDIRECT == PLAN%FINAL%COUNT) THEN
  PLAN%FUSE_FINAL=.FALSE.
  PLAN%RECOMPRESS_FINAL=.FALSE.
ENDIF
END SUBROUTINE BUILD_RECOMPRESSED_FINAL

LOGICAL FUNCTION FINAL_GROUP_LESS(GROUP,KI,KJ)
TYPE(BUTTERFLY_GPU_GROUPS),INTENT(IN) :: GROUP
INTEGER(KIND=JPIM),INTENT(IN) :: KI,KJ
FINAL_GROUP_LESS=GROUP%DST_COL(KI) < GROUP%DST_COL(KJ) .OR. &
  & (GROUP%DST_COL(KI) == GROUP%DST_COL(KJ) .AND. &
  & GROUP%N(KI) <= GROUP%N(KJ))
END FUNCTION FINAL_GROUP_LESS

LOGICAL FUNCTION FINAL_GROUP_SAME(GROUP,KI,KJ)
TYPE(BUTTERFLY_GPU_GROUPS),INTENT(IN) :: GROUP
INTEGER(KIND=JPIM),INTENT(IN) :: KI,KJ
FINAL_GROUP_SAME=GROUP%DST_COL(KI) == GROUP%DST_COL(KJ) .AND. &
  & GROUP%N(KI) == GROUP%N(KJ)
END FUNCTION FINAL_GROUP_SAME

SUBROUTINE FILL_HYBRID(HYBRID,KMLOC,PLAN,KPOS,KPIVOT_POS,K0,KFINAL,KDENSE,KFW,KRO,KRE,&
  & LTRANSPOSED)
TYPE(HYBRID_MATRIX),INTENT(IN) :: HYBRID
INTEGER(KIND=JPIM),INTENT(IN) :: KMLOC
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIB),INTENT(INOUT) :: KPOS,KPIVOT_POS
INTEGER(KIND=JPIM),INTENT(INOUT) :: K0,KFINAL,KDENSE,KFW(:),KRO(:),KRE(:)
LOGICAL,INTENT(IN) :: LTRANSPOSED
INTEGER(KIND=JPIM) :: JB

DO JB=1,HYBRID%BLOCK_COUNT
  IF (HYBRID%BLOCKS(JB)%KIND == HYBRID_DENSE) THEN
    CALL FILL_DENSE(HYBRID%BLOCKS(JB),KMLOC,PLAN,KPOS,KDENSE,LTRANSPOSED)
  ELSE
    CALL FILL_MATRIX(HYBRID%BLOCKS(JB)%BUT,KMLOC,&
      & HYBRID%BLOCKS(JB)%FIRST_ROW,HYBRID%BLOCKS(JB)%FIRST_COL,&
      & HYBRID%BLOCKS(JB)%WORK_BASE,PLAN,KPOS,KPIVOT_POS,K0,KFINAL,KFW,KRO,KRE,&
      & LTRANSPOSED)
  ENDIF
ENDDO
END SUBROUTINE FILL_HYBRID

SUBROUTINE FILL_DENSE(BLOCK,KMLOC,PLAN,KPOS,KDENSE,LTRANSPOSED)
USE TPM_DISTR, ONLY: D
TYPE(HYBRID_BLOCK),INTENT(IN) :: BLOCK
INTEGER(KIND=JPIM),INTENT(IN) :: KMLOC
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIB),INTENT(INOUT) :: KPOS
INTEGER(KIND=JPIM),INTENT(INOUT) :: KDENSE
LOGICAL,INTENT(IN) :: LTRANSPOSED
INTEGER(KIND=JPIB) :: IOFF
REAL(KIND=JPRBT),ALLOCATABLE :: ZT(:,:)

ALLOCATE(ZT(BLOCK%NCOLS,BLOCK%NROWS))
ZT=TRANSPOSE(BLOCK%DENSE)
IOFF=KPOS-1
PLAN%FACTORS(KPOS:KPOS+BLOCK%DENSE_COST-1)=RESHAPE(ZT,[BLOCK%DENSE_COST])
KPOS=KPOS+BLOCK%DENSE_COST
KDENSE=KDENSE+1
IF (LTRANSPOSED) THEN
  CALL SET_GROUP(PLAN%DENSE,KDENSE,BLOCK%NROWS,BLOCK%NCOLS,BLOCK%NCOLS,&
    & D%OFFSETS_GEMM1(KMLOC)+BLOCK%FIRST_COL-1,&
    & D%OFFSETS_GEMM2(KMLOC)+BLOCK%FIRST_ROW-1,IOFF)
ELSE
  CALL SET_GROUP(PLAN%DENSE,KDENSE,BLOCK%NROWS,BLOCK%NCOLS,BLOCK%NCOLS,&
    & D%OFFSETS_GEMM2(KMLOC)+BLOCK%FIRST_COL-1,&
    & D%OFFSETS_GEMM1(KMLOC)+BLOCK%FIRST_ROW-1,IOFF)
ENDIF
DEALLOCATE(ZT)
END SUBROUTINE FILL_DENSE

SUBROUTINE FILL_MATRIX(BUT,KMLOC,KFIRST_ROW,KFIRST_COL,KWORK_BASE,&
  & PLAN,KPOS,KPIVOT_POS,K0,KFINAL,KFW,KRO,KRE,LTRANSPOSED)
USE TPM_DISTR, ONLY: D
TYPE(BUTTERFLY_STRUCT),INTENT(IN) :: BUT
INTEGER(KIND=JPIM),INTENT(IN) :: KMLOC,KFIRST_ROW,KFIRST_COL
INTEGER(KIND=JPIB),INTENT(IN) :: KWORK_BASE
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIB),INTENT(INOUT) :: KPOS,KPIVOT_POS
INTEGER(KIND=JPIM),INTENT(INOUT) :: K0,KFINAL,KFW(:),KRO(:),KRE(:)
LOGICAL,INTENT(IN) :: LTRANSPOSED
INTEGER(KIND=JPIM) :: JL,JJ,JK,IRANKL,IRANKR
INTEGER(KIND=JPIB) :: IOFF,IPIVOT_OFF,ISRC,IDST
TYPE(NODE_TYPE),POINTER :: YNODE,YLEFT,YRIGHT

DO JK=1,BUT%SLEV(0)%IK
  YNODE=>BUT%SLEV(0)%NODE(1,JK)
  CALL PACK_PLAN_PROJECTION(YNODE,PLAN,KPOS,KPIVOT_POS,IOFF,IPIVOT_OFF)
  K0=K0+1
  IF (LTRANSPOSED) THEN
    ISRC=D%OFFSETS_GEMM1(KMLOC)+KFIRST_COL+YNODE%IFCOL-2
  ELSE
    ISRC=D%OFFSETS_GEMM2(KMLOC)+KFIRST_COL+YNODE%IFCOL-2
  ENDIF
  IDST=KWORK_BASE+YNODE%IOFFBETA
  CALL SET_GROUP(PLAN%LEVEL0,K0,YNODE%IRANK,YNODE%ICOLS,YNODE%ICOLS,&
    & ISRC,IDST,IOFF,IPIVOT_OFF)
ENDDO

DO JL=1,BUT%N_LEVELS
  DO JK=1,BUT%SLEV(JL)%IK
    DO JJ=1,BUT%SLEV(JL)%IJ
      YNODE=>BUT%SLEV(JL)%NODE(JJ,JK)
      YLEFT=>BUT%SLEV(JL-1)%NODE((JJ+1)/2,2*JK-1)
      IRANKL=YLEFT%IRANK
      IRANKR=0
      IF (2*JK <= BUT%SLEV(JL-1)%IK) THEN
        YRIGHT=>BUT%SLEV(JL-1)%NODE((JJ+1)/2,2*JK)
        IRANKR=YRIGHT%IRANK
      ENDIF
      CALL PACK_PLAN_PROJECTION(YNODE,PLAN,KPOS,KPIVOT_POS,IOFF,IPIVOT_OFF)
      ISRC=KWORK_BASE+YLEFT%IOFFBETA
      IDST=KWORK_BASE+YNODE%IOFFBETA
      KFW(JL)=KFW(JL)+1
      CALL SET_GROUP(PLAN%LEVEL(JL)%FWD,KFW(JL),YNODE%IRANK,IRANKL+IRANKR,&
        & IRANKL+IRANKR,ISRC,IDST,IOFF,IPIVOT_OFF)
      IF (MOD(JJ,2) == 1) THEN
        KRO(JL)=KRO(JL)+1
        CALL SET_GROUP(PLAN%LEVEL(JL)%REV_ODD,KRO(JL),YNODE%IRANK,&
          & IRANKL+IRANKR,IRANKL+IRANKR,ISRC,IDST,IOFF,IPIVOT_OFF)
      ELSE
        KRE(JL)=KRE(JL)+1
        CALL SET_GROUP(PLAN%LEVEL(JL)%REV_EVEN,KRE(JL),YNODE%IRANK,&
          & IRANKL+IRANKR,IRANKL+IRANKR,ISRC,IDST,IOFF,IPIVOT_OFF)
      ENDIF
    ENDDO
  ENDDO
ENDDO

JL=BUT%N_LEVELS
DO JK=1,BUT%SLEV(JL)%IK
  DO JJ=1,BUT%SLEV(JL)%IJ
    YNODE=>BUT%SLEV(JL)%NODE(JJ,JK)
    IOFF=KPOS-1
    PLAN%FACTORS(KPOS:KPOS+INT(YNODE%IROWS,JPIB)*YNODE%IRANK-1)=&
      & RESHAPE(REAL(YNODE%B,JPRBT),[YNODE%IROWS*YNODE%IRANK])
    KPOS=KPOS+INT(YNODE%IROWS,JPIB)*YNODE%IRANK
    KFINAL=KFINAL+1
    IF (LTRANSPOSED) THEN
      CALL SET_GROUP(PLAN%FINAL,KFINAL,YNODE%IROWS,YNODE%IRANK,YNODE%IROWS,&
        & KWORK_BASE+YNODE%IOFFBETA,&
        & D%OFFSETS_GEMM2(KMLOC)+KFIRST_ROW+YNODE%IFROW-2,IOFF)
    ELSE
      CALL SET_GROUP(PLAN%FINAL,KFINAL,YNODE%IROWS,YNODE%IRANK,YNODE%IROWS,&
        & KWORK_BASE+YNODE%IOFFBETA,&
        & D%OFFSETS_GEMM1(KMLOC)+KFIRST_ROW+YNODE%IFROW-2,IOFF)
    ENDIF
  ENDDO
ENDDO
END SUBROUTINE FILL_MATRIX

SUBROUTINE PACK_PLAN_PROJECTION(NODE,PLAN,KPOS,KPIVOT_POS,KOFFSET,KPIVOT_OFFSET)
TYPE(NODE_TYPE),INTENT(IN) :: NODE
TYPE(BUTTERFLY_GPU_PLAN),INTENT(INOUT) :: PLAN
INTEGER(KIND=JPIB),INTENT(INOUT) :: KPOS,KPIVOT_POS
INTEGER(KIND=JPIB),INTENT(OUT) :: KOFFSET,KPIVOT_OFFSET
INTEGER(KIND=JPIB) :: ICOUNT

IF (.NOT.PLAN%COMPACT_ID) THEN
  CALL PACK_PROJECTION(NODE,PLAN%FACTORS,KPOS,KOFFSET)
  KPIVOT_OFFSET=-1_JPIB
  RETURN
ENDIF

KOFFSET=KPOS-1
ICOUNT=INT(NODE%IRANK,JPIB)*INT(NODE%ICOLS-NODE%IRANK,JPIB)
IF (ICOUNT > 0) THEN
  PLAN%FACTORS(KPOS:KPOS+ICOUNT-1)=NODE%PNONIM(1:ICOUNT)
  KPOS=KPOS+ICOUNT
ENDIF
KPIVOT_OFFSET=KPIVOT_POS-1
PLAN%PIVOTS(KPIVOT_POS:KPIVOT_POS+NODE%ICOLS-1)=NODE%ICLIST-1
KPIVOT_POS=KPIVOT_POS+NODE%ICOLS
END SUBROUTINE PACK_PLAN_PROJECTION

SUBROUTINE PACK_PROJECTION(NODE,PFACTORS,KPOS,KOFFSET)
TYPE(NODE_TYPE),INTENT(IN) :: NODE
REAL(KIND=JPRBT),INTENT(INOUT) :: PFACTORS(:)
INTEGER(KIND=JPIB),INTENT(INOUT) :: KPOS
INTEGER(KIND=JPIB),INTENT(OUT) :: KOFFSET
REAL(KIND=JPRBT),ALLOCATABLE :: ZT(:,:)
INTEGER(KIND=JPIM) :: JI,JR,IC

ALLOCATE(ZT(NODE%ICOLS,NODE%IRANK))
ZT=ZERO
DO JI=1,NODE%ICOLS
  IC=NODE%ICLIST(JI)
  IF (JI <= NODE%IRANK) THEN
    ZT(IC,JI)=ONE
  ELSE
    DO JR=1,NODE%IRANK
      ZT(IC,JR)=NODE%PNONIM((JI-NODE%IRANK-1)*NODE%IRANK+JR)
    ENDDO
  ENDIF
ENDDO
KOFFSET=KPOS-1
PFACTORS(KPOS:KPOS+INT(NODE%ICOLS,JPIB)*NODE%IRANK-1)=&
  & RESHAPE(ZT,[NODE%ICOLS*NODE%IRANK])
KPOS=KPOS+INT(NODE%ICOLS,JPIB)*NODE%IRANK
DEALLOCATE(ZT)
END SUBROUTINE PACK_PROJECTION

